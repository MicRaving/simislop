        [Fact]
        public void ApplyBudgetTakesTheTailOfAnOrderedListAndSaysWhatItCut()
        {
            //<see cref="SimitoneSurroundingsPlan.ApplyBudget"/> and
            //<see cref="SimitoneSurroundingsPlan.OrderNearestFirst"/> on their own, over a
            //candidate list the test builds itself, because they are the two functions the plan
            //calls and a plan-shaped fixture cannot show what they do to a list that was already
            //in an odd order. Shuffled input in particular: the budget must not be a function of
            //the order the reachability flood-fill happened to reach the lots in.
            var world = World();
            var active = world.Lots[0].Number;
            var plan = PlanWithNoContents(world, active);
            var full = new List<SimitoneSurroundingsNeighbour>(plan.Neighbours);
            Assert.True(full.Count >= 3, "the fixture needs three neighbours: " + plan.Describe());

            //--- the cut, from an order that is not nearest-first -----------------------------------
            var shuffled = new List<SimitoneSurroundingsNeighbour>(full);
            shuffled.Reverse();
            var ordered = new List<SimitoneSurroundingsNeighbour>(shuffled);
            SimitoneSurroundingsPlan.OrderNearestFirst(plan.ActiveLot, ordered);

            var gaps = new List<int>();
            foreach (var neighbour in ordered)
            {
                gaps.Add(SimitoneSurroundingsPlan.SubWorldGapFor(plan.ActiveLot, neighbour.Lot));
            }
            AssertNearestFirst(gaps, NumbersOf(ordered), "the ordered list");
            Assert.Equal(plan.SelectionOrder, NumbersOf(ordered));
            Assert.NotEqual(NumbersOf(shuffled), NumbersOf(ordered));

            //Two kept out of three, and the deferred list is the tail in the same order.
            var candidates = new List<SimitoneSurroundingsNeighbour>(ordered);
            var deferred = new List<SimitoneSurroundingsNeighbour>();
            var cut = SimitoneSurroundingsPlan.ApplyBudget(candidates, 2, deferred);
            Assert.Equal(full.Count - 2, cut);
            Assert.Equal(2, candidates.Count);
            Assert.Single(deferred);
            Assert.Equal(ordered[2].Lot.Number, deferred[0].Lot.Number);
            //The list really was truncated in place rather than copied, which is what makes the
            //plan's "the order the budget was applied in" record meaningful.
            Assert.Equal(2, candidates.Count);

            //--- a budget that does not bind -------------------------------------------------------
            var all = new List<SimitoneSurroundingsNeighbour>(ordered);
            var none = new List<SimitoneSurroundingsNeighbour>();
            Assert.Equal(0, SimitoneSurroundingsPlan.ApplyBudget(all, full.Count, none));
            Assert.Equal(full.Count, all.Count);
            Assert.Empty(none);
            //A budget above the count takes everything and says nothing was cut.
            Assert.Equal(0, SimitoneSurroundingsPlan.ApplyBudget(all, full.Count + 100, none));
            Assert.Equal(full.Count, all.Count);

            //--- and a null list, a null deferred, and a zero budget ---------------------------------
            Assert.Equal(0, SimitoneSurroundingsPlan.ApplyBudget(null, 4, null));
            var emptied = new List<SimitoneSurroundingsNeighbour>(ordered);
            var emptiedDeferred = new List<SimitoneSurroundingsNeighbour>(ordered);
            Assert.Equal(full.Count, SimitoneSurroundingsPlan.ApplyBudget(emptied, 0, emptiedDeferred));
            Assert.Empty(emptied);
            Assert.Equal(full.Count, emptiedDeferred.Count);
            //A null deferred is a caller that does not want the record, not a crash.
            var quiet = new List<SimitoneSurroundingsNeighbour>(ordered);
            Assert.Equal(full.Count, SimitoneSurroundingsPlan.ApplyBudget(quiet, 0, null));
            Assert.Empty(quiet);
            //A negative budget is zero, and a null or single-element list is already ordered.
            var negative = new List<SimitoneSurroundingsNeighbour>(ordered);
            Assert.Equal(full.Count, SimitoneSurroundingsPlan.ApplyBudget(negative, -1, null));
            Assert.Empty(negative);
            SimitoneSurroundingsPlan.OrderNearestFirst(plan.ActiveLot, null);
            var single = new List<SimitoneSurroundingsNeighbour> { ordered[0] };
            SimitoneSurroundingsPlan.OrderNearestFirst(plan.ActiveLot, single);
            Assert.Single(single);
        }

