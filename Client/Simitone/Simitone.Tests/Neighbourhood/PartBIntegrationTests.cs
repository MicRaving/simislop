        /// <summary>
        /// The same plan at a stated radius, which the Wave 9 tests need because they are about
        /// what the *shipped* radius produces rather than about this fixture's wide one.
        /// </summary>
        private static SimitoneSurroundingsPlan PlanFor(
            SimitoneNeighbourhoodWorld world, int lotNumber, int radius)
        {
            SimitoneSurroundingsPlacement placement;
            string reason;
            Assert.True(SimitoneSurroundingsPlacement.TryFor(
                world.Layout, world.Map, lotNumber, out placement, out reason), reason);

            //the query is rasterised once when the world is built, not once per lot switch
