        /// <summary>
        /// The screen, as the switch sees it: it holds the current lot, and everything else it is
        /// asked for comes from the world the switch is about to move.
        ///
        /// <para>
        /// A fake of the real <see cref="ILotTravelHost"/> rather than a dictionary, so the ordering
        /// the service guarantees is asserted against the same six calls a screen implements - and
        /// the store and transit table behind two of those members are the world's own, which is
        /// what makes this an integration rather than a restatement of
        /// <c>LotTravelServiceTests</c>.
        /// </para>
        /// </summary>
        private sealed class WorldBackedTravelHost : ILotTravelHost
        {
            public readonly List<string> Calls = new List<string>();

            public readonly SimitoneNeighbourhoodWorld World;

            public int CurrentHouseId { get; set; }

            public int? ActiveFamilyHouseNumber { get; set; }

            public VMMarshal LastLoadedMarshal { get; private set; }

            public string LastLoadedPath { get; private set; }

            public WorldBackedTravelHost(SimitoneNeighbourhoodWorld world, int currentHouseId)
            {
                World = world;
                CurrentHouseId = currentHouseId;
                ActiveFamilyHouseNumber = currentHouseId;
            }

            public string GetHousePath(int houseId)
            {
                Calls.Add("getpath:" + houseId);
                return "UserData/Neighbourhoods/Houses/House" + houseId + ".iff";
            }

            public VMMarshal SaveCurrentLot()
            {
                Calls.Add("save:" + CurrentHouseId);
                //the live lot's real state, stashed under its own number - the store's keying, and
                //§11 item 4's rule restated once
                var marshal = World.ActiveMarshal ?? new VMMarshal();
                World.LotStore.SetActive((short)CurrentHouseId, marshal);
                return marshal;
            }

            public bool TryRestoreSaved(short lot, out VMMarshal marshal)
            {
                Calls.Add("restore:" + lot);
                return World.LotStore.TryGetActive(lot, out marshal);
            }

            public void RemoveSaved(short lot)
            {
                Calls.Add("remove:" + lot);
                World.LotStore.Remove(lot);
            }

            public void SetDowntown(bool downtown)
            {
                Calls.Add("downtown:" + (downtown ? "on" : "off"));
            }

            public void LoadLot(string path, int houseId)
            {
                Calls.Add("load-file:" + houseId);
                LastLoadedPath = path;
                LastLoadedMarshal = null;
                CurrentHouseId = houseId;
                //The world's one switch path: it stashes the lot being left and takes the one
                //arriving out of the store. A lot read from its file has live state from that moment
                //on, so the world is handed a freshly marshalled one rather than nothing - which is
                //what makes the next departure out of this lot stash something.
                World.SetActiveLotWith(houseId, new VMMarshal());
            }

            public void LoadLot(VMMarshal marshal, int houseId)
            {
                Calls.Add("load-state:" + houseId);
                LastLoadedMarshal = marshal;
                LastLoadedPath = null;
                CurrentHouseId = houseId;
                World.SetActiveLotWith(houseId, marshal);
            }

            public Action<NeighbourhoodTransitRecord> RecordTransit
            {
                get
                {
                    return record =>
                    {
                        Calls.Add("hop:" + record.Origin + "->" + record.Destination);
                        World.Transit.Add(record);
                    };
                }
            }
        }

