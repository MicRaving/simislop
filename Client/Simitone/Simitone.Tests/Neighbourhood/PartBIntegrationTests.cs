        /// <summary>
        /// The body of the member whose declaration starts with <paramref name="signature"/>,
        /// found by counting braces rather than by looking for a closing one at a fixed indent.
        /// A depth counter is the only version of this that survives an edit which changes a
        /// method's nesting, and a source assertion that breaks when somebody reformats is an
        /// assertion nobody keeps.
        /// </summary>
        private static string MethodBody(string source, string signature)
        {
            var start = source.IndexOf(signature, StringComparison.Ordinal);
            Assert.True(start > 0, "no member starting with: " + signature);
            var open = source.IndexOf('{', start);
            Assert.True(open > 0, "no body for: " + signature);
            var depth = 0;
            for (var i = open; i < source.Length; i++)
            {
                if (source[i] == '{') depth++;
                else if (source[i] == '}')
                {
                    depth--;
                    if (depth == 0) return source.Substring(open, i - open + 1);
                }
            }
            Assert.Fail("unterminated body for: " + signature);
            return null;
        }

        private static bool Contains(IReadOnlyList<int> numbers, int number)
        {
            for (int i = 0; i < numbers.Count; i++)
            {
                if (numbers[i] == number) return true;
            }
            return false;
        }

        private static int IndexOf(IList<string> calls, string call)
        {
            return calls.IndexOf(call);
        }

        private static int CountOf(IList<string> calls, string call)
        {
            var count = 0;
            for (int i = 0; i < calls.Count; i++)
            {
                if (calls[i] == call) count++;
            }
            return count;
        }

        // ================================================== layout + map -> query -> plan (B2)

        [Fact]
        public void EveryLotOfAGeneratedNeighbourhoodPlansRealNeighboursWithUsableTerrain()
        {
            //The whole of Part A's spatial substrate answering Part B's first question, end to end
            //and with no engine: the generator's streets, the adapter's layout, the query the world
            //builds once, and the plan that decides which of those lots become real sub-worlds.
            //
            //Every lot is walked rather than one, because "this neighbourhood has a neighbour" and
            //"every house in it has neighbours" are different claims, and only the second is what a
            //player standing in a corner lot would notice.
            var world = World();

            //not vacuous: a fixture whose lots could not reach each other would satisfy the per-lot
            //assertions below for the wrong reason
            Assert.True(world.Query.RoadComponentCount >= 1);
            Assert.Equal(4, world.Lots.Count);

            var planned = 0;
            for (int i = 0; i < world.Lots.Count; i++)
            {
                var lot = world.Lots[i];
                var reachable = world.Query.NeighboursOf(lot.Number);
                Assert.NotEmpty(reachable);
                planned++;

                var plan = PlanFor(world, lot.Number);

                Assert.True(plan.IsValid, plan.Failure);
                Assert.Null(plan.Failure);
                Assert.True(plan.RoadReachability);
                Assert.Equal(lot.Number, plan.ActiveLot.Number);
                Assert.Equal(Radius, plan.RadiusTiles);
                Assert.True(plan.ActiveTerrain.IsValid);

                //more than zero neighbours, which is B2's acceptance line for the decision half
                Assert.NotEmpty(plan.Neighbours);
                Assert.Empty(plan.Warnings);
                Assert.False(plan.Contains(lot.Number));

                foreach (var neighbour in plan.Neighbours)
                {
                    var described = neighbour.Describe();
                    Assert.True(neighbour.IsValid, described);
                    Assert.True(neighbour.Terrain.IsValid, described);
                    Assert.True(neighbour.SubWorldSize >= SimitoneSurroundingsPlan.MinSubWorldSize, described);

                    //the plan may not select a lot the query cannot reach, or the bridge would stand
                    //a house in the middle of a field
                    Assert.True(Contains(reachable, neighbour.Lot.Number), described);
                    Assert.True(SimitoneSurroundingsPlan.WithinRadius(lot, neighbour.Lot, Radius), described);

                    //and it stands where the layout says, which is the number TSO's
                    //RestoreSurroundings gets wrong for a layout that is not a uniform grid
                    Assert.True(neighbour.Lot.WorldX - lot.WorldX == (int)neighbour.SubWorldPosition.X,
                        described);
                    Assert.True(neighbour.Lot.WorldY - lot.WorldY == (int)neighbour.SubWorldPosition.Y,
                        described);

                    //the terrain it is built out of is the lot's own ground, read off the generated
                    //elevation rather than guessed at
                    Assert.Equal(SimitoneNeighbourTerrain.GridSamples, neighbour.Terrain.Heights.Count);
                    Assert.InRange(neighbour.BaseLevel, 0, int.MaxValue);

                    //nothing has been stored for it yet, so every neighbour is built blank
                    Assert.False(neighbour.IsHollow, described);
                }

                //ascending lot number, whatever order reachability came in
                for (int n = 1; n < plan.Neighbours.Count; n++)
                {
                    Assert.True(plan.Neighbours[n - 1].Lot.Number < plan.Neighbours[n].Lot.Number);
                }
            }

            //every lot in this fixture has a door on a street, so every lot plans
            Assert.Equal(world.Lots.Count, planned);
        }

        [Fact]
        public void WhatTheLotStoreHoldsDecidesWhetherANeighbourIsBuiltFromItsContents()
        {
            //§5.3 across the seam: the world owns one store, the plan reads it, and a neighbour the
            //store holds a hollow marshal for is built from its contents while the rest are built
            //blank. Nothing about the map changes between the two plans, so the store really is the
            //only thing that decides this.
            var world = World();
            var active = world.Lots[0];
            var plan = PlanFor(world, active.Number);
            Assert.NotEmpty(plan.Neighbours);
            Assert.Equal(0, plan.HollowCount);

            //two of the reachable neighbours get stored contents, in the world's own store
            var hollowed = new List<short>();
            for (int i = 0; i < 2 && i < plan.Neighbours.Count; i++)
            {
                var number = plan.Neighbours[i].Lot.Number;
                world.LotStore.SetHollow(number, new VMHollowMarshal());
                hollowed.Add(number);
                Assert.Equal(NeighbourhoodLotState.Hollow, world.LotStore.StateOf(number));
            }

            var restocked = PlanFor(world, active.Number);

            //the same lots, chosen the same way
            Assert.Equal(plan.NeighbourNumbers, restocked.NeighbourNumbers);
            Assert.Equal(hollowed.Count, restocked.HollowCount);
            foreach (var number in hollowed)
            {
                Assert.True(restocked.Contains(number));
                var entry = restocked.NeighbourFor(number);
                Assert.True(entry.IsHollow);
                VMHollowMarshal marshal;
                Assert.True(world.LotStore.TryGetHollow(number, out marshal));
                Assert.Same(marshal, entry.Hollow);
            }
            Assert.Contains("2 hollow", restocked.Describe());

            //a lot cannot be both resident and hollow, and the displacement is deliberate: the
            //marshal being replaced was committed to that lot's own HouseNN.iff first
            var reclaimed = hollowed[0];
            world.LotStore.SetActive(reclaimed, new VMMarshal());
            Assert.Equal(NeighbourhoodLotState.Active, world.LotStore.StateOf(reclaimed));
            VMHollowMarshal gone;
            Assert.False(world.LotStore.TryGetHollow(reclaimed, out gone));
            Assert.Equal(restocked.HollowCount - 1, PlanFor(world, active.Number).HollowCount);
        }

