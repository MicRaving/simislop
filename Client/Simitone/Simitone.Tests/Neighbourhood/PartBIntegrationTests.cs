        [Fact]
        public void AWorldKeepsTimeWhileNobodyIsInALotAndSaysSoInASession()
        {
            //B1 and B7 from the same direction: the neighbourhood keeps the time - the player is on
            //the neighbourhood screen, in no lot at all - and that time is a field of the session
            //state alongside the active lot and the hops.
            var world = World();

            //the clock the interface exposes is the world clock, not a read-only projection of one
            Assert.Same(world.Clock, ((INeighbourhoodWorld)world).Clock);

            var start = world.Clock.Ticks;
            Assert.True(world.Tick(60.0));

            //a real second is a game minute, so sixty of them is an hour of neighbourhood time
            Assert.Equal(start + 60 * WorldClock.TicksPerMinuteTs1, world.Clock.Ticks);
            Assert.Equal(1, world.Clock.Hours);
            Assert.True(world.Clock.IsAvailable);

            //in no lot, and the time kept moving: §5.2's "keeps time while the player is standing in
            //no lot at all", and the reason the clock is the world's rather than a lot's to hand
            Assert.Equal(SimitoneNeighbourhoodWorld.NoActiveLot, world.ActiveLotNumber);
            Assert.True(world.Tick(60.0));
            Assert.Equal(2, world.Clock.Hours);

            //two hops, in the order they were started, one of them already arrived
            var home = world.Lots[0].Number;
            var neighbour = world.Lots[1].Number;
            var far = world.Lots[2].Number;
            world.SetActiveLot(home);
            Assert.Equal(home, world.ActiveLotNumber);
            world.Transit.Add(7, home, neighbour, LotTravelService.DiscreteTravelMode, 40);
            world.Transit.Add(9, neighbour, far, LotTravelService.DiscreteTravelMode);
            world.Transit.Complete(9);
            Assert.True(world.Transit.InTransit);

            var saved = NeighbourhoodWorldState.FromClock(world.Clock, world.ActiveLotNumber);
            world.Transit.WriteTo(saved);

            Assert.Equal(NeighbourhoodWorldState.CurrentWorldVersion, saved.WorldVersion);
            Assert.True(saved.ClockAvailable);
            Assert.Equal(home, saved.ActiveLot);
            Assert.Equal(2, saved.TransitCount);
            Assert.True(saved.InTransit);
            Assert.Equal(7, saved.Transit[0].Sim);
            Assert.Equal(far, saved.Transit[1].Destination);
            Assert.True(saved.Transit[1].IsComplete);

            //the saved copy is a copy: the live world keeps running and the session does not follow
            Assert.True(world.Tick(60.0));
            Assert.NotEqual(saved.Ticks, world.Clock.Ticks);
            world.Transit.UpdateProgress(7, 95);
            Assert.Equal(40, saved.Transit[0].Progress);
        }

        [Fact]
        public void WhatWasSavedResumesIntoAWorldThatSavesBackTheSameThing()
        {
            //The round trip B7's "quit and resume" is: a session written out of a live world, loaded
            //into a second one, and written out again. SameAs is the whole claim - the clock's eight
            //time fields, the active lot, the flag word and the hops in order - and it is an equality
            //rather than a set comparison because both sides hold hops in start order.
            var world = World();
            world.Tick(60.0);
            world.SetActiveLot(world.Lots[0].Number);
            world.Transit.Add(7, world.Lots[0].Number, world.Lots[1].Number,
                LotTravelService.DiscreteTravelMode, 40);
            world.Transit.Add(9, world.Lots[1].Number, world.Lots[2].Number, 0, 15);

            var saved = NeighbourhoodWorldState.FromClock(world.Clock, world.ActiveLotNumber);
            world.Transit.WriteTo(saved);

            //a second session over the same neighbourhood. The world itself has no loader, so the
            //handshake is the one §5.2 defines: put the session's time into a lot's clock shape and
            //pull it into the resuming world
            var resumed = World();
            resumed.SyncClockFrom(LotClockOf(saved));
            resumed.Transit.LoadFrom(saved);
