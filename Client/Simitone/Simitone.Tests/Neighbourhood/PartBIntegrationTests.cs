            string reason;
            Assert.True(transit.TryBeginTransit(origin, destination, out path, out reason), reason);
            Assert.True(path.IsValid, path.Describe());
            Assert.True(path.Length > 0,
                "a walk between two different lots has to cross at least one tile: " + path.Describe());
            Assert.Equal(origin, path.OriginLot);
            Assert.Equal(destination, path.DestinationLot);

            //The two ends are the doors the map states, not tiles the search happened to prefer.
            var start = world.Query.EntranceFor(origin);
            var end = world.Query.EntranceFor(destination);
            Assert.NotNull(start);
            Assert.NotNull(end);
            Assert.Equal(start.X, path.Start.X);
            Assert.Equal(start.Y, path.Start.Y);
            Assert.Equal(end.X, path.End.X);
            Assert.Equal(end.Y, path.End.Y);
            Assert.Equal(origin, path.Start.LotNumber);
            Assert.Equal(destination, path.End.LotNumber);

            //Every tile is road - a route that cut across a garden would be a route a player could
            //not walk - and the walk does not stand still at the start or turn up at the door twice.
            for (int i = 0; i < path.Waypoints.Count; i++)
            {
                var waypoint = path.Waypoints[i];
                Assert.True(world.Query.IsRoad(waypoint.X, waypoint.Y),
                    "waypoint " + i + " (" + waypoint + ") carries no road");
                if (i == 0 || i + 1 == path.Waypoints.Count) continue;
                Assert.False(waypoint.X == path.Start.X && waypoint.Y == path.Start.Y,
                    "the walk stands still at " + path.Start);
                Assert.False(waypoint.X == path.End.X && waypoint.Y == path.End.Y,
                    "the walk turns up at the destination door before it ends");
            }

            //One owner throughout, and while the avatar is on the street the world names no lot:
            //that is the whole reason the transit lot exists.
            Assert.Equal(ActiveLotKind.Transit, transit.Kind);
            Assert.Equal(NeighbourhoodTransitLot.NoLot, transit.ActiveLotNumber);
            Assert.Equal(SimitoneNeighbourhoodWorld.NoActiveLot, world.ActiveLotNumber);
            Assert.True(transit.HasOwner);

            //Walked in steps that do not divide the distance and are replayed until the walk is over,
            //so a rounding that dropped a step would leave the avatar short of the door rather than
            //merely late. The guard is a bug-catcher, not a bound: a walk of any length gets here.
            var steps = new[] { 0.5, 1.25, 2.0, 3.5, 7.0, 11.0, 29.0 };
            var step = 0;
            while (!transit.State.IsArrived)
            {
                Assert.True(step < 10000, "the walk never arrived: " + transit.State.Describe());
                transit.Advance(steps[step % steps.Length]);
                step++;
                string invariant;
                Assert.True(NeighbourhoodTransitLot.IsExactlyOneActiveLot(transit.Kind,
                    transit.ActiveLotNumber, out invariant), invariant);
            }
            Assert.True(step > 1, "the whole walk was one step, which is not a walk: " + path.Describe());

            //Arrived means on the door: not past it, not short of it, and a bar all the way along.
            Assert.Equal((double)path.Length, transit.State.Progress);
            Assert.Equal(path.End.X, transit.State.Current.X);
            Assert.Equal(path.End.Y, transit.State.Current.Y);
            Assert.Equal(1.0, transit.State.Fraction);
            Assert.Equal(0.0, transit.State.Remaining);
            Assert.True(transit.State.IsArrived);
            Assert.False(transit.IsWalking);

            //An overshoot is refused rather than carried past the door, a step that is not a
            //positive distance is ignored, and arrival is sticky - so a fixed-step loop that
            //catches up cannot walk the sim through the front door.
            Assert.False(transit.Advance(0.0));
            Assert.True(transit.Advance(50.0));
            Assert.Equal((double)path.Length, transit.State.Progress);
            Assert.True(transit.State.IsArrived);
            Assert.True(transit.Advance(0.5));
            Assert.Equal((double)path.Length, transit.State.Progress);

            //And completing hands the avatar to the destination, which the world's own switch then
            //agrees with: one owner, and it is a house again.
            Assert.True(transit.CompleteTransit(out reason), reason);
            Assert.Equal(destination, transit.ActiveLotNumber);
            Assert.Equal(ActiveLotKind.Active, transit.Kind);
            Assert.False(transit.IsWalking);
            Assert.False(transit.State.IsValid);

            world.SetActiveLot(destination);
            Assert.Equal(destination, world.ActiveLotNumber);
            Assert.True(NeighbourhoodTransitLot.IsExactlyOneActiveLot(transit.Kind,
                world.ActiveLotNumber, out reason), reason);
        }

