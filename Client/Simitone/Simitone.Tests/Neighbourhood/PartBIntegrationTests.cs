            Assert.Equal(1, CountOf(host.Calls, "save:" + home));
            Assert.Equal(1, CountOf(host.Calls, "save:" + neighbour));
            Assert.Equal(1, CountOf(host.Calls, "save:" + far));

            //each lot kept its own state, so the far lot's never replaced home's
            Assert.True(world.LotStore.TryGetActive(far, out stashed));
            Assert.NotSame(homeState, stashed);

            //and the player is standing in the marshal home was left in, resumed rather than reloaded
            Assert.Same(homeState, host.LastLoadedMarshal);
            Assert.Same(homeState, world.ActiveMarshal);
            Assert.Equal(home, world.ActiveLotNumber);
            Assert.Null(host.LastLoadedPath);
            Assert.Contains("resumed preserved state", reason);

            //The store holds the lots the player is not in - and only those. Home is not one of them any
            //more because its snapshot was resumed rather than kept; the two lots the player walked
            //out of are, each under its own number.
            Assert.Equal(NeighbourhoodLotState.Unloaded, world.LotStore.StateOf(home));
