        /// <summary>
        /// Whether a lot number is in a set of them. A short-typed loop rather than the
        /// <c>int</c>-typed <see cref="Contains"/> above, because every lot number in this file is
        /// a <c>short</c> and a widening cast in an assertion is noise.
        /// </summary>
        private static bool ShortContains(IReadOnlyList<short> numbers, short number)
        {
            for (int i = 0; i < numbers.Count; i++)
            {
                if (numbers[i] == number) return true;
            }
            return false;
        }

        /// <summary>That a list of lot numbers ascends, with the lot it failed on named.</summary>
        private static void AssertAscending(IReadOnlyList<short> numbers, string what)
        {
            for (int i = 1; i < numbers.Count; i++)
            {
                Assert.True(numbers[i] > numbers[i - 1],
                    what + " is not ascending: " + numbers[i - 1] + " then " + numbers[i]);
            }
        }

        /// <summary>
        /// That a gap sequence ascends and that equal gaps are broken by ascending lot number -
        /// the two halves of <see cref="SimitoneSurroundingsPlan.OrderNearestFirst"/>, and the
        /// determinism the budget's whole claim rests on.
        /// </summary>
        private static void AssertNearestFirst(
            List<int> gaps, IReadOnlyList<short> numbers, string what)
        {
            for (int i = 1; i < gaps.Count; i++)
            {
                if (gaps[i] > gaps[i - 1]) continue;
                Assert.True(gaps[i] == gaps[i - 1],
                    what + " is not nearest-first: gap " + gaps[i - 1] + " then " + gaps[i]);
                Assert.True(numbers[i] > numbers[i - 1],
                    what + " has two lots at gap " + gaps[i] + " and the lower number came second ("
                    + numbers[i - 1] + ", " + numbers[i] + ")");
            }
        }

        [Fact]
        public void ABudgetThatBindsCostsFlatnessAtTheFarEdgeAndNeverAHoleInTheStreet()
        {
            //The other half of the coverage claim, asked of a budget small enough to bind. Three
            //things have to be true together and only together: the <em>nearest</em> lots are the
            //ones that survive, the ones that did not are <em>named</em> rather than dropped, and
            //every one of them is still drawn - as a facade, which is what
            //<see cref="NeighbourhoodRenderDecision"/> gives a lot inside the region that is not a
            //sub-world. A budget that dropped a lot would put a hole in the street, and a budget
            //that kept the far ring would spend the player's load-time stall on the part of the
            //view they are not looking at.
            var world = World();
            var active = world.Lots[0].Number;
            SimitoneSurroundingsPlacement placement;
            string reason;
            Assert.True(SimitoneSurroundingsPlacement.TryFor(
                world.Layout, world.Map, active, out placement, out reason), reason);

            var full = PlanWithNoContents(world, active);
            Assert.True(full.IsFullyCovered, full.Describe());
            Assert.True(full.Neighbours.Count >= 3,
                "the fixture needs at least three neighbours for a budget to cut: " + full.Describe());

            //--- a budget of two -------------------------------------------------------------------
            var cut = SimitoneSurroundingsPlan.ForQuery(placement, world.Map, world.Query,
                world.Layout, world.LotStore,
                SimitoneSurroundingsPlan.DefaultSubWorldRadiusTiles, 2);

            Assert.True(cut.IsValid, cut.Failure);
            Assert.Equal(2, cut.Neighbours.Count);
            Assert.False(cut.IsFullyCovered);
            Assert.Equal(full.Neighbours.Count - 2, cut.DeferredCount);
            Assert.Equal(full.Neighbours.Count - 2, cut.DeferredNumbers.Count);
            //The selection order is the *candidates*, recorded before the cut, so it is the same at
            //every budget and at the same length as the full plan's. That is what lets a caller see
            //that a lot was considered and lost rather than only that it is not here.
            Assert.Equal(full.SelectionOrder, cut.SelectionOrder);
            Assert.Equal(full.Neighbours.Count, cut.SelectionOrder.Count);

            //The survivors are the *prefix* of that order and the deferred lot is the next one - so
            //the cut is nearest-first, which is what makes the choice a function of where the player
            //is standing and not of the order a neighbour list was walked in.
            for (int i = 0; i < cut.Neighbours.Count; i++)
            {
                Assert.True(ShortContains(cut.NeighbourNumbers, cut.SelectionOrder[i]),
                    "selection order entry " + i + " is not one of the lots that were kept");
            }
            for (int i = 0; i < cut.DeferredNumbers.Count; i++)
            {
                Assert.Equal(cut.SelectionOrder[2 + i], cut.DeferredNumbers[i]);
            }
            //The two sets are disjoint and together they are every lot the full plan named: no lot
            //is both a sub-world and a facade, and none is neither.
            var real = new List<short>(cut.NeighbourNumbers);
            var deferred = new List<short>(cut.DeferredNumbers);
            foreach (var number in deferred)
            {
                Assert.False(ShortContains(real, number),
                    "lot " + number + " is both real and deferred");
                Assert.True(ShortContains(full.NeighbourNumbers, number));
            }
            foreach (var number in real)
            {
                Assert.False(ShortContains(deferred, number));
            }
            //The cut plan's own list is ascending by lot number, whatever the selection order was.
            AssertAscending(cut.NeighbourNumbers, "the cut plan's neighbour list");

            //--- and the deferred lots are facades, not holes --------------------------------------
            //This is the load-bearing line. Asked of the same render decision the screen asks, over
            //the same drawn region.
            var cull = placement.Cull;
            Assert.True(NeighbourhoodRenderDecision.SubWorldsAreInsideCut(cut, cull),
                "a plan reaching past the drawn region would open a gap rather than close a "
                + "double draw");
            var cache = FacadeCache(world, placement, active);
            cache.UseSubWorlds(cut);

            var queued = DrawnLotsLayout(world, placement, active).Lots;
            var facades = 0;
            foreach (var deferredLot in deferred)
            {
                var lot = world.Layout.FindLot(deferredLot);
                Assert.NotNull(lot);
                Assert.True(lot.HasHouse);
                //Inside the region - the budget cannot cost a lot its facade, because the region is
                //what decides that and the budget is inside it.
                Assert.True(NeighbourhoodRenderDecision.InsideCut(lot, cull));
                Assert.True(NeighbourhoodFacadePlan.ShouldDraw(lot, active, cache.SubWorldLots),
                    "lot " + deferredLot + " was deferred and is now drawn as nothing at all");
                Assert.Equal(NeighbourhoodLotRender.Facade,
                    NeighbourhoodRenderDecision.Decide(lot, active, cut, cull));
                facades++;
            }
            Assert.Equal(deferred.Count, facades);
            Assert.Equal(NeighbourhoodLotRender.None, NeighbourhoodRenderDecision.Decide(
                world.Layout.FindLot(active), active, cut, cull));

            //--- the budget is said out loud -------------------------------------------------------
            //A street with a flat house in it and nothing in the log to say why is the failure this
            //number exists to make visible.
            Assert.Contains("past the budget", string.Join(" | ", cut.Warnings));
            Assert.Contains("will be drawn as facades instead", string.Join(" | ", cut.Warnings));
            foreach (var number in deferred)
            {
                Assert.Contains(number.ToString(), string.Join(" | ", cut.Warnings));
            }
            Assert.Contains("left to the facade pass", cut.Describe());
            Assert.Contains("2 sub-worlds", cut.Describe());
            //And a plan that cut nothing says nothing, because a warning nobody can act on trains a
            //player to ignore the log.
            Assert.DoesNotContain("past the budget", string.Join(" | ", full.Warnings));

            //--- the cut is a pure function of the two numbers, and the same every time --------------
            var again = SimitoneSurroundingsPlan.ForQuery(placement, world.Map, world.Query,
                world.Layout, world.LotStore,
                SimitoneSurroundingsPlan.DefaultSubWorldRadiusTiles, 2);
            Assert.Equal(cut.SelectionOrder, again.SelectionOrder);
            Assert.Equal(cut.DeferredNumbers, again.DeferredNumbers);
            Assert.Equal(cut.Describe(), again.Describe());

            //--- and the helpers on their own, so a caller can reason about the cut -----------------
            //The gap is the same measure the radius thresholds on, which is what lets a lot not be
            //"closer" than the budget's order says and still outside the radius.
            Assert.Equal(0, SimitoneSurroundingsPlan.SubWorldGapFor(full.ActiveLot,
