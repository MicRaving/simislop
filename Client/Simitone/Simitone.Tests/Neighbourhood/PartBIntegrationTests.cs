        /// <summary>
        /// What one off-screen run leaves behind: the clock it ended on, the motive table the stored
        /// lot's Sim ended with, the aggregate record made for that lot, and the record for a lot
        /// with no contents of its own. Everything a determinism claim needs, and nothing that would
        /// make the comparison a comparison of object identity.
        /// </summary>
        private sealed class OffscreenRun
        {
            public long StartClock;
            public long Clock;
            public short[] StartMotives;
            public short[] Motives;
            public OffscreenLotRecord Record;
            public OffscreenLotRecord Coarse;
            public int Records;
        }

        /// <summary>
        /// Stand in lot 0, put a resident marshal in lot 1 and a hollow marshal in lot 2, and let the
        /// world run for eight game hours at <paramref name="fidelity"/>. Two kinds of stored lot,
        /// because they are two different claims: lot 1's motive table is real data the simulator
        /// writes into, and lot 2's record is the model of a lot with no data to write - which is
        /// where the seed is visible at all.
        /// </summary>
        private static OffscreenRun RunOffscreen(long seed, OffscreenFidelity fidelity)
        {
            var world = World();
            var simulator = new OffscreenSimulator(seed);
            simulator.Fidelity = fidelity;
            simulator.ActiveLot = world.Lots[0].Number;

            var stored = world.Lots[1].Number;
            var hollow = world.Lots[2].Number;
            var marshal = ResidentMarshal(100);
            world.LotStore.SetActive(stored, marshal);
            world.LotStore.SetHollow(hollow, new VMHollowMarshal());

            var run = new OffscreenRun
            {
                StartClock = world.Clock.Ticks,
                Clock = world.Clock.Ticks,
                StartMotives = MotivesOf(marshal),
                Motives = null,
                Records = 0
            };

            var result = simulator.Tick(EightGameHours, world.Clock, world.LotStore, world.Layout);

            run.Clock = world.Clock.Ticks;
            run.Motives = MotivesOf(marshal);
            run.Record = simulator.RecordFor(stored);
            run.Coarse = simulator.RecordFor(hollow);
            run.Records = simulator.RecordCount;

            if (fidelity == OffscreenFidelity.Paused)
            {
                //nothing at all: no clock, no motive, not even a record for a lot being looked at
                //for the first time
                Assert.True(result.Paused);
                Assert.False(result.Changed);
                Assert.Equal(run.StartClock, run.Clock);
                Assert.Equal(run.StartMotives, run.Motives);
                Assert.Equal(0, run.Records);
                Assert.Null(run.Record);
                Assert.Null(run.Coarse);
            }
            else
            {
                Assert.False(result.Paused);
                Assert.True(result.Changed, result.ToString());
                Assert.Equal(2, result.LotsDecayed);
                //only the resident lot has Sims to write: the hollow one is modelled, not written
                Assert.Equal(1, result.AvatarsDecayed);
                Assert.NotEqual(run.StartMotives, run.Motives);
                Assert.NotNull(run.Coarse);
            }

            return run;
        }

