        [Fact]
        public void ASubWorldAtDeltaDPutsItsPavementOnTheWorldTilesTheGeneratedBandPutsItOn()
        {
            //The alignment invariant, and the failure it rules out is the most visible one Wave 9
            //had: the surround drew the road graph's own street, one tile *outside* the neighbour's
            //footprint, while the sub-world standing there draws <c>RestoreRoad</c>'s band *inside*
            //it - so a player's front path was a strip of pavement in the middle of their own lawn
            //with a second one across the street.
            //
            //The invariant is one fact and it is pure: for every neighbour the plan stands up, and
            //for every edge of it the band says has a street, the lot-local tile
            //<see cref="SimitoneLotViewRoad.PavementOffsetFor"/> names is the tile
            //<see cref="SimitoneLotViewRoadBand"/> says is pavement. Same function on both sides -
            //that is the point - so this is a statement about the two halves agreeing rather than
            //about a number somebody typed.
            var world = World();
            var active = world.Lots[0].Number;
            var plan = PlanWithNoContents(world, active);
            Assert.True(plan.IsValid, plan.Failure);
            Assert.NotEmpty(plan.Neighbours);

            //The region the surround draws, in map tiles: the plan's own radius around the active
            //lot's rectangle, which is the only place the band is asked about.
            var region = new Rectangle(
                Math.Max(0, plan.ActiveLot.WorldX - plan.RadiusTiles),
                Math.Max(0, plan.ActiveLot.WorldY - plan.RadiusTiles),
                plan.ActiveLot.Size + 2 * plan.RadiusTiles,
                plan.ActiveLot.Size + 2 * plan.RadiusTiles);
            var band = SimitoneLotViewRoadBand.For(world.Map, world.Layout.Lots, region);
            Assert.NotNull(band.Map);
            Assert.True(band.Width > 0 && band.Height > 0, band.ToString());
            //Not vacuous: the fixture's lots all have a street on the edge the packer put their
            //door on, so a band over them is a band with pavement in it.
            Assert.True(band.PavementTileCount > 0, band.ToString());
            Assert.True(band.TarmacTileCount > band.PavementTileCount, band.ToString());
            Assert.False(band.IsEmpty);
            Assert.Equal(band.TarmacTileCount + band.PavementTileCount, band.RoadTileCount);

            var edges = new[]
            {
                SimitoneNeighbourTerrain.RoadWest, SimitoneNeighbourTerrain.RoadNorth,
                SimitoneNeighbourTerrain.RoadEast, SimitoneNeighbourTerrain.RoadSouth
            };
            var checkedPavements = 0;

            foreach (var neighbour in plan.Neighbours)
            {
                var lot = neighbour.Lot;
                var described = neighbour.Describe();

                //The sub-world's position is the raw tile delta, unsigned, which is what
                //<c>SubDraw</c> and <c>PreDraw</c> read; the band is in the parent's own map tiles,
                //so the two are the same place only if the delta is right.
                var delta = SimitoneSurroundingsPlan.SubWorldPositionFor(plan.ActiveLot, lot);
                Assert.Equal(delta, neighbour.SubWorldPosition);
                Assert.Equal(lot.WorldX - plan.ActiveLot.WorldX, (int)neighbour.SubWorldPosition.X);
                Assert.Equal(lot.WorldY - plan.ActiveLot.WorldY, (int)neighbour.SubWorldPosition.Y);
                //The sub-world's own tile (0,0) lands at the parent's tile delta, so its local tile
                //(x, y) is at the parent's tile (delta + (x, y)) - which is this lot's own map tile,
                //because delta is the difference of the two minimum corners. That identity is the
                //whole of the placement, and it is what lets the band and the sub-world be compared
                //tile for tile at all.
                var local = new Vector2(0, 0);
                Assert.Equal(lot.WorldX - plan.ActiveLot.WorldX + (int)local.X,
                    (int)neighbour.SubWorldPosition.X);
                Assert.Equal(lot.WorldY - plan.ActiveLot.WorldY + (int)local.Y,
                    (int)neighbour.SubWorldPosition.Y);

                //One road byte for both ends of the seam. The sub-world is handed this byte by the
                //restore, and the band reads the same function, so the two cannot be laid on
                //different edges of the same lot.
                var roads = SimitoneLotViewRoad.RoadByteFor(world.Map, lot);
                Assert.Equal(roads, SimitoneNeighbourTerrain.RoadByteFor(world.Map,
                    lot.WorldX, lot.WorldY, lot.WorldX + lot.Size - 1, lot.WorldY + lot.Size - 1));
                Assert.Equal(roads, SimitoneLotViewRoad.RoadByteFor(world.Map, lot));
                if (roads == 0) continue;

                var minX = lot.WorldX;
                var minZ = lot.WorldY;
                var maxX = lot.WorldX + lot.Size - 1;
                var maxZ = lot.WorldY + lot.Size - 1;

                for (int e = 0; e < edges.Length; e++)
                {
                    var edge = edges[e];
                    var offset = SimitoneLotViewRoad.PavementOffsetFor(roads, edge);
                    if (offset < 0)
                    {
                        //No street on that edge, and the band agrees: the helper is the only thing
                        //that decides which edges there are, so this is bookkeeping rather than a
                        //claim - but it is the state a lot on the edge of the world is in.
                        Assert.Equal(-1, SimitoneLotViewRoad.TarmacOffsetFor(roads, edge));
                        continue;
                    }

                    //The tile the sub-world stamps its pavement on, in the parent's map tiles.
                    int px, pz;
                    switch (edge)
                    {
                        case SimitoneNeighbourTerrain.RoadWest:
                            px = minX + offset; pz = minZ; break;
                        case SimitoneNeighbourTerrain.RoadNorth:
                            px = minX; pz = minZ + offset; break;
                        case SimitoneNeighbourTerrain.RoadEast:
                            px = maxX - offset; pz = minZ; break;
                        default:
                            px = minX; pz = maxZ - offset; break;
                    }

                    //--- the invariant ------------------------------------------------------------
                    //The band puts its pavement on that tile and on the rest of that edge, and the
                    //lot-local offset is the *same* offset the sub-world stamps it at. This is the
                    //alignment: a sub-world at delta d has its pavement on the world tiles the
                    //generated band puts it on, and not on a parallel street a tile away.
                    Assert.True(band.TileAt(px, pz) == SimitoneLotViewRoadBand.Pavement,
                        "lot " + lot.Number + " edge 0x" + edge.ToString("X2") + ": the pavement at map "
                        + "tile (" + px + "," + pz + ") is " + band.TileAt(px, pz) + " and not pavement"
                        + " - " + described);
                    //And the tile just inside it is the lot's own ground, not another road: the
                    //pavement is a single tile wide and it is at offset 5 (or 6 on a far edge), not
                    //at the edge of the lot and not halfway across it.
                    Assert.False(band.IsPavement(minX, minZ) && (edge == SimitoneNeighbourTerrain.RoadWest
                        || edge == SimitoneNeighbourTerrain.RoadNorth) && offset != 5,
                        "lot " + lot.Number + " has a pavement strip along its own frontage");
                    checkedPavements++;

                    //The tarmac on the same edge starts where <c>StampTilemap</c> starts it, one
                    //tile in - and the outermost tile of a lot is never road, which is the fact the
                    //surround's old band got wrong by drawing in the gap instead.
                    var tarmac = SimitoneLotViewRoad.TarmacOffsetFor(roads, edge);
                    Assert.Equal(SimitoneLotViewRoad.TarmacFromEdge, tarmac);
                    var count = SimitoneLotViewRoad.TarmacCountFor(edge);
                    Assert.True(count == SimitoneLotViewRoad.TarmacTiles
                        || count == SimitoneLotViewRoad.FarTarmacTiles);
                    int tx, tz;
                    switch (edge)
                    {
                        case SimitoneNeighbourTerrain.RoadWest:
                            tx = minX + tarmac; tz = minZ; break;
                        case SimitoneNeighbourTerrain.RoadNorth:
                            tx = minX; tz = minZ + tarmac; break;
                        case SimitoneNeighbourTerrain.RoadEast:
                            tx = maxX - count + 1; tz = minZ; break;
                        default:
                            tx = minX; tz = maxZ - count + 1; break;
                    }
                    Assert.True(band.IsTarmac(tx, tz),
                        "lot " + lot.Number + " edge 0x" + edge.ToString("X2")
                        + ": the tarmac at (" + tx + "," + tz + ") is " + band.TileAt(tx, tz)
                        + " - " + described);
                }
            }

            Assert.True(checkedPavements > 0,
                "no neighbour in the fixture has a street, so the alignment above proved nothing");

            //--- the offsets themselves, which is the grammar the two halves share -----------------
            //The outermost tile of a lot is never road, the near edge is three tarmac then a gap
            //then the pavement, and the far edge is four tarmac then a gap then the pavement. Read
            //off <c>RestoreRoad</c>'s tilemaps, and the whole reason the two bands can be compared
            //is that they are read off the same three sentences.
            Assert.Equal(1, SimitoneLotViewRoad.TarmacFromEdge);
            Assert.Equal(3, SimitoneLotViewRoad.TarmacTiles);
            Assert.Equal(4, SimitoneLotViewRoad.FarTarmacTiles);
            Assert.Equal(4, SimitoneLotViewRoad.GapFromEdge);
            Assert.Equal(5, SimitoneLotViewRoad.FarGapFromEdge);
            Assert.Equal(5, SimitoneLotViewRoad.PavementFromEdge);
            Assert.Equal(6, SimitoneLotViewRoad.FarPavementFromEdge);
            //And the four edges' own depths, which are not all the same: west is offset 5 because
            //TopLeftRoadTile is three columns of tarmac, and the north, east and south edges are
            //offset 6 because their tilemaps are four rows of tarmac deep. The north edge is a
            //near edge and still one tile deeper than the west - which is the tile this used to get
            //wrong by pinning it at 5 with the west.
            byte all = (byte)(SimitoneNeighbourTerrain.RoadWest | SimitoneNeighbourTerrain.RoadNorth
                | SimitoneNeighbourTerrain.RoadEast | SimitoneNeighbourTerrain.RoadSouth);
            Assert.Equal(5, SimitoneLotViewRoad.PavementOffsetFor(all,
                SimitoneNeighbourTerrain.RoadWest));
            Assert.Equal(SimitoneLotViewRoad.NorthPavementFromEdge,
                SimitoneLotViewRoad.PavementOffsetFor(all,
                    SimitoneNeighbourTerrain.RoadNorth));
            Assert.Equal(6, SimitoneLotViewRoad.PavementOffsetFor(all,
                SimitoneNeighbourTerrain.RoadEast));
            Assert.Equal(6, SimitoneLotViewRoad.PavementOffsetFor(all,
                SimitoneNeighbourTerrain.RoadSouth));
            //An edge with no street is -1, not offset 5: there is no pavement to find.
            Assert.Equal(-1, SimitoneLotViewRoad.PavementOffsetFor(0,
                SimitoneNeighbourTerrain.RoadWest));
            Assert.Equal(-1, SimitoneLotViewRoad.TarmacOffsetFor(SimitoneNeighbourTerrain.RoadNorth,
                SimitoneNeighbourTerrain.RoadWest));
            //A null map or lot is a road byte of zero rather than a throw, which is what a lot the
            //map cannot answer about gets.
            Assert.Equal(0, SimitoneLotViewRoad.RoadByteFor(null, plan.ActiveLot));
            Assert.Equal(0, SimitoneLotViewRoad.RoadByteFor(world.Map, null));

            //--- and the band's masks, which are what the draw actually asks ----------------------
            //A pavement tile is asked of pavement: its nearest tarmac is a tile away, behind the
            //gap column, so asked of tarmac it would answer nothing and the pavement would be
            //geometry the band holds and never draws.
            var masksFound = 0;
            for (int z = band.MinZ; z < band.MaxZ; z++)
            {
                for (int x = band.MinX; x < band.MaxX; x++)
                {
                    if (band.TileAt(x, z) == SimitoneLotViewRoadBand.None)
                    {
                        Assert.Equal(RoadMask.None, band.MaskAt(x, z));
                        continue;
                    }
                    var mask = band.MaskAt(x, z);
                    Assert.True(mask != RoadMask.None,
                        "the band holds a street at (" + x + "," + z + ") and would draw nothing");
                    masksFound++;
                }
            }
            Assert.True(masksFound > 0);
            //Out of the region is nothing at all, and asking does not throw.
            Assert.Equal(SimitoneLotViewRoadBand.None, band.TileAt(-1, -1));
            Assert.False(band.IsRoad(-1, -1));
            Assert.False(band.IsTarmac(band.MaxX, band.MinZ));
            Assert.False(band.IsPavement(band.MaxX, band.MinZ));
        }

