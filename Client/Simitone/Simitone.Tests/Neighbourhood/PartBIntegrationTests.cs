            Assert.Equal(int.MaxValue, SimitoneSurroundingsPlan.SubWorldGapFor(null, full.ActiveLot));
            Assert.Equal(int.MaxValue, SimitoneSurroundingsPlan.SubWorldGapFor(full.ActiveLot, null));
