            Assert.True(map.TerrainTypeColorData.Any(c => c.A != 0)
                || map.TerrainType.Any(t => t != NeighbourhoodTerrain.Grass),
                "the fixture generated a map with no terrain variation");

            //--- the round trip, through the file, in the real user directory ----------------------
            var path = NeighbourhoodRasterCache.PathFor(_root, layout.Slot);
            Assert.NotNull(path);
            Assert.Equal(NeighbourhoodRasterCache.FileExtension,
                System.IO.Path.GetExtension(path));
            //It lives beside the layout sidecar and never inside a TS1 neighbourhood folder.
            Assert.Equal(NeighbourhoodLayoutStore.GeneratedFolder(_root),
                System.IO.Path.GetDirectoryName(path));
            Assert.False(NeighbourhoodLayoutStore.IsInsideUserData(_root, path));
            Assert.False(File.Exists(path));

            Assert.True(NeighbourhoodRasterCache.Save(_root, layout, map));
            Assert.True(File.Exists(path));
            //Twelve bytes a tile, a header and a trailing checksum: the size is computable rather
            //than declared, which is what makes a truncated file detectable before a single array
            //is allocated.
            var expected = NeighbourhoodRasterCache.HeaderSize
                + (long)map.Width * map.Height * NeighbourhoodRasterCache.BytesPerTile
                + NeighbourhoodRasterCache.ChecksumSize;
            Assert.Equal(expected, new FileInfo(path).Length);

            var loaded = NeighbourhoodRasterCache.Load(_root, layout.Slot, layout);
            Assert.NotNull(loaded);
            Assert.Equal(map.Width, loaded.Width);
            Assert.Equal(map.Height, loaded.Height);
            Assert.Equal(map.TerrainType, loaded.TerrainType);
            Assert.Equal(map.ElevationData, loaded.ElevationData);
            Assert.Equal(map.RoadData, loaded.RoadData);
            Assert.Equal(map.ForestDensityData, loaded.ForestDensityData);
            Assert.Equal(map.TerrainTypeColorData, loaded.TerrainTypeColorData);
            Assert.Equal(map.ForestTypeData, loaded.ForestTypeData);

