        [Fact]
        public void ANearNeighbourStandsUpAsARealLotAndAFarOneKeepsItsFacadeAndNeitherIsBoth()
        {
            //§B2 task 5 across the seam the single-type suite cannot reach: the plan the *screen*
            // builds is the plan the *facade cache* is told about, over the *generated*
            // neighbourhood rather than a hand-written one. Three claims, and the third is the one
            // that matters: a lot inside the plan is a real sub-world and not a facade, a lot
            // outside it but inside the drawn region is still a facade, and the two sets are
            // disjoint over every lot of the region - which is the whole of "one decision per lot".
            var world = World();
            var active = world.Lots[0].Number;

            SimitoneSurroundingsPlacement placement;
            string reason;
            Assert.True(SimitoneSurroundingsPlacement.TryFor(
                world.Layout, world.Map, active, out placement, out reason), reason);
            var cull = placement.Cull;
            Assert.True(cull.IsValid, cull.Describe());

            //The two radii are two numbers doing two jobs - a budget of whole lots stood up, and
            //how much ground is drawn - and only the relation between them is load-bearing: the
            //sub-world cut may be tighter than the facade cut, never wider.
            Assert.True(SimitoneSurroundingsPlan.RadiusFitsCut(
                SimitoneSurroundingsPlan.DefaultSubWorldRadiusTiles,
                SimitoneSurroundingsPlacement.CullRadiusTiles));

            var plan = SimitoneSurroundingsPlan.ForQuery(placement, world.Map, world.Query,
                world.Layout, world.LotStore, SubWorldRadius, SubWorldBudget);
            Assert.True(plan.IsValid, plan.Failure);
            Assert.NotEmpty(plan.Neighbours);

            //The invariant the surround checks before it withholds anything: every lot the plan
            //builds is inside the region the surround draws, so withholding a facade closes a
            //double draw rather than opening a hole in the street.
            Assert.True(plan.SubWorldsInside(cull));
            Assert.True(NeighbourhoodRenderDecision.SubWorldsAreInsideCut(plan, cull));
            Assert.True(NeighbourhoodRenderDecision.SubWorldsAreInsideCut(plan, null),
                "no region means no cut, which is the map view's situation rather than a refusal");

            //And the stronger shape the lot screen now ships: the two radii are one number, so
            //there is no ring of facades between the real lots and the edge of the drawn ground.
            Assert.True(plan.RadiusSharedWith(cull));

            //--- before: every lot with a house in the region is a facade -----------------------
            var cache = FacadeCache(world, placement, active);
            var queued = DrawnLotsLayout(world, placement, active).Lots;
            Assert.NotEmpty(queued);
            Assert.Equal(0, cache.WithheldCount);

            var housesBefore = 0;
            for (int i = 0; i < queued.Count; i++)
            {
                Assert.True(NeighbourhoodFacadePlan.ShouldDraw(queued[i], active));
                if (queued[i].HasHouse) housesBefore++;
            }
            Assert.Equal(housesBefore, NeighbourhoodFacadePlan.Eligible(
                DrawnLotsLayout(world, placement, active), active));

            //--- after: the plan's lots are sub-worlds, and only those ---------------------------
            var withheld = cache.UseSubWorlds(plan);
            Assert.Equal(plan.Neighbours.Count, withheld);
            Assert.Equal(plan.Neighbours.Count, cache.WithheldCount);
            Assert.NotEmpty(cache.SubWorldLots);

            var subWorlds = 0;
            var facades = 0;
            for (int i = 0; i < queued.Count; i++)
            {
                var lot = queued[i];
                var render = NeighbourhoodRenderDecision.Decide(lot, active, plan, cull);
                var drawsFacade = NeighbourhoodFacadePlan.ShouldDraw(lot, active, cache.SubWorldLots);

                //The two halves, asked the same question, must never both say yes. This is the
                //assertion that rules out the double draw; everything else here is bookkeeping.
                Assert.Equal(NeighbourhoodRenderDecision.IsFacade(render), drawsFacade);
                Assert.False(NeighbourhoodRenderDecision.IsSubWorld(render)
                    && NeighbourhoodRenderDecision.IsFacade(render));

                if (NeighbourhoodRenderDecision.IsSubWorld(render))
                {
                    subWorlds++;
                    //The plan really did name this lot, and the cache really did drop it: not a
                    //facade, not in the queue, and not counted in the progress line.
                    Assert.True(plan.Contains(lot.Number), lot.Number.ToString());
                    Assert.True(cache.IsWithheld(lot.Number), lot.Number.ToString());
                    Assert.False(NeighbourhoodFacadePlan.ShouldDraw(lot, active, cache.SubWorldLots));
                }
                if (drawsFacade)
                {
                    facades++;
                    Assert.False(plan.Contains(lot.Number),
                        "lot " + lot.Number + " is planned as a sub-world and queued for a facade");
                    Assert.False(cache.IsWithheld(lot.Number));
                }
            }

            //The player's own lot is in neither count - the lot view is drawing that one in full,
            //out of its own house file - and the queue really did shrink by exactly the number of
            //sub-worlds. "Still to build" must never count a lot that is deliberately not being
            //built, or the surround drains and then sits saying "1 still to build" for ever.
            Assert.Equal(subWorlds, withheld);
            Assert.Equal(housesBefore, subWorlds + facades);
            Assert.Equal(NeighbourhoodLotRender.None, NeighbourhoodRenderDecision.Decide(
                world.Layout.FindLot(active), active, plan, cull));
            Assert.Equal(facades, NeighbourhoodFacadePlan.Eligible(
                DrawnLotsLayout(world, placement, active), active, cache.SubWorldLots));
            Assert.Equal(facades, cache.Outstanding(active, Vector2.Zero));

            //A plan wider than the drawn region would put real lots on ground that was never
            //drawn, and the surround refuses exactly that rather than half-applying it: nothing
            //is withheld, so every lot in the region keeps the facade it would have had.
            var wide = SimitoneSurroundingsPlan.ForQuery(placement, world.Map, world.Query,
                world.Layout, world.LotStore, SimitoneSurroundingsPlacement.CullRadiusTiles + 1);
            Assert.False(SimitoneSurroundingsPlan.RadiusFitsCut(wide.RadiusTiles, cull.RadiusTiles));
            var before = cache.WithheldCount;
            if (!wide.SubWorldsInside(cull))
            {
                Assert.Equal(0, cache.UseSubWorlds(wide));
                Assert.Equal(before, cache.WithheldCount);
            }
        }

