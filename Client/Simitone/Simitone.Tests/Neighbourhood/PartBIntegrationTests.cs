        [Fact]
        public void AGeneratedMapRoundTripsThroughItsOwnFileAndAStaleStampIsAGenerationNotAMap()
        {
            //The persisted raster, end to end, with no graphics device and no content: the six
            //512x512 arrays a generation pass produced, written beside the layout sidecar and read
            //back. Two claims that only mean anything together.
            //
            //The first is the round trip. A cache file is a pure function of its inputs, so the
            //same map from the same layout is the same bytes - which is what makes this a round
            //trip rather than a set of values, and what makes a byte-level comparison the honest
            //assertion. A cache that loses a byte of a colour or shifts an array by one tile would
            //still produce a map that looks like a neighbourhood.
            //
            //The second is the stamp. A file is only used when it is stamped for *this* layout, and
            //every way of not being stamped for it is a regeneration and nothing else - because a
            //partly-trusted map would put some tiles from one world and some from another and would
            //look entirely plausible.
            var world = World();
            var layout = world.Layout;
            var map = world.Map;
            var plan0 = PlanWithNoContents(world, world.Lots[0].Number);

            //Not vacuous: the fixture has real data in all six arrays.
            Assert.NotNull(map);
            Assert.Equal(layout.MapSize, map.Width);
            Assert.Equal(layout.MapSize, map.Height);
            Assert.True(map.ElevationData.Any(b => b != 0) || map.RoadData.Any(b => b != 0),
