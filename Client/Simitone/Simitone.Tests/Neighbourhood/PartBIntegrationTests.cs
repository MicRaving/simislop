        /// <summary>Which lot of <paramref name="world"/> is its resident, off-screen one.</summary>
        private const short ResidentLot = 42;

        /// <summary>Which lot of <paramref name="world"/> is open to the neighbourhood.</summary>
        private const short CommunityLot = 41;

        /// <summary>
        /// One run of the off-screen simulator with or without the world's own B8 state built,
        /// and everything the two subsystems answered with: the clock they ended on, the stored
        /// lot's motive table, its record, and - where the features were built - the company the
        /// world reported at each frame. The company is counted rather than collected because two
        /// runs with different frame counts sample different minutes; the comparison is of the
        /// run's end state and of the counts, which are the same shape whatever the frames were.
        /// </summary>
        private sealed class VisitorRun
        {
            public long Clock;
            public short[] Motives;
            public OffscreenLotRecord Record;
            public int OpenSamples;
            public int CompanySamples;
            public int RecordedLots;
            public bool HadFeatures;
        }

        /// <summary>
        /// Fifteen game hours of one world with the off-screen capability on, and with the B1
        /// capability either on or off - which is the whole difference between the two runs:
        /// with it on the world builds and re-reads its own features object, and with it off that
        /// object is never constructed at all. A null visitor source is not a mock, a stub or a
        /// different call path; it is the state every other off-screen test in this file is
        /// already in.
        /// </summary>
        private static VisitorRun RunWithOptionalSource(bool visitorSource, int chunks)
        {
            NeighbourhoodWorldFlags.Set(NeighbourhoodWorldFlag.World, visitorSource, save: false);

            var world = WorldWithCommunityLot();
            world.Clock.SeedFromGlobalState(GameGlobals());
            world.LotStore.SetActive(ResidentLot, ResidentMarshal(100));

            var run = new VisitorRun();
            for (int frame = 0; frame < chunks; frame++)
            {
                Assert.True(world.Tick(FifteenGameHours / chunks));
                if (world.Visitors.Count > 0) run.CompanySamples++;
                if (NamesCommunityLot(world.Visitors)) run.OpenSamples++;
            }

            run.HadFeatures = world.HasFeatures;
            run.Clock = world.Clock.Ticks;
            run.Motives = MotivesOf(StoredMarshal(world, ResidentLot));
            OffscreenLotRecord record;
            run.RecordedLots = world.TryGetOffscreenRecord(ResidentLot, out record) ? 1 : 0;
            run.Record = record;
            return run;
        }

        private static bool NamesCommunityLot(IReadOnlyList<NeighbourhoodCommunityVisitor> visitors)
        {
            for (int i = 0; i < visitors.Count; i++)
            {
                if (visitors[i].LotNumber == CommunityLot) return true;
            }
            return false;
        }

        private static void AssertSameVisitors(IReadOnlyList<NeighbourhoodCommunityVisitor> expected,
            IReadOnlyList<NeighbourhoodCommunityVisitor> actual, string what)
        {
            Assert.True(expected.Count == actual.Count, what + ": " + expected.Count + " visitor lot(s) against "
                + actual.Count);
            for (int i = 0; i < expected.Count; i++)
            {
                Assert.True(expected[i] == actual[i],
                    what + ": lot " + expected[i] + " against lot " + actual[i]);
            }
        }

        [Fact]
        public void AVisitorSourceIsAReaderOnTheSameClockAndNeverMovesTheNumbersItIsReading()
        {
            //The seam B6 and B8 meet at, and which no single-type suite can see: two subsystems
            //wired to nothing, both holding the <em>world's</em> clock and the world's own seed.
            //The visitor draw is a function of the hour the clock reads; the off-screen decay is
            //a function of the tick the clock has reached. So a visitor source must be
            //invisible to the simulator - constructing one, refreshing it on every frame and
            //reading the company off it cannot move a neighbour's motives - and the run must
            //end in the same place however the hours were carried.
            NeighbourhoodWorldFlags.Reset();
            NeighbourhoodWorldFlags.Set(NeighbourhoodWorldFlag.Offscreen, true, save: false);
            Assert.True(NeighbourhoodWorldFlags.IsOn(NeighbourhoodWorldFlag.Offscreen));

            var runs = new List<VisitorRun>();
            foreach (var chunks in EveningChunkings)
            {
                var run = RunWithOptionalSource(true, chunks);
                runs.Add(run);

                //Not vacuous: the community lot is open, so every one of these walks found
                //company, and the simulator really did write into the store.
                Assert.True(run.CompanySamples > 0, chunks + " frame(s) found nobody home at all");
                Assert.True(run.OpenSamples > 0,
                    chunks + " frame(s) never reported the open community lot: " + run.OpenSamples);
                Assert.Equal(1, run.RecordedLots);
                Assert.NotNull(run.Record);
                Assert.Equal(1, run.Record.AvatarCount);
                Assert.Equal(ResidentLot, run.Record.Lot);
            }

            //Fifteen game hours in three frame patterns is the same neighbourhood, down to the
            //per-Sim accumulator: the visitor list is a reading of the clock, so it is identical
            //whenever the clock is, and so is everything the simulator wrote while it was read.
            //The number of frames that found company is deliberately <em>not</em> compared: a
            //sixty-frame run samples sixty minutes and a three-frame run samples five hours, so
            //the counts are counts of samples and a run that found company on all three of its
            //samples and one that found it on all sixty are the same evening.
            for (int i = 1; i < runs.Count; i++)
            {
                Assert.Equal(runs[0].Clock, runs[i].Clock);
                Assert.True(Describe(runs[0].Motives) == Describe(runs[i].Motives),
                    EveningChunkings[i] + " frame(s) against "
                    + EveningChunkings[0] + ": " + Describe(runs[0].Motives) + " vs "
                    + Describe(runs[i].Motives));
                Assert.True(runs[0].Record.SameAs(runs[i].Record),
                    runs[0].Record + " vs " + runs[i].Record);
            }

            //A null source is the old behaviour exactly. Not "the same clock" - the same motive
            //table, the same record, the same number of frames' worth of decay. A visitor source
            //that could see the simulation stream, or that advanced it by being refreshed, would
            //fail here and pass every assertion above. And the run without one really is the old
            //one: the world never built a features object at all, so there is nothing else in it.
            var without = RunWithOptionalSource(false, 15);
            var with_ = runs[1];
            Assert.True(with_.HadFeatures);
            Assert.False(without.HadFeatures);
            Assert.Equal(without.Clock, with_.Clock);
            Assert.True(Describe(without.Motives) == Describe(with_.Motives),
                "a visitor source moved the off-screen numbers: " + Describe(without.Motives)
                + " vs " + Describe(with_.Motives));
            Assert.True(without.Record.SameAs(with_.Record),
                without.Record + " vs " + with_.Record);
            Assert.Equal(0, without.CompanySamples);
            Assert.Equal(0, without.OpenSamples);
        }

        [Fact]
        public void PausedIgnoresTheVisitorsBecauseTheHourTheyAreDrawnForNeverArrives()
        {
            //The pause clause, asked of the other half of the seam. A visitor record is a
            //function of the hour; a paused simulator does not move the clock; so a paused
            //neighbourhood must report the same company on every frame - not because it ignored
            //the visitor source, but because the hour the source would draw for has not come.
            //The second half of the test is the contrast that makes the first mean anything: the
            //same world, the same frames, unpaused, walks out of the visiting window and the
            //company goes with it.
            NeighbourhoodWorldFlags.Reset();
            NeighbourhoodWorldFlags.Set(NeighbourhoodWorldFlag.Offscreen, true, save: false);
            NeighbourhoodWorldFlags.Set(NeighbourhoodWorldFlag.World, true, save: false);

            var world = WorldWithCommunityLot();
            world.Clock.SeedFromGlobalState(GameGlobals());

            //Parked at seven in the evening: the community lot is open and the street's
            //residential hump is at its widest, and the clock is stopped here for both halves.
            SetHour(world.Clock, NeighbourhoodWorldFeatures.NeighbourFirstHour + 3);
            var parked = world.Clock.Ticks;
            var hours = NeighbourhoodWorldFeatures.NeighbourLastHour
                - NeighbourhoodWorldFeatures.NeighbourFirstHour - 3;

            //One unpaused frame on an empty store, to build the world's features and put them on
            //that hour. It has to be a real tick rather than a `Refresh`, because a paused tick
            //moves nothing and therefore re-reads nothing - that is the behaviour under test, and
            //a fixture should not quietly work around it. The store is still empty, so this frame
            //has seen no lot at all and the paused half below starts from nothing.
            Assert.True(world.Tick(1.0));
            world.LotStore.SetActive(ResidentLot, ResidentMarshal(100));
            world.Offscreen.Fidelity = OffscreenFidelity.Paused;
            var features = world.Features;
            var atRest = world.Visitors;
            Assert.True(NamesCommunityLot(atRest), "the open community lot is not on the list: "
                + features.Describe());
            var refreshes = world.FeatureTicks;
            var motives = MotivesOf(StoredMarshal(world, ResidentLot));

            //Fifteen frames, each a quarter of an hour of neighbourhood time.
            for (int frame = 0; frame < 15; frame++)
            {
                Assert.False(world.Tick(FifteenGameHours / 60));
                Assert.Equal(NeighbourhoodWorldFeatures.NeighbourFirstHour + 3,
