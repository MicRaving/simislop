            //Nothing is cached yet - the build above failed, and a lot that could not be read is
            //never remembered - so the lot still needs one.
            var marshal = new VMHollowMarshal();
            loader.MaxBuilds = 0;
            Assert.False(loader.AllowsBuild());
            Assert.Equal(0, loader.CachedLots);
            Assert.True(NeighbourHollowLoader.NeedsBuild(lot, loader.CachedHashes));

            VMHollowMarshal cached;
            Assert.False(loader.TryGetCached(lot.Number, lot.HouseHash, out cached));
            Assert.Null(cached);

            loader.Remember(lot.Number, lot.HouseHash, marshal);
            Assert.Equal(1, loader.CachedLots);
            Assert.True(loader.TryGetCached(lot.Number, lot.HouseHash, out cached));
            Assert.Same(marshal, cached);
            //A matching hash with no marshal behind it is a miss, not a hit: the two are written
            //together and read together, and a "hit" that handed back null would be a lot that
            //succeeded and then built blank.
            Assert.False(NeighbourHollowLoader.TryGetCached(lot.Number, lot.HouseHash,
                new Dictionary<short, uint> { { lot.Number, lot.HouseHash } },
                new Dictionary<short, VMHollowMarshal>(), out cached));
            Assert.Null(cached);

            //And now the budget is irrelevant: the cache is asked *before* the budget, so a lot we
            //can answer for free is never blanked because the pass has spent its allowance.
            Assert.False(loader.AllowsBuild());
            Assert.True(loader.TryLoad(lot, out cached, out why));
            Assert.Same(marshal, cached);
            Assert.Null(why);
            Assert.Equal(1, loader.CachedCount);
            Assert.Equal(1, loader.BlankCount);
            Assert.Equal(1, loader.Attempts);
            Assert.Contains("1 cache hit", loader.Describe());

            //--- the file moved, and the cache is not a hit ---------------------------------------
            var moved = new NeighbourhoodLot
            {
                Number = lot.Number, WorldX = lot.WorldX, WorldY = lot.WorldY, Size = lot.Size,
                HasHouse = true, HouseHash = lot.HouseHash + 1u
            };
            Assert.True(NeighbourHollowLoader.NeedsBuild(moved, loader.CachedHashes));
            Assert.False(loader.TryGetCached(moved.Number, moved.HouseHash, out cached));
            Assert.Null(cached);
            //and it is answered blank rather than from the file it had before
            Assert.False(loader.TryLoad(moved, out cached, out why));
            Assert.Null(cached);
            Assert.Contains("budget", why, StringComparison.Ordinal);

            //--- forgetting ------------------------------------------------------------------------
            loader.Clear();
            Assert.Equal(0, loader.CachedLots);
            Assert.Empty(loader.CachedHashes);
            Assert.False(loader.TryGetCached(lot.Number, lot.HouseHash, out cached));
            //Remember with a null is the same as forgetting, which is what a caller pruning the
            //cache does.
            loader.Remember(lot.Number, lot.HouseHash, marshal);
            Assert.Equal(1, loader.CachedLots);
            loader.Remember(lot.Number, lot.HouseHash, null);
            Assert.Equal(0, loader.CachedLots);

            //And a new pass restarts the counters but not the cache, because a pass is about what
            //this load may spend rather than about what it knows.
            loader.Remember(lot.Number, lot.HouseHash, marshal);
            loader.BeginPass();
            Assert.Equal(0, loader.Attempts);
            Assert.Equal(0, loader.BuiltCount);
            Assert.Equal(0, loader.CachedCount);
            Assert.Equal(0, loader.BlankCount);
            Assert.Equal(1, loader.CachedLots);
        }

        [Fact]
        public void TheLoaderSpendsItsBudgetCountFirstAndTheClockSecondWithTheFirstLotFree()
        {
            //<see cref="NeighbourHollowLoader.AllowsBuild"/>, as a table rather than as a
            //description, because both of its rules fail in a way that only shows up in the
            //combination: a budget that is checked before the cache blanks a lot we can answer for
            //free, and a clock that is checked before the first build of a pass gives a queue that
            //can never advance - which is the exact bug the facade pass already learned from.
            //Over-budget is "false" in every row, and the first build is unconditional in every one.
            var cases = new[]
            {
                //maxBuilds, soFar, msBudget, elapsed, holds
                new { Max = 4, SoFar = 0, Ms = 2500d, Elapsed = 0d, Allows = true },
                new { Max = 4, SoFar = 3, Ms = 2500d, Elapsed = 0d, Allows = true },
                new { Max = 4, SoFar = 4, Ms = 2500d, Elapsed = 0d, Allows = false },
                new { Max = 4, SoFar = 5, Ms = 2500d, Elapsed = 0d, Allows = false },
                new { Max = 0, SoFar = 0, Ms = 0d, Elapsed = 0d, Allows = false },
                new { Max = -3, SoFar = 0, Ms = 0d, Elapsed = 0d, Allows = false },
                //The count alone is the whole rule when there is no clock: zero or less means "no
                //wall-clock limit", which is the facade pass's own convention and not "no budget".
                new { Max = 4, SoFar = 4, Ms = 0d, Elapsed = 1e9, Allows = false },
                new { Max = 4, SoFar = 3, Ms = -1d, Elapsed = 1e9, Allows = true },
                //The clock, once the pass has already built something.
                new { Max = 4, SoFar = 1, Ms = 2500d, Elapsed = 2499d, Allows = true },
                new { Max = 4, SoFar = 1, Ms = 2500d, Elapsed = 2500d, Allows = false },
                new { Max = 4, SoFar = 1, Ms = 2500d, Elapsed = 2500.1, Allows = false },
                //The first build of a pass, on a clock that is already spent. History needs something
                //to be history about, and there is none on the first build.
                new { Max = 4, SoFar = 0, Ms = 2500d, Elapsed = 1e9, Allows = true }
            };
            for (int i = 0; i < cases.Length; i++)
            {
                var row = cases[i];
                Assert.True(row.Allows == NeighbourHollowLoader.AllowsBuild(
                        row.Max, row.SoFar, row.Ms, row.Elapsed),
                    "budget " + row.Max + ", " + row.SoFar + " built, " + row.Ms + "ms of "
                    + row.Elapsed + "ms spent");
            }

            //The same rule on the object rather than the function, and a lot that cannot be built
            //is a blank lot with a sentence naming the number and the budget.
            var world = World();
            var plan = PlanWithNoContents(world, world.Lots[0].Number);
            var lot = Fingerprinted(plan.NeighbourFor(plan.NeighbourNumbers[0]).Lot, AnyHouseHash);

            var loader = new NeighbourHollowLoader(null, 1);
            Assert.Equal(NeighbourHollowLoader.DefaultMaxBuilds, 4);
            Assert.True(loader.MaxMilliseconds <= 0d,
                "the one-argument loader is the uncapped-clock one, which is what a caller that has "
                + "not thought about milliseconds wants");

            VMHollowMarshal marshal;
            string why;
            Assert.False(loader.TryLoad(lot, out marshal, out why));
            Assert.Equal(1, loader.Attempts);
            Assert.False(loader.AllowsBuild());
            Assert.Contains("budget", loader.Describe());

            //The second lot of the *same* pass is refused on the budget, and the sentence says what
            //will happen instead - which is the difference between a blank lot a player can explain
            //and a blank lot they cannot. No <c>BeginPass</c> here: a new pass would make the first
            //build unconditional again, which is the very rule the table above is about, and
            //asserting that a pass restarts is <c>BeginPass</c>'s own claim rather than this one's.
            loader.MaxMilliseconds = 1d;
            Assert.False(loader.AllowsBuild());
            Assert.False(loader.TryLoad(lot, out marshal, out why));
            Assert.Null(marshal);
            Assert.Contains("read the next time a lot load has budget", why, StringComparison.Ordinal);
            Assert.Contains("hollow build", why, StringComparison.Ordinal);
            //Still one attempt: a lot refused on the budget never cost a world.
            Assert.Equal(1, loader.Attempts);
            Assert.Equal(2, loader.BlankCount);
        }

