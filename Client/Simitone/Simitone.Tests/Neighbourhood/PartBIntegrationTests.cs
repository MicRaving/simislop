    /// <summary>
    /// Part B end to end, with no graphics device, no content manager and no running <c>VM</c>:
    /// the pieces of a live neighbourhood connected to each other rather than each tested alone.
    ///
    /// <para>
    /// <b>Why this file exists when the per-milestone suites already exist.</b> Every milestone's
    /// own tests hold one type up on its own -
    /// <c>SimitoneSurroundingsPlanTests</c> plans over a hand-written street,
    /// <c>SimitoneNeighbourhoodWorldTests</c> ticks a world over a blank map,
    /// <c>LotTravelServiceTests</c> asserts the switch order against a dictionary. Each is right
    /// about its own type and silent about the seams between them, and the seams are where a
    /// milestone's pieces actually meet: the query the world builds is the query the plan asks, the
    /// store the plan reads is the store the switch writes, the hops the switch records are the hops
    /// the sidecar persists, and the seed the layout carries is the seed the off-screen simulator
    /// draws from. A change that breaks one of those passes every single-type suite and fails here.
    /// </para>
    ///
    /// <para>
    /// <b>The fixtures are the real ones.</b> A four-lot neighbourhood is generated by the real
    /// generator (streets, ground, heights) and described by the real adapter, and the world builds
    /// its own query over the result - so "the map can answer for this lot" is a fact about the map
    /// rather than a hand-written byte. The travel host is a fake, because the screen is not
    /// reachable without a content manager, but it is a fake of the real
    /// <see cref="ILotTravelHost"/> and the store and transit table behind two of its members are
    /// the world's own.
    /// </para>
    ///
    /// <para>
    /// <b>Why this class is in the non-parallel collection.</b> The capability switches are
    /// process-wide and cached in a static, and the tests that move them on and off read them back
