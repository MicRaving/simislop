        /// <summary>
        /// Where a waypoint sits in a path's chain, or -1. A loop rather than
        /// <c>IndexOf</c> because <see cref="TransitPath.Waypoints"/> is a read-only list and this
        /// file takes no LINQ, so the helper is the one place the two views of a walk - the full
        /// chain and the turn-only corners - are lined up against each other.
        /// </summary>
        private static int IndexOfWaypoint(TransitPath path, TransitWaypoint waypoint)
        {
            for (int i = 0; i < path.Waypoints.Count; i++)
            {
                if (path.Waypoints[i] == waypoint) return i;
            }
            return -1;
        }

        /// <summary>
        /// Everything <see cref="TransitPath"/> promises about itself, on one planned walk: the
        /// chain is single-tile steps, the length is the chain, the two ends are the two doors
        /// and nothing else carries a lot number, and the corners are the turns and only the
        /// turns - so a debug draw of the corners and a follower walking the chain cannot be
        /// looking at two different routes.
        /// </summary>
        private static void AssertWellFormedPath(TransitPath path, int origin, int destination)
        {
            Assert.True(path.IsValid, path.Describe());
            Assert.Equal(origin, path.OriginLot);
            Assert.Equal(destination, path.DestinationLot);
            Assert.Equal(path.Waypoints.Count - 1, path.Length);
            Assert.Equal(path.Waypoints[0], path.Start);
            Assert.Equal(path.Waypoints[path.Waypoints.Count - 1], path.End);

            //The two ends are the doors, and they are the only waypoints that name a lot.
            Assert.True(path.Start.IsEntrance);
            Assert.True(path.End.IsEntrance);
            Assert.Equal(origin, path.Start.LotNumber);
            Assert.Equal(destination, path.End.LotNumber);
            for (int i = 1; i + 1 < path.Waypoints.Count; i++)
            {
                Assert.False(path.Waypoints[i].IsEntrance,
                    "waypoint " + i + " (" + path.Waypoints[i] + ") is not a door but names a lot");
            }

            //The corners are a subset of the chain, in the chain's order, and between two of
            //them every step goes the same way - which is the definition of "turn" and the only
            //thing a turn-only view can be allowed to elide.
            Assert.True(path.Corners.Count >= 2, path.Describe());
            Assert.True(path.Corners.Count <= path.Waypoints.Count, path.Describe());
            Assert.Equal(path.Start, path.Corners[0]);
            Assert.Equal(path.End, path.Corners[path.Corners.Count - 1]);
            var previous = -1;
            for (int c = 0; c < path.Corners.Count; c++)
            {
                var at = IndexOfWaypoint(path, path.Corners[c]);
                Assert.True(at > previous, "the corners are not in the chain's order: " + path.Describe());
                previous = at;
            }
            for (int c = 1; c < path.Corners.Count; c++)
            {
                var from = IndexOfWaypoint(path, path.Corners[c - 1]);
                var to = IndexOfWaypoint(path, path.Corners[c]);
                if (to == from + 1) continue;
                //Every step between two corners is the same single-tile step: that is what a
                //turn-only view is allowed to elide, and it is checked as the step rather than
                //as the displacement - a straight run of twenty-four tiles is twenty-four steps
                //of one, not one step of twenty-four.
                var stepX = path.Waypoints[from + 1].X - path.Waypoints[from].X;
                var stepY = path.Waypoints[from + 1].Y - path.Waypoints[from].Y;
                Assert.Equal(1, Math.Abs(stepX) + Math.Abs(stepY));
                for (int i = from + 1; i <= to; i++)
                {
                    Assert.Equal(stepX, path.Waypoints[i].X - path.Waypoints[i - 1].X);
                    Assert.Equal(stepY, path.Waypoints[i].Y - path.Waypoints[i - 1].Y);
                }
            }
        }

        [Fact]
        public void TheTransitLotPlansTheSameWalkEveryTimeAndRefusesRatherThanGuessing()
        {
            //B4's decision half, over the generated map the rest of this file uses rather than
            //over a hand-written grid. Three claims that only mean anything together: the route
            //is a function of the query alone (B7 resumes a walk from a sidecar, and a
            //pathfinder that re-tied its open set differently on a later run would move the
            //avatar somewhere the save did not say), every lot pair in a real neighbourhood is
            //walkable, and everything the planner cannot do is a sentence rather than a guess.
            var world = World();

            for (int from = 0; from < world.Lots.Count; from++)
            {
                for (int to = 0; to < world.Lots.Count; to++)
                {
                    var origin = world.Lots[from].Number;
                    var destination = world.Lots[to].Number;

                    var planner = new NeighbourhoodTransitLot(world.Query, ActiveLotKind.Active, origin);
                    TransitPath path;
                    string reason;

                    //Lot to itself: the shortest walk there is, and a valid one. Zero length is
                    //arrived, not walking, and the caller that walks it must not fall off the end
                    //of a list of one.
                    Assert.True(planner.TryPlanPath(origin, destination, out path, out reason), reason);
                    if (origin == destination)
                    {
                        Assert.Equal(0, path.Length);
                        Assert.True(path.IsValid);
                        Assert.Equal(path.Start, path.End);
                        continue;
                    }

                    AssertWellFormedPath(path, origin, destination);
                    Assert.True(path.Length > 0, "a walk between two different lots crosses no "
                        + "tiles at all: " + path.Describe());

                    //The two ends are the doors the map states, and every tile is road: a route
                    //that cut across a garden would be a route a player could not walk.
                    var door = world.Query.EntranceFor(destination);
                    Assert.NotNull(door);
                    Assert.Equal(door.X, path.End.X);
                    Assert.Equal(door.Y, path.End.Y);
                    for (int i = 0; i < path.Waypoints.Count; i++)
                    {
                        Assert.True(world.Query.IsRoad(path.Waypoints[i].X, path.Waypoints[i].Y),
                            "waypoint " + i + " (" + path.Waypoints[i] + ") carries no road");
                    }

                    //Planned twice, by two objects, is the same walk in the same order. The
                    //frontier's order is a total order over tiles and the neighbours are
                    //expanded in a fixed direction order, so this is a property of the query and
                    //not of the heap's current contents.
                    var again = new NeighbourhoodTransitLot(world.Query, ActiveLotKind.Active, origin);
                    TransitPath repeated;
                    Assert.True(again.TryPlanPath(origin, destination, out repeated, out reason), reason);
                    Assert.Equal(path.Waypoints.Count, repeated.Waypoints.Count);
                    Assert.Equal(path.Corners.Count, repeated.Corners.Count);
                    for (int i = 0; i < path.Waypoints.Count; i++)
                    {
                        Assert.True(path.Waypoints[i] == repeated.Waypoints[i],
                            "two plans over one query differ at tile " + i + ": "
                            + path.Waypoints[i] + " vs " + repeated.Waypoints[i]);
                    }

                    //And back the other way costs the same number of tiles, because both are
                    //shortest routes on the same graph - a walk that is cheaper one way round
                    //would mean the planner is not measuring what it is walking.
                    var back = new NeighbourhoodTransitLot(world.Query, ActiveLotKind.Active, destination);
                    TransitPath reversed;
                    Assert.True(back.TryPlanPath(destination, origin, out reversed, out reason), reason);
                    AssertWellFormedPath(reversed, destination, origin);
                    Assert.Equal(path.Length, reversed.Length);
                }
            }
        }

        /// <summary>
        /// One row of the exactly-one-active-lot table: the owning kind (or none), the lot it
        /// names, and whether that pair is allowed to hold the avatar. A struct rather than a
        /// tuple or a string so the table reads as the rule it is, and so a row cannot be
        /// written in the wrong order without a compile error.
        /// </summary>
        private readonly struct InvariantCase
        {
            public readonly ActiveLotKind? Kind;
            public readonly int Lot;
            public readonly bool Holds;

            public InvariantCase(ActiveLotKind? kind, int lot, bool holds)
            {
                Kind = kind;
                Lot = lot;
                Holds = holds;
            }
        }

        [Fact]
        public void TheTransitLotRefusesWhatItCannotPlanAndAlwaysNamesOneOwner()
        {
            //The other half of the same module: what it says no to. A walk decision that guesses
            //is worse than one that refuses, because a caller that is told "no" can grey a lot
            //out and a caller that is handed a route it cannot walk cannot. The invariant table
            //is asked in full here, including the two states the type's own lifecycle is
            //written never to reach, so a change to the predicate is a change to this test.
            var world = World();
            var origin = world.Lots[0].Number;
            var destination = world.Lots[2].Number;

            //--- the invariant, as a table -------------------------------------------------------
            //Active and Hollow are houses and name exactly one lot; Transit is a street region
            //and names none; 0 is "the player is in no lot"; and a value cast in from nowhere
            //names no state this world can be in. Every row, so a change to the predicate is a
            //change to this test rather than to one row of it.
            var cases = new[]
            {
                new InvariantCase(null, NeighbourhoodTransitLot.NoLot, false),
                new InvariantCase(ActiveLotKind.Transit, NeighbourhoodTransitLot.NoLot, true),
                new InvariantCase(ActiveLotKind.Active, origin, true),
                new InvariantCase(ActiveLotKind.Hollow, origin, true),
                new InvariantCase(ActiveLotKind.Active, NeighbourhoodTransitLot.NoLot, false),
                new InvariantCase(ActiveLotKind.Hollow, NeighbourhoodTransitLot.NoLot, false),
                new InvariantCase(ActiveLotKind.Transit, origin, false),
                new InvariantCase((ActiveLotKind)7, origin, false),
                new InvariantCase((ActiveLotKind)(-1), origin, false)
            };
            for (int i = 0; i < cases.Length; i++)
            {
                var row = cases[i];
                string because;
                var held = NeighbourhoodTransitLot.IsExactlyOneActiveLot(row.Kind, row.Lot, out because);
                Assert.True(row.Holds == held,
                    (row.Kind.HasValue ? row.Kind.Value.ToString() : "no kind") + " owning lot "
                    + row.Lot + " should " + (row.Holds ? "" : "not ") + "hold the invariant: " + because);
                Assert.Equal(row.Holds,
                    NeighbourhoodTransitLot.IsExactlyOneActiveLot(row.Kind, row.Lot));
                Assert.True(held == (because == null), "a passing predicate that still says why");
                if (row.Holds) Assert.Null(because);
                else Assert.False(string.IsNullOrWhiteSpace(because));
            }

            //--- refusals, each naming its case --------------------------------------------------
            var planner = new NeighbourhoodTransitLot(world.Query, ActiveLotKind.Active, origin);
            TransitPath none;
            string reason;

            Assert.False(planner.TryPlanPath(99, destination, out none, out reason));
            Assert.Same(TransitPath.None, none);
            Assert.Contains("99", reason);
            Assert.Contains("not in this neighbourhood", reason);

            Assert.False(planner.TryPlanPath(origin, 99, out none, out reason));
            Assert.Contains("not in this neighbourhood", reason);
            Assert.Contains("destination", reason);

            //A plot with no house has no door, which is the same reason the query gives it no
            //entrance - and a bulldozed lot in the middle of a working street is the case a
            //player would meet first.
            var plotInput = NeighbourhoodTestInput.OneBulldozedLot();
