        [Fact]
        public void TheDrawnRegionIsFullyRealAndOnlyTheBudgetEverMakesItNot()
        {
            //B2's coverage claim over a real generated neighbourhood and a real drawn region: every
            //lot inside the region is a real sub-world while the budget holds, the radii are the
            //same number so there is no band of facades between the real lots and the drawn ground,
            //and a budget that does bind takes the nearest lots and leaves the rest as facades
            //rather than as holes.
            var world = World();
            var layout = world.Layout;
            var active = world.Lots[0];
            SimitoneSurroundingsPlacement placement;
            string reason;
            Assert.True(SimitoneSurroundingsPlacement.TryFor(
                layout, world.Map, active.Number, out placement, out reason), reason);
            var cull = placement.Cull;
            Assert.True(cull.IsValid, cull.Describe());

            var inRegion = cull.LotsInRange(layout, (short)active.Number);
            Assert.True(inRegion.Count > 1,
                "the drawn region holds " + inRegion.Count + " lot(s) other than the player's own,"
                + " so there is nothing for the coverage claim to be about");

            //--- under budget: the region is entirely real ----------------------------------------
            var full = SimitoneSurroundingsPlan.ForQuery(placement, world.Map, world.Query,
                layout, world.LotStore, SubWorldRadius, SubWorldBudget);
            Assert.True(full.IsValid, full.Failure);
            Assert.NotEmpty(full.Neighbours);
            Assert.True(full.IsFullyCovered, full.Describe());
            Assert.Equal(0, full.DeferredCount);
            Assert.Equal(SubWorldRadius, full.RadiusTiles);
            Assert.Equal(SubWorldBudget, full.SubWorldBudget);
            Assert.True(full.RadiusSharedWith(cull));

            for (int i = 0; i < inRegion.Count; i++)
            {
                var lot = inRegion[i];
                Assert.True(NeighbourhoodRenderDecision.IsSubWorld(
                        NeighbourhoodRenderDecision.Decide(lot, active.Number, full, cull)),
                    "lot " + lot.Number + " is inside the drawn region but is not a real lot");
                Assert.DoesNotContain(lot.Number, full.DeferredNumbers);
            }
            Assert.Equal(0, NeighbourhoodRenderDecision.FacadeFallbackCount(
                layout, active.Number, full, cull));

            //--- over budget: nearest first, and the surplus is drawn rather than dropped ----------
            foreach (var budget in new[] { 0, 1, Math.Max(1, full.Neighbours.Count - 1) })
            {
                var trimmed = SimitoneSurroundingsPlan.ForQuery(placement, world.Map, world.Query,
                    layout, world.LotStore, SubWorldRadius, budget);
                Assert.True(trimmed.IsValid, trimmed.Failure);
                Assert.Equal(budget, trimmed.SubWorldBudget);
                Assert.Equal(budget, trimmed.Neighbours.Count);

                //the nearest-first prefix survives and the rest is deferred, both in that order
                var order = full.SelectionOrder;
                Assert.Equal(order, trimmed.SelectionOrder);
                for (int i = 0; i < budget; i++)
                {
                    Assert.Contains(order[i], trimmed.NeighbourNumbers);
                    Assert.DoesNotContain(order[i], trimmed.DeferredNumbers);
                }
                for (int i = budget; i < order.Count; i++)
                {
                    Assert.DoesNotContain(order[i], trimmed.NeighbourNumbers);
                    Assert.Contains(order[i], trimmed.DeferredNumbers);
                }

                //and every lot in the region is drawn exactly one way - a sub-world or a facade,
                //never neither, which is the hole this change must not be able to open
                var facades = 0;
                for (int i = 0; i < inRegion.Count; i++)
                {
                    var lot = inRegion[i];
                    var render = NeighbourhoodRenderDecision.Decide(lot, active.Number, trimmed, cull);
                    //A bulldozed plot draws nothing whichever way the budget went - it has no mesh
                    //to build and nothing to stand up - and that is the one lot in the region that
                    //is allowed to be neither. Everything else is drawn exactly one way.
                    if (lot.HasHouse) Assert.NotEqual(NeighbourhoodLotRender.None, render);
                    if (NeighbourhoodRenderDecision.IsFacade(render))
                    {
                        facades++;
                        Assert.True(trimmed.DeferredNumbers.Contains(lot.Number),
                            "lot " + lot.Number + " is a facade but was not deferred by the budget");
                    }
                    else if (NeighbourhoodRenderDecision.IsSubWorld(render))
                    {
                        Assert.True(trimmed.Contains(lot.Number));
                    }
                }
                //The facade count is over the deferred lots that have a house on them, since a
                //bulldozed plot draws nothing either way.
                Assert.Equal(facades, NeighbourhoodRenderDecision.FacadeFallbackCount(
                    layout, active.Number, trimmed, cull));
                Assert.Equal(trimmed.IsFullyCovered, facades == 0);
            }

            //--- and the capability-off behaviour is untouched by any of it ------------------------
            //With no plan at all, every lot in the region is a facade exactly as it was before this
            //feature: no plan means no sub-worlds, and the decision falls through to the facade
            //test Part A already had.
            var none = SimitoneSurroundingsPlan.ForQuery(placement, world.Map, world.Query,
                layout, world.LotStore, SubWorldRadius, 0);
            Assert.Empty(none.Neighbours);
            var offPlan = SimitoneSurroundingsPlan.ForQuery(placement, world.Map, world.Query,
                layout, null, SubWorldRadius, 0);
            var facadesOff = 0;
            for (int i = 0; i < inRegion.Count; i++)
            {
                var lot = inRegion[i];
                Assert.Equal(NeighbourhoodLotRender.Facade,
                    NeighbourhoodRenderDecision.Decide(lot, active.Number, offPlan, cull));
                facadesOff++;
            }
            Assert.Equal(facadesOff, NeighbourhoodRenderDecision.FacadeFallbackCount(
                layout, active.Number, offPlan, cull));
            Assert.True(facadesOff > 0);
        }

