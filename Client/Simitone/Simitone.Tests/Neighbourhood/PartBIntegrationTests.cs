            //the same file, and a cache that is not deterministic cannot be compared to anything.
            var again = NeighbourhoodRasterCache.Serialize(layout, map);
            var first = NeighbourhoodRasterCache.Serialize(layout, loaded);
            Assert.Equal(first, again);

            //And the map that comes out of it is a real map, not six arrays: the query walks it and
