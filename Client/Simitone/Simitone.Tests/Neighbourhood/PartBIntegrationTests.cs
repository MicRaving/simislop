            //than a draw, so it holds for every seed and every neighbourhood.
            SetHour(world.Clock, 4);
            features.Refresh();
            Assert.Equal(4, features.Lighting.TimeOfDay.Hour);
            Assert.Empty(features.Visitors);
            for (int i = 0; i < world.LotCount; i++)
            {
                Assert.False(features.IsLotActive(world.Lots[i].Number));
                Assert.False(NeighbourhoodWorldFeatures.IsLotActive(world.Lots[i].Number,
                    world.Clock, world.Seed, world.Layout));
            }

            //Eight in the evening, the peak. Whatever the draw says, every lot the list names is a
            //lot the predicate says is active, the list is ascending by lot number, and it fits in
            //the budget it publishes. The peak is an hour after the sun has gone, which is the
            //point of a visiting hump: company is not a daylight phenomenon.
            SetHour(world.Clock, NeighbourhoodWorldFeatures.PeakVisitorHour);
            features.Refresh();
            var listed = features.Visitors;
            Assert.NotNull(listed);
            Assert.True(listed.Count <= NeighbourhoodWorldFeatures.MaxActiveVisitorLots,
                listed.Count + " visitor lots is more than the "
                + NeighbourhoodWorldFeatures.MaxActiveVisitorLots + " it publishes a budget for");
            Assert.Equal(WorldDayPhase.Night, features.DayPhase);
            Assert.True(features.IsNight);

            for (int i = 0; i < listed.Count; i++)
            {
                var lot = listed[i].LotNumber;
                Assert.True(features.IsLotActive(lot), "lot " + lot + " is listed but not active");
                Assert.True(NeighbourhoodWorldFeatures.IsLotActive(lot, world.Clock, world.Seed,
                    world.Layout), "the pure predicate disagrees with the object about lot " + lot);
                NeighbourhoodLot found;
                Assert.True(world.TryGetLot(lot, out found));
                Assert.True(found.HasHouse);
                Assert.Equal(LotZoning.ZoneResidential, found.Zone);
                Assert.Equal(NeighbourhoodVisitorKind.Neighbour, listed[i].Kind);
                if (i == 0) continue;
                Assert.True(listed[i - 1].LotNumber < lot, "the visitor list is not ascending");
            }

            //Asked twice, at the same hour, by two objects: the same list. The draw is keyed by the
            //seed, the day and the lot, so a second object is not a second sequence to walk.
            var other = new NeighbourhoodWorldFeatures(world.Clock, world.Layout);
            var repeated = NeighbourhoodWorldFeatures.VisitorsAt(world.Clock, world.Seed, world.Layout);
            Assert.Equal(listed.Count, repeated.Count);
            for (int i = 0; i < listed.Count; i++) Assert.Equal(listed[i], repeated[i]);
            Assert.Equal(listed.Count, other.Visitors.Count);

            //The list is bounded, the predicate is not: a lot the list had no room for is still
            //answerable, which is the difference between the two members that they both exist.
            var anyActive = 0;
            for (int i = 0; i < world.LotCount; i++)
            {
                if (features.IsLotActive(world.Lots[i].Number)) anyActive++;
            }
            Assert.True(anyActive >= listed.Count,
                "the bounded list named more lots than the predicate says are active");

            //The refusals, which are answers rather than exceptions: a lot that is not in this
            //neighbourhood, and a plot with no door for a visitor to arrive at.
            Assert.False(NeighbourhoodWorldFeatures.IsLotActive(99, world.Clock, world.Seed, world.Layout));

            var plotInput = NeighbourhoodTestInput.OneBulldozedLot();
            var plot = new SimitoneNeighbourhoodWorld(
                NeighbourhoodMapAdapter.DescribeInput(plotInput),
                NeighbourhoodMapGenerator.Generate(plotInput), true);
            var plotFeatures = new NeighbourhoodWorldFeatures(plot.Clock, plot.Layout);
            SetHour(plot.Clock, NeighbourhoodWorldFeatures.PeakVisitorHour);
            plotFeatures.Refresh();
            Assert.Empty(plotFeatures.Visitors);
            Assert.False(plotFeatures.IsLotActive(plot.Lots[0].Number));
        }

