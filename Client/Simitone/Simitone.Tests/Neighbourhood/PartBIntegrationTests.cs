        /// <summary>
        /// Frame counts over <see cref="FifteenGameHours"/> that each carry a whole number of
        /// coarse decay steps - thirty steps in total, two an hour - so the off-screen results of
        /// one run and the next are directly comparable. Sixty frames is deliberately absent: it
        /// carries half a step each, and the test that uses it asserts the bound rather than the
        /// equality.
        /// </summary>
        private static readonly int[] StepAlignedChunkings = { 1, 2, 3, 5, 15 };

        // ======================= the off-screen room score and income (B6) ====================

        [Fact]
        public void TheRoomScoreAndTheIncomeEstimateAreOffUntilAskedForAndTheSameSeedGivesTheSameAnswer()
        {
            //B6's two opt-in models across the seam they are wired at: the world's *own* simulator,
            //reached through the world's own tick, over a generated neighbourhood with the world's
            //own store. Three claims:
            //
            //  - both are off by default, and off means the numbers the build produced before the
            //    models existed - the same motive table, the same record, field for field;
            //  - on, they are bounded, deterministic and frame-rate independent, and the seed is
            //    what makes them a *neighbourhood's* rather than the type's;
            //  - turning either on moves nothing but what it is allowed to move: no decay draw,
            //    no clock, and no second model disturbed by the other.
            var seed = WorldSeed();

            //--- off: the pre-model answer, exactly ----------------------------------------------
            var off = ModelledRun(seed, room: false, income: false, StepAlignedChunkings[0]);
            Assert.False(off.Room);
            Assert.False(off.Income);
            Assert.False(off.Record.HasRoomScore);
            Assert.Equal(0, off.Record.RoomScore);
            Assert.False(off.Record.HasIncomeEstimate);
            Assert.Equal(0, off.Record.EstimatedDailyIncome);
            Assert.Equal(OffscreenSimulator.NoPaydayHour, off.Record.PaydayHour);
            Assert.Equal(0, off.Record.EstimatedPaydays);
            Assert.Equal(0L, off.Record.EstimatedIncomePaid);

            //And the two off halves are the same run: neither model was asked for, so there is no
            //way to tell which one "off" referred to, which is the identity the default promises.
            Assert.Equal(Describe(off.Motives), Describe(ModelledRun(
                seed, room: false, income: false, StepAlignedChunkings[0]).Motives));
            Assert.Equal(Describe(off.Motives), Describe(ModelledRun(
                seed, room: false, income: true, StepAlignedChunkings[0]).Motives));

            //Turning both models on moves exactly one slot and nothing else: the room score, which
            //the engine adds to the mood sum and reads from nowhere else. Every decaying motive,
            //and therefore every rate and every accumulator, is the off run's - which is the whole
            //of "with it off every other number this type produces is the number it produced before
            //the model existed", stated as an equality rather than as a flag.
            var both = ModelledRun(seed, room: true, income: true, StepAlignedChunkings[0]);
            Assert.Equal(Decaying(off.Motives), Decaying(both.Motives));
            Assert.NotEqual(off.Motives[(int)VMMotive.Room], both.Motives[(int)VMMotive.Room]);

            //--- on: bounded, deterministic, and frame-rate independent ---------------------------
            //The frame patterns here all land on a whole number of decay steps - a coarse step is
            //half an hour of game time and fifteen game hours is thirty of them, so 1, 2, 3, 5 and
            //15 frames each carry a whole number of them. That is not a convenience: a frame
            //*shorter* than a step splits one step's game hour across two frames, and the payday
            //rule counts distinct hours per call, so the same household can be paid twice for one
            //hour. That bound is asserted separately and honestly below rather than hidden by
            //choosing only the comfortable chunkings.
            var runs = new List<ModelRun>();
            foreach (var chunks in StepAlignedChunkings)
            {
                var run = ModelledRun(seed, room: true, income: true, chunks);
                runs.Add(run);
                Assert.True(run.Record.HasRoomScore, chunks + " frame(s) modelled no room score");
                Assert.True(run.Record.HasIncomeEstimate, chunks + " frame(s) modelled no income");
            }

            var first = runs[0];
            //The room score is the engine's own arithmetic on the engine's own bound, so it lands
            //inside -100..100 and nowhere else, and it is reachable from the Sim's own motive
            //table because that is the only place the engine reads one from.
            Assert.InRange(first.Record.RoomScore, VMRoomScore.Min, VMRoomScore.Max);
            Assert.Equal(first.Record.RoomScore, first.RoomSlot);

            //The income is a rate and never a balance: bounded at both ends, and the running total
            //is the product of the rate and the payday count, computed on read. There is no second
            //ledger here to disagree with anything.
            Assert.InRange(first.Record.EstimatedDailyIncome,
                OffscreenSimulator.MinEarnerDailyIncome, OffscreenSimulator.MaxEstimatedDailyIncome);
            //The rate is keyed on the family the stored Sims named, and the running total is the
            //product of the rate and the payday count - so there is no stored balance that could
            //drift away from the rate that produced it, and nothing here to reconcile.
            Assert.NotEqual(OffscreenSimulator.NoFamilyNumber, first.Record.FamilyNumber);
            Assert.Equal((long)first.Record.EstimatedDailyIncome * first.Record.EstimatedPaydays,
                first.Record.EstimatedIncomePaid);
            Assert.InRange(first.Record.PaydayHour, 0, OffscreenSimulator.HoursPerGameDay - 1);

            //Fifteen game hours in three frame patterns, and one household's whole modelled answer
            //is the same in all of them. A frame rate is not a save file, so it must not be a fact
            //about a neighbour's evening either.
            for (int i = 1; i < runs.Count; i++)
            {
                Assert.Equal(first.Record.RoomScore, runs[i].Record.RoomScore);
                Assert.Equal(first.Record.EstimatedDailyIncome, runs[i].Record.EstimatedDailyIncome);
                Assert.Equal(first.Record.PaydayHour, runs[i].Record.PaydayHour);
                Assert.Equal(first.Record.EstimatedPaydays, runs[i].Record.EstimatedPaydays);
                Assert.True(first.Record.SameAs(runs[i].Record),
                    StepAlignedChunkings[i] + " frame(s): " + first.Record + " vs " + runs[i].Record);
                Assert.Equal(Decaying(first.Motives), Decaying(runs[i].Motives));
                Assert.Equal(first.RoomSlot, runs[i].RoomSlot);
            }

            //The same fifteen hours in sixty frames - a quarter of an hour each, half a decay step
            //- and the honest answer is not "identical". The room score, the rate and the payday
            //hour are still the same numbers, because each is drawn once per lot; the *count* of
            //paydays can be one higher, because the hour a step falls in was counted by two frames
            //rather than one. One extra payday in fifteen game hours is the size of the error, and
            //it is bounded by the number of frames rather than growing with them - which is the
            //distinction that matters: a rate that is a function of frame rate, and a count that is
            //off by at most one frame's worth.
            var split = ModelledRun(seed, room: true, income: true, 60);
            Assert.Equal(first.Record.RoomScore, split.Record.RoomScore);
