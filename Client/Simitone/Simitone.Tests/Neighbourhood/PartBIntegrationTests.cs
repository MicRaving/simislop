        /// <summary>
        /// Fifteen game hours in real seconds: 05:30 to half past eight in the evening, which
        /// is the far side of the residential visiting window and after sunset. Long enough
        /// that the walk crosses a weather segment boundary and every hour band, and short
        /// enough to stay under the world's own per-call budget (ten game hours) in every
        /// chunking the tests use.
        /// </summary>
        private static readonly double FifteenGameHours = 15 * 60 * OffscreenSimulator.GameMinutesPerRealSecond;

        /// <summary>
        /// Frame counts that divide fifteen game hours exactly - 300, 60 and 15 real seconds a
        /// frame - so two runs of the same total are the same number of clock ticks and what
        /// is compared between them is the arrival rather than the truncation of a partial
        /// frame. Stated here rather than written as 900 divided by each test's divisor so
        /// that the numbers being wrong is visible in one place.
        /// </summary>
        private static readonly int[] EveningChunkings = { 3, 15, 60 };

        /// <summary>
        /// A world walked to half past eight in the evening in <paramref name="chunks"/> frames,
        /// with the B1 capability on so the world builds and re-reads <em>its own</em> features
        /// object on each of them. The world is the seam here: it holds the clock, it holds the
        /// seed, and it is the thing that decides when its own B8 state is stale, so a test that
        /// constructed a features object beside it would be testing a bystander.
        /// </summary>
        private static SimitoneNeighbourhoodWorld EveningWorld(long seed, int chunks)
        {
            var world = WorldWithSeed(seed);
            world.Clock.SeedFromGlobalState(GameGlobals());

            for (int frame = 0; frame < chunks; frame++)
            {
                Assert.True(world.Tick(FifteenGameHours / chunks));
            }
            return world;
        }

        [Fact]
        public void TheWorldsLightAndWeatherAreAPureFunctionOfTheClockItActuallyKeeps()
        {
            //B8 through the world, over its own tick rather than over a throwaway clock, because
            //the claims are about the seam and not about the arithmetic: the world holds the
            //clock, the seed and one features object, it re-reads that object on the frames that
            //moved something, and the drawable answer is computed from it on read. The three runs
            //below are the same fifteen game hours in three frame patterns, a fourth in a
            //decomposition none of them uses, and a fifth under another seed, so "which frames
            //carried the hours" and "which neighbourhood this is" both stop being facts.
            NeighbourhoodWorldFlags.Reset();
            NeighbourhoodWorldFlags.Set(NeighbourhoodWorldFlag.World, true, save: false);
            Assert.True(NeighbourhoodWorldFlags.IsOn(NeighbourhoodWorldFlag.World));
            Assert.False(NeighbourhoodWorldFlags.IsOn(NeighbourhoodWorldFlag.Offscreen),
                "this test is about the clock-only path, so the off-screen capability has to be off");

            var seed = WorldSeed();
            var worlds = new List<SimitoneNeighbourhoodWorld>();
            foreach (var chunks in EveningChunkings)
            {
                worlds.Add(EveningWorld(seed, chunks));
            }

            //Half past eight, and dark: the run really did arrive where it was told to, and the
            //world arrived there on its own - it re-read its features on every frame that moved
            //the clock, so nothing had to be told twice.
            var first = worlds[0];
            Assert.Equal(20, first.Lighting.TimeOfDay.Hour);
            Assert.Equal(30, first.Lighting.TimeOfDay.Minute);
            Assert.Equal(WorldDayPhase.Night, first.Features.DayPhase);
            Assert.True(first.Features.IsNight);
            Assert.Equal((long)EveningChunkings[0], first.FeatureTicks);
            Assert.True(first.HasFeatures);
            Assert.Same(first.Features, first.Features);

            //One features object, holding the world's own clock and layout: three references
            //rather than three copies, which is the reason a lot and the street can never be on
            //different clocks.
            Assert.Same(first.Clock, first.Features.Clock);
            Assert.Same(first.Layout, first.Features.Layout);
            Assert.Equal((long)first.Seed, first.Features.WorldSeed);

            //A pure function of the state, and the statics are the only other statement about the
            //light and the weather that exists: read both at the same instant, on every run, and
            //the world's cached answer agrees with them field for field. Were the world caching
            //something of its own - a rate, a segment index, a frame counter - this is where it
            //would first disagree, and it would disagree with itself between two runs that ended
            //on the same tick.
            var expectedTicks = 15L * 60 * WorldClock.TicksPerMinuteTs1;
            for (int i = 0; i < worlds.Count; i++)
            {
                var world = worlds[i];
                Assert.Equal(expectedTicks, world.Clock.Ticks);
                Assert.Equal(20, world.Lighting.TimeOfDay.Hour);
                Assert.Equal(WorldLightingState.FromClock(world.Clock), world.Lighting);
                Assert.Equal(WorldWeather.At(seed, world.Clock), world.Weather);
                AssertSameVisitors(
                    NeighbourhoodWorldFeatures.VisitorsAt(world.Clock, seed, world.Layout),
                    world.Visitors, "run " + EveningChunkings[i]);
            }

            //And all three runs are the same run: the light, the weather, the company and the
            //drawable answer, in three frame patterns. A frame rate is not a save file, so it
            //must not be a fact about a neighbourhood's evening either.
            for (int i = 1; i < worlds.Count; i++)
            {
                Assert.Equal(first.Lighting, worlds[i].Lighting);
                Assert.Equal(first.Weather, worlds[i].Weather);
                Assert.Equal(first.CurrentLighting, worlds[i].CurrentLighting);
                Assert.Equal(first.Visitors.Count, worlds[i].Visitors.Count);
                for (int v = 0; v < first.Visitors.Count; v++)
                {
                    Assert.Equal(first.Visitors[v], worlds[i].Visitors[v]);
                }
            }

            //The drawable answer is a pure function of the two values above, computed on read and
            //cached nowhere, so a renderer can ask for it every frame and a caller cannot be
            //holding a second copy that has gone stale behind the world's back.
            var drawn = first.CurrentLighting;
            Assert.Equal(drawn, first.CurrentLighting);
            Assert.Equal(drawn, NeighbourhoodWorldLighting.From(first.Lighting, first.Weather));
            Assert.False(drawn.IsSunUp, "half past eight in the evening has no sun up: " + drawn);

            //The fourth run is the same neighbourhood under the same seed, arrived at in forty-
            //five frames of twenty seconds - a decomposition that is in none of the three above
            //and divides the fifteen hours exactly - and the fifth is a neighbourhood one seed
            //over walked the same way. Same seed, same evening: which is the whole of what
            //"deterministic by seed" has to mean for a neighbourhood a player comes back to.
            var twin = EveningWorld(seed, 45);
            Assert.Equal(expectedTicks, twin.Clock.Ticks);
            Assert.Equal(first.Lighting, twin.Lighting);
            Assert.Equal(first.Weather, twin.Weather);
            Assert.Equal(drawn, twin.CurrentLighting);
            AssertSameVisitors(first.Visitors, twin.Visitors, "the same seed, 45 frames");

            var other = EveningWorld(seed + 1, 60);
            Assert.NotEqual(twin.Seed, other.Seed);
            Assert.Equal(twin.Clock.Ticks, other.Clock.Ticks);

            //The seed is what makes the weather a neighbourhood's; it must not be what makes the
            //sun come up, and it must be what makes one neighbourhood rain where another does not
            //- including in what a lot view is handed to draw with, which is where the weather is
            //finally folded in.
            Assert.Equal(first.Lighting, other.Lighting);
            Assert.NotEqual(first.Weather, other.Weather);
            Assert.Equal(drawn.IsSunUp, other.CurrentLighting.IsSunUp);

            //--- and with the capability off, nothing is built -----------------------------------
            //The switch, at the branch. With B1 off the world's tick is the clock-only path and
            //its features object is never built: the clock still moves - off means the previous
            //stage's behaviour, not a stopped world - and every B8 reader answers "nothing
            //derived yet" without that reading being the thing that built one.
            NeighbourhoodWorldFlags.Set(NeighbourhoodWorldFlag.World, false, save: false);
            var off = World(true);
            off.Clock.SeedFromGlobalState(GameGlobals());
            Assert.False(off.HasFeatures);
            for (int i = 0; i < 8; i++) Assert.True(off.Tick(EightGameHours / 8));

            Assert.Equal(13, off.Clock.Hours);
            Assert.False(off.HasFeatures);
            Assert.Equal(0L, off.FeatureTicks);
            Assert.Equal(default(WorldLightingState), off.Lighting);
            Assert.Equal(default(WorldWeather), off.Weather);
            Assert.Empty(off.Visitors);
            Assert.Equal(default(NeighbourhoodWorldLighting), off.CurrentLighting);
            Assert.Null(off.LastOffscreenTick);

            //The off-screen object is not built either: asking whether a lot has a record reads
            //a field rather than building a simulator, and the simulator the property hands back
            //on demand is an empty one - so "the flag is off and a neighbour moved" is not a
            //state this world can be reached in.
            for (int i = 0; i < off.LotCount; i++)
            {
                OffscreenLotRecord none;
                Assert.False(off.TryGetOffscreenRecord(off.Lots[i].Number, out none));
                Assert.Null(none);
            }
            Assert.Equal(0, off.Offscreen.RecordCount);

            //And asking the adapter for a world's defaults is an answer rather than an exception,
            //so a screen can read the first frame of a lot load and gate on the flag itself.
            //What it gets is "no cloud, no rain, no fog to speak of" - a clear sky, which is a
            //real state and a different one from a real evening.
            var nothing = NeighbourhoodWorldLighting.From(default(WorldLightingState),
                default(WorldWeather));
            Assert.Equal(nothing, NeighbourhoodWorldLighting.From(default(WorldLightingState),
                default(WorldWeather)));

            //The distinction a renderer gates on: a world that has derived nothing answers with
            //the zeroed value, and the adapter asked with nothing to fold in answers with a clear
            //sky. They are two different "no", and neither is the other one by accident.
            Assert.Equal(default(NeighbourhoodWorldLighting), off.CurrentLighting);
            Assert.NotEqual(drawn, nothing);
            //Fog shortens the view, so the clear-sky default is the furthest of the two and
            //the evening's own number is inside the published range whatever its weather is.

            //And with the world itself switched off there is no clock to read at all, which is
            //the last state the three gates can be in.
            var dead = World(false);
            dead.Clock.SeedFromGlobalState(GameGlobals());
            var frozen = dead.Features;
            var frozenReading = frozen.Lighting;
            Assert.False(dead.Tick(600.0));
            Assert.Equal(0L, dead.Clock.Ticks);
            Assert.Equal(0L, dead.FeatureTicks);
            Assert.Equal(frozenReading, dead.Lighting);
        }

