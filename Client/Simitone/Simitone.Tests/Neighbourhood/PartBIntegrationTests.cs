            Assert.True(world.Transit.Active[0].IsComplete);
        }

        [Fact]
        public void APreservedSnapshotIsPlayedExactlyOnceAndTheNextVisitReadsTheDisk()
        {
            //Precedence and consume-once together, across the seam, on the walk that makes them both
            //visible: an in-session snapshot always outranks the lot's own file, and it is dropped
            //as it is played so the next visit plays the snapshot taken at the latest departure
            //rather than replaying the one from the first.
            var world = World();
            var home = world.Lots[0].Number;
            var neighbour = world.Lots[1].Number;

            var homeState = new VMMarshal();
            world.SetActiveLotWith(home, homeState);
            var host = new WorldBackedTravelHost(world, home);
            var service = new LotTravelService();

            string reason;
            Assert.True(service.TryTransition(host,
                new LotTransitionRequest(neighbour, TransitionReason.Picker), out reason), reason);

            //the first visit to a lot reads its own file: nothing has been stored for it
            Assert.Equal(1, CountOf(host.Calls, "load-file:" + neighbour));
            Assert.DoesNotContain("load-state:" + neighbour, host.Calls);

            host.CurrentHouseId = neighbour;
            Assert.True(service.TryTransition(host,
                new LotTransitionRequest(home, TransitionReason.Picker), out reason), reason);

            //home's snapshot is played, and consumed before the load, so a load that failed cannot
            //leave a spent snapshot behind to be replayed on the next visit
            Assert.True(IndexOf(host.Calls, "remove:" + home) < IndexOf(host.Calls, "load-state:" + home),
                string.Join(", ", host.Calls));
            Assert.Same(homeState, host.LastLoadedMarshal);
            Assert.Contains("resumed preserved state", reason);
            Assert.Equal(NeighbourhoodLotState.Unloaded, world.LotStore.StateOf(home));

            host.CurrentHouseId = home;
            Assert.True(service.TryTransition(host,
                new LotTransitionRequest(neighbour, TransitionReason.MoveIn), out reason), reason);

            //the neighbour's own snapshot - taken when the player walked out of it - now outranks its
            //house file, which is the precedence rule both halves of TravelSave depend on
            Assert.Equal(1, CountOf(host.Calls, "load-file:" + neighbour));
            Assert.Contains("load-state:" + neighbour, host.Calls);
            Assert.True(IndexOf(host.Calls, "remove:" + neighbour)
                < IndexOf(host.Calls, "load-state:" + neighbour), string.Join(", ", host.Calls));
            Assert.Contains("resumed preserved state", reason);

            //Three switches: one from disk and two from memory, and every resume consumed exactly once -
            //a store that kept its entries would be replaying the state a lot was in two visits
            //ago, which is a lot that silently undoes everything the player did in it.
            Assert.Equal(1, CountOf(host.Calls, "load-state:" + home));
            Assert.Equal(1, CountOf(host.Calls, "load-state:" + neighbour));
            foreach (var call in host.Calls)
            {
                if (!call.StartsWith("load-state:", StringComparison.Ordinal)) continue;
                var lot = call.Substring("load-state:".Length);
                Assert.Equal(1, CountOf(host.Calls, "remove:" + lot));
                Assert.True(IndexOf(host.Calls, "remove:" + lot) < IndexOf(host.Calls, call),
                    "the snapshot for lot " + lot + " was played before it was consumed: "
                    + string.Join(", ", host.Calls));
            }

            //and the store holds nothing for the lot the player is standing in
            Assert.Equal(NeighbourhoodLotState.Unloaded, world.LotStore.StateOf(neighbour));

            //a request that names no lot is refused before the host is touched, so the player stays
            //where they were rather than being left half-switched
            var calls = host.Calls.Count;
            Assert.False(service.TryTransition(host,
                new LotTransitionRequest(99, TransitionReason.Picker), out reason));
            Assert.Equal(calls, host.Calls.Count);
            Assert.Contains("99", reason);
            Assert.Equal(neighbour, world.ActiveLotNumber);
        }

