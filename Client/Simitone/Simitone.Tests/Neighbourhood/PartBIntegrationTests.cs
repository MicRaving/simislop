        /// <summary>
        /// Everything one run of the two opt-in models answered with. The motive table and the
        /// room slot are read off the stored marshal rather than off the record, because the
        /// marshal is where the engine reads both from and a record could agree with itself about
        /// a number nobody would ever see.
        /// </summary>
        private sealed class ModelRun
        {
            public bool Room;
            public bool Income;
            public short[] Motives;
            public short RoomSlot;
            public OffscreenLotRecord Record;
        }

        /// <summary>
        /// Fifteen game hours of one world with the two models as the caller asked for them,
        /// carried in <paramref name="chunks"/> frames of the world's own tick. The world is the
        /// seam: it holds the clock, the seed and the store, so the flags are read where the screen
        /// reads them rather than at a call site the test owns.
        /// </summary>
        private static ModelRun ModelledRun(long seed, bool room, bool income, int chunks)
        {
            NeighbourhoodWorldFlags.Reset();
            NeighbourhoodWorldFlags.Set(NeighbourhoodWorldFlag.World, true, save: false);
            NeighbourhoodWorldFlags.Set(NeighbourhoodWorldFlag.Offscreen, true, save: false);

            var world = WorldWithSeed(seed);
            world.Offscreen.ModelsRoomScore = room;
            world.Offscreen.EstimatesHouseholdIncome = income;

            var lot = world.Lots[1].Number;
            var marshal = WorkingMarshal(Family: 7, JobType: 3, Promotion: 4);
            world.LotStore.SetActive(lot, marshal);
            //The lot the player is standing in, stamped the way the world's own tick stamps it -
            //which is what keeps the fixture from testing itself.
            world.SetActiveLot(world.Lots[0].Number);

            for (int frame = 0; frame < chunks; frame++)
            {
                Assert.True(world.Tick(FifteenGameHours / chunks), "a modelled frame moved nothing");
            }

            var run = new ModelRun
            {
                Room = room,
                Income = income,
                Motives = MotivesOf(marshal),
                Record = RecordOf(world)
            };
            run.RoomSlot = Motives(marshal)[(int)VMMotive.Room];
            return run;
        }

        /// <summary>One Sim's motive table, read fresh so a run cannot be compared with itself.</summary>
        private static short[] Motives(VMMarshal marshal)
        {
            return MotivesOf(marshal);
        }

        /// <summary>
        /// The seven decaying motives, as one comparable line. Deliberately not the whole table:
        /// the room model writes <see cref="VMMotive.Room"/> and moves mood, so a comparison over
        /// all sixteen slots would be asserting the model had no effect at all - which is the one
        /// thing it is allowed to do.
        /// </summary>
        private static string Decaying(short[] motives)
        {
            var parts = new string[OffscreenLotRecord.MotiveCount];
            var order = VMTS1MotiveDecay.DecrementMotives;
            for (int i = 0; i < OffscreenLotRecord.MotiveCount; i++)
            {
                parts[i] = motives[(int)order[i]].ToString();
            }
            return string.Join(",", parts);
        }

        // ====================================================================================
        // Wave 9. The four decisions a live neighbourhood now makes that no milestone suite can
        // reach, asked of the same real generated map the rest of this file builds over.
        //
        // The seams here are not "which lots are real" any more - that was B2 and it is still
        // pinned above. They are the four things that sit *behind* that answer and decide what a
        // player actually sees standing in the street:
        //
        //   - the hollow loader, which is the only thing that turns a generated neighbourhood's
        //     never-visited lots from blank plots into the houses their HouseNN.iff describes;
        //   - the alignment invariant, which is a sub-world's own street and the surround's
        //     street landing on the same world tiles rather than on two parallel ones;
        //   - the full-region coverage claim: every lot the surround draws ground for is a real
        //     lot, and the budget is what says so out loud when it is not;
        //   - the raster cache, which makes the second *launch* of a neighbourhood as cheap as
        //     the second visit - and the LOD rule, which is the other half of "the whole map
        //     stays drawable at every zoom".
        //
        // What none of the four can be asked about is the pass that actually reads a house file
        // (a graphics device, a content manager and a running VM), the GPU upload of a level of
        // detail, and the draw that submits it. Each of those is named where it arises rather
        // than faked; what is asserted is that the decision each of them would have to make is
        // already made, and made twice, by the pure types above it.
        // ====================================================================================

        // ============================ the hollow loader (real neighbour contents) ==============

        /// <summary>
        /// A plan over the fixture's real map whose store holds nothing, which is the state a
        /// generated neighbourhood is in the first time a player stands in it: nobody has entered
        /// any of those lots, so §5.3's store is empty and every neighbour arrives blank.
        ///
        /// <para>
        /// Built at the <em>shipped</em> radius rather than this file's fixture-wide
        /// <see cref="Radius"/>. The Wave 9 claims are about what a player gets, and a claim
        /// measured at a radius the screen does not use would be a claim about a neighbourhood
        /// nobody opens - wider here only means the test reaches further than the product does.
        /// </para>
        /// </summary>
        private static SimitoneSurroundingsPlan PlanWithNoContents(SimitoneNeighbourhoodWorld world,
            int lotNumber, int radius = SimitoneSurroundingsPlan.DefaultSubWorldRadiusTiles)
        {
            return PlanFor(world, lotNumber, radius);
        }

        /// <summary>
        /// A lot with a house file's fingerprint on it, which is what a lot whose
        /// <c>HouseNN.iff</c> has actually been read carries. The fixture's layouts come from
        /// <see cref="NeighbourhoodMapAdapter.DescribeInput"/>, which builds them from the
        /// generator's own input and never reads a house file - so its lots carry a hash of zero,
        /// and a hash of zero is precisely the state
        /// <see cref="NeighbourHollowLoader.BuildRefusalFor"/> refuses: there is nothing to stand a
        /// world up for and nothing to key a cache entry on. Stamping one here is the difference
        /// between "a lot the loader would refuse" and "a lot the loader would be asked about", and
        /// it is the second of those the loader's rules are about.
        /// </summary>
        private static NeighbourhoodLot Fingerprinted(NeighbourhoodLot lot, uint hash)
        {
            var copy = CopyLot(lot);
            copy.HouseHash = hash;
            return copy;
        }

        /// <summary>Any non-zero fingerprint, for a test that only needs the lot to be buildable.</summary>
        private const uint AnyHouseHash = 0x5EA1ED01u;

        [Fact]
        public void EveryLotTheStoreCannotAnswerForIsOneTheLoaderIsAskedAboutAndNobodyElseIs()
        {
            //The seam between the plan and the loader, and the whole of why "0 hollow, 3 blank"
            //stopped being the end of the story. A generated neighbourhood's lots have been visited
            //by nobody, so the store holds no marshals and every neighbour is a bare plot; the
            //contents are in each lot's own HouseNN.iff and reading them out is a whole
            // <c>World</c> and a whole <c>VM</c> per lot. So the question is not "can this be
            //built" but "is this worth a world", and
            // <see cref="SimitoneSurroundingsPlan.NeedsHollows"/> is the one place that is asked.
            //
            //Three states, over the same map and the same plan, so the only thing that differs is
            //what the store holds.
            var world = World();
            var active = world.Lots[0].Number;

            //--- an empty store: the ordinary case, and it must ask ---------------------------------
            var plan = PlanWithNoContents(world, active);
            Assert.True(plan.IsValid, plan.Failure);
            Assert.NotEmpty(plan.Neighbours);
            Assert.Equal(0, plan.HollowCount);
            Assert.True(plan.NeedsHollows(),
                "a neighbourhood nobody has visited is exactly the case the loader exists for");

            //Every neighbour is one it would be asked about, and each refusal is a lot the plan
            //itself can name - not the lot the player is standing in, and not a lot the map cannot
            //answer for.
            foreach (var neighbour in plan.Neighbours)
            {
                Assert.True(neighbour.IsValid, neighbour.Describe());
                Assert.False(neighbour.IsHollow, neighbour.Describe());
                //The fixture's layouts carry no house-file fingerprint, so the lot is stamped with
                //one first - see <see cref="Fingerprinted"/>. Without it this would be asserting
                //about the wrong state: a zero hash is a refusal, not a build.
                var buildable = Fingerprinted(neighbour.Lot, AnyHouseHash);
                Assert.True(NeighbourHollowLoader.BuildRefusalFor(buildable) == null,
                    "a planned neighbour the loader would refuse: " + neighbour.Describe());
                Assert.True(NeighbourHollowLoader.NeedsBuild(buildable, null));
                //And the un-stamped lot really is refused, which is the other half of the same rule
                //and the one a hand-written layout runs into.
                Assert.Contains("fingerprint",
                    NeighbourHollowLoader.BuildRefusalFor(neighbour.Lot), StringComparison.Ordinal);
            }
            //And the lot the player is standing in is never one of them, so the loader is never
            //asked to stand a world up for the lot the lot view is already drawing.
            Assert.False(plan.Contains(active));

            //--- a store that holds one: the loader is asked about the rest, and the one it is
            //    not asked about is already hollow, so asking would buy nothing --------------------
            var stocked = plan.NeighbourNumbers[0];
            var marshal = new VMHollowMarshal();
            world.LotStore.SetHollow(stocked, marshal);

            var restocked = PlanWithNoContents(world, active);
            Assert.Equal(plan.NeighbourNumbers, restocked.NeighbourNumbers);
            Assert.Equal(1, restocked.HollowCount);
            Assert.True(restocked.NeedsHollows(), "the other lots still have no contents anywhere");

            var filled = restocked.WithHollows(new Dictionary<short, VMHollowMarshal>
            {
                { restocked.NeighbourNumbers[1], marshal }
            });

            //Two of three, and the plan still needs the third: which is the whole point of the
            //loop, and the reason the loader is called once per lot load rather than once ever.
            Assert.Equal(2, filled.HollowCount);
            Assert.True(filled.NeedsHollows());
            Assert.Equal(3, filled.Neighbours.Count);
            Assert.Same(marshal, filled.NeighbourFor(stocked).Hollow);
            Assert.Same(marshal, filled.NeighbourFor(filled.NeighbourNumbers[1]).Hollow);

            //--- a store that holds all of them: the loader is never constructed -------------------
            var all = new Dictionary<short, VMHollowMarshal>();
            for (int i = 0; i < plan.NeighbourNumbers.Count; i++)
            {
                all[plan.NeighbourNumbers[i]] = marshal;
            }
            var complete = restocked.WithHollows(all);
            Assert.Equal(plan.Neighbours.Count, complete.HollowCount);
            Assert.False(complete.NeedsHollows(),
                "a plan whose neighbours the store already holds marshals for must not reach for a "
                + "loader at all: that is a World and a VM per lot for a marshals dictionary lookup");

            //And the plan itself is unchanged by any of it: a plan is a value, and
            //<c>WithHollows</c> returns a copy rather than revising the one it was given.
            Assert.Equal(1, restocked.HollowCount);
            Assert.Equal(0, plan.HollowCount);
            Assert.Equal(plan.NeighbourNumbers, complete.NeighbourNumbers);
        }

