            Assert.True(store.TryGetActive(resident, out stillResident));
            Assert.NotNull(stillResident);
            //and the neighbour's own contents were not disturbed by the refusal
            Assert.True(store.TryGetHollow(lot, out held));
            Assert.Same(marshal, held);

            //A null store is not something to publish into, and a null marshal is nothing to publish.
