            Assert.NotEqual(NeighbourhoodRasterCache.LayoutHash(layout),
                NeighbourhoodRasterCache.LayoutHash(repacked));
            Assert.False(NeighbourhoodRasterCache.TryDeserialize(again, repacked, out refused, out why));
            Assert.Null(refused);
            Assert.Contains("arrangement", why);

            //5. nothing to check it against: a raster with no layout is a raster nobody may use
            Assert.False(NeighbourhoodRasterCache.TryDeserialize(again, null, out refused, out why));
            Assert.Null(refused);
            Assert.Contains("no layout", why);

            //--- and a file that is damaged, in the three ways a file can be ------------------------
            //Empty, and truncated: the cheapest checks and the most damning.
            Assert.False(NeighbourhoodRasterCache.TryDeserialize(
                null, layout, out refused, out why));
            Assert.Contains("empty", why);
            Assert.False(NeighbourhoodRasterCache.TryDeserialize(
                new byte[8], layout, out refused, out why));
            Assert.Contains("truncated", why);
            //A header that is not a raster at all.
            var notRaster = (byte[])again.Clone();
            notRaster[NeighbourhoodRasterCache.MagicOffset] = (byte)'X';
            Assert.False(NeighbourhoodRasterCache.TryDeserialize(notRaster, layout, out refused, out why));
            Assert.Contains("not a generated-map raster", why);
            //A build that does not know the shape must not go on to interpret the shape, so the
            //version comes before anything is believed.
            var future = (byte[])again.Clone();
            future[NeighbourhoodRasterCache.VersionOffset + 3] = 99;
            Assert.False(NeighbourhoodRasterCache.TryDeserialize(future, layout, out refused, out why));
            Assert.Contains("format version", why);
            //A header that disagrees with itself: a 96-wide map stamped as a 512 one.
            var mismatched = (byte[])again.Clone();
            WriteInt32(mismatched, NeighbourhoodRasterCache.WidthOffset, 8);
            Assert.False(NeighbourhoodRasterCache.TryDeserialize(mismatched, layout, out refused, out why));
            Assert.Contains("stamps its size as", why);
            //A payload count that is not what a map of that size holds.
            var lying = (byte[])again.Clone();
            WriteInt64(lying, NeighbourhoodRasterCache.PayloadOffset, 1234);
            Assert.False(NeighbourhoodRasterCache.TryDeserialize(lying, layout, out refused, out why));
            Assert.Contains("bytes of map", why);
            //Truncated from the end, which the length check catches before a byte is read.
            var short1 = new byte[again.Length - 16];
            Array.Copy(again, short1, short1.Length);
            Assert.False(NeighbourhoodRasterCache.TryDeserialize(short1, layout, out refused, out why));
            Assert.Contains("its own header describes", why);
            //The right length and the wrong content: the case a length check cannot see, and the one
            //a half-trusted map would come from.
            var scribbled = (byte[])again.Clone();
            scribbled[NeighbourhoodRasterCache.HeaderSize + 7] ^= 0xFF;
            Assert.False(NeighbourhoodRasterCache.TryDeserialize(
                scribbled, layout, out refused, out why));
            Assert.Contains("checksum", why);

            //Every one of them says so, and none of them throws - a cache file is the one place in
            //this pipeline where a bad byte must be indistinguishable from no file at all.
            Assert.NotNull(why);
            Assert.False(string.IsNullOrWhiteSpace(why));

            //--- the file level, which is the same contract as the layout sidecar's -----------------
            //A slot with no file is not a warning; a file this build will not stand behind is a
            //warning and a null. Both mean exactly one thing: generate the map again.
            Assert.Null(NeighbourhoodRasterCache.Load(_root, layout.Slot,
                CopyWith(layout, seed: layout.Seed + 7)));
            Assert.Null(NeighbourhoodRasterCache.Load(null, layout.Slot, layout));
            Assert.Null(NeighbourhoodRasterCache.Load(_root, 99, layout));

            //--- the refusals on the way out are refusals, not exceptions ---------------------------
            Assert.False(NeighbourhoodRasterCache.Save(_root, null, map));
            Assert.False(NeighbourhoodRasterCache.Save(_root, layout, null));
            Assert.False(NeighbourhoodRasterCache.Save(null, layout, map));
            //A map that is not the layout's size is not written at all: it would be refused by
            //every later read, so storing it would buy nothing and cost three megabytes.
            var wrongSize = NeighbourhoodMap.Create(layout.MapSize + 8);
            Assert.False(NeighbourhoodRasterCache.Save(_root, layout, wrongSize));
            //And the serialiser refuses rather than wrapping.
            Assert.Throws<ArgumentNullException>(() => NeighbourhoodRasterCache.Serialize(null, map));
            Assert.Throws<ArgumentNullException>(() => NeighbourhoodRasterCache.Serialize(layout, null));
        }

        [Fact]
        public void TheRasterStampMovesForTheArrangementAndNotForAFieldTheGeneratorNeverReads()
        {
            //<see cref="NeighbourhoodRasterCache.LayoutHash"/> on its own, because the choice it
            //makes is the difference between a cache that works and one that is never a hit. It
            //hashes the *generator's own input* rather than the layout, because the input is what
            //the raster depends on: hashing the whole layout would invalidate the file for a field
            //the generator never reads - a lot's map-bitmap position, its rotation, the session a
            //save stamped on it - and each of those would cost a regeneration to produce
            //byte-identical tiles.
            var world = World();
            var layout = world.Layout;
            var baseline = NeighbourhoodRasterCache.LayoutHash(layout);
            Assert.NotEqual(0UL, baseline);
            Assert.Equal(0UL, NeighbourhoodRasterCache.LayoutHash(null));
            //Pure: asked twice it is the same number, and asked of a layout that was not mutated
            //it is the same number again.
            Assert.Equal(baseline, NeighbourhoodRasterCache.LayoutHash(layout));

            var one = layout.Lots[0];

            //--- fields the generator reads: the stamp moves ---------------------------------------
            //Every one of these changes the tiles, and each is a field of a lot record the
            //generator's input carries, so a change must cost a regeneration.
            var mutations = new List<NeighbourhoodLot>
            {
                With(one, l => l.WorldX = l.WorldX + 2),
                With(one, l => l.WorldY = l.WorldY + 2),
                With(one, l => l.Size = l.Size + 8),
                With(one, l => l.Zone = LotZoning.ZoneCommunity),
                With(one, l => l.TerrainType = l.TerrainType == TerrainType.GRASS
                    ? TerrainType.SAND : TerrainType.GRASS),
                With(one, l => l.BaseHeight = (short)(l.BaseHeight + 1)),
                With(one, l => l.DoorSide = l.DoorSide == NeighbourhoodLotSide.East
                    ? NeighbourhoodLotSide.West : NeighbourhoodLotSide.East),
                With(one, l => l.HasHouse = !l.HasHouse),
                With(one, l => l.Number = (short)(l.Number + 1)),
                //and the two the stamp checks on their own rather than through the hash
                With(one, l => { })
            };
            for (int i = 0; i < mutations.Count - 1; i++)
            {
                var changed = Replace(layout, 0, mutations[i]);
                Assert.True(baseline != NeighbourhoodRasterCache.LayoutHash(changed),
                    "lot field " + i + " changes the tiles and did not move the stamp");
            }
            //The last one is a no-op, and its assertion is the other half: an unchanged lot leaves
            //the stamp alone. Without it the nine above would pass against a hash of noise.
            Assert.Equal(baseline,
                NeighbourhoodRasterCache.LayoutHash(Replace(layout, 0, mutations[mutations.Count - 1])));
            //A lot that is not in the layout at all does move it, because the count is hashed.
            Assert.NotEqual(baseline, NeighbourhoodRasterCache.LayoutHash(
                new NeighbourhoodLayout(layout.Slot, layout.Seed, layout.GeneratorVersion,
                    layout.SchemaVersion, layout.MapSize, new List<NeighbourhoodLot>())));

            //--- fields the generator never reads: the stamp does not move -------------------------
            //Each of these is a real field of a real lot record and each would cost a regeneration
            //to produce byte-identical tiles if it were hashed.
            var ignored = new List<NeighbourhoodLot>
            {
                //The neighbourhood bitmap's little map of the lot, and its rotation: the facade and
                //the 2D fallback read both and the generator reads neither.
                With(one, l => { l.MapX = l.MapX + 1; }),
                With(one, l => { l.MapY = l.MapY + 1; }),
                With(one, l => { l.Rotation = (l.Rotation + 1) & 3; }),
                //The house file's own fingerprint: it is the facade cache's key, and the raster is
                //not a function of it - a lot's furniture changing must not cost a regeneration.
                With(one, l => { l.HouseHash = l.HouseHash + 12345u; })
            };
            for (int i = 0; i < ignored.Count; i++)
            {
                //xunit's Equal has no message overload, so the index that failed is named by the
                //loop variable in a comment rather than by a third argument nobody can pass.
                Assert.True(baseline
                        == NeighbourhoodRasterCache.LayoutHash(Replace(layout, 0, ignored[i])),
                    "a field the generator never reads moved the stamp: ignored[" + i + "]");
            }

            //--- and the round trip is the real answer, not the hash -------------------------------
            //The stamp is a claim about the raster, so the last word belongs to the file: two
            //layouts that hash the same serialise to the same bytes, and the map that comes back out
            //of one is the map that went into the other.
            var ignoredCopy = Replace(layout, 0, ignored[3]);
            Assert.Equal(baseline, NeighbourhoodRasterCache.LayoutHash(ignoredCopy));
            Assert.Equal(NeighbourhoodRasterCache.Serialize(layout, world.Map),
                NeighbourhoodRasterCache.Serialize(ignoredCopy, world.Map));
        }

        /// <summary>A copy of a lot record with one field changed.</summary>
        private static NeighbourhoodLot With(NeighbourhoodLot lot, Action<NeighbourhoodLot> change)
        {
            var copy = CopyLot(lot);
            change(copy);
            return copy;
        }

        private static NeighbourhoodLot CopyLot(NeighbourhoodLot lot)
        {
            return new NeighbourhoodLot
            {
                Number = lot.Number,
                WorldX = lot.WorldX,
                WorldY = lot.WorldY,
                Size = lot.Size,
                Zone = lot.Zone,
                TerrainType = lot.TerrainType,
                BaseHeight = lot.BaseHeight,
                DoorSide = lot.DoorSide,
                HasHouse = lot.HasHouse,
                HouseHash = lot.HouseHash,
                MapX = lot.MapX,
                MapY = lot.MapY,
                Rotation = lot.Rotation
            };
        }

        private static NeighbourhoodLayout Replace(
            NeighbourhoodLayout layout, int index, NeighbourhoodLot replacement)
        {
            var lots = new List<NeighbourhoodLot>(layout.Lots);
            lots[index] = replacement;
            return new NeighbourhoodLayout(layout.Slot, layout.Seed, layout.GeneratorVersion,
                layout.SchemaVersion, layout.MapSize, lots);
        }

        /// <summary>
        /// The same layout with one of the three stamp fields changed, for the cases a cache file
        /// must refuse.
        /// </summary>
        private static NeighbourhoodLayout CopyWith(
            NeighbourhoodLayout layout, int? seed = null, int? slot = null,
            int? generatorVersion = null)
        {
            return new NeighbourhoodLayout(slot ?? layout.Slot, seed ?? layout.Seed,
                generatorVersion ?? layout.GeneratorVersion, layout.SchemaVersion,
                layout.MapSize, new List<NeighbourhoodLot>(layout.Lots));
        }

        private static void WriteInt32(byte[] bytes, int offset, int value)
        {
            bytes[offset] = (byte)value;
            bytes[offset + 1] = (byte)(value >> 8);
            bytes[offset + 2] = (byte)(value >> 16);
            bytes[offset + 3] = (byte)(value >> 24);
        }

        private static void WriteInt64(byte[] bytes, int offset, long value)
        {
            WriteInt32(bytes, offset, (int)value);
            WriteInt32(bytes, offset + 4, (int)(value >> 32));
        }

        // ================================ the level of detail (the whole map stays drawable) ======

        [Fact]
        public void TheLevelOfDetailIsChosenByHowMuchOfItSpansTheViewAndTheSelectorHoldsItPastTheLine()
        {
            //Two claims about one rule, and the second is the reason the first is not enough.
            //
            //<see cref="NeighbourhoodMeshLod"/> is a pure function of the view's width, stated in
            //tiles so it needs no device: a whole 512-tile map framed at full screen spans 724 tiles,
            //so the quarter level is chosen; a lot focused at the ordinary zoom spans 483, where the
            //half level is chosen; and anything closer than about 160 tiles gets the full-detail one.
            //That is "the whole map stays drawable at every zoom" as a number rather than a frame
            //time.
            //
            //<see cref="NeighbourhoodMeshLodSelector"/> is what stops it flickering, and the two
            //axes are the part that is easy to get wrong: the factor answers "is the view too wide to
            //afford one quad per tile" and the subdivision answers "is a tile now big enough on screen
            //that one flat quad of it is visible as a flat quad", so a zoom can be sitting on one
            //boundary while nowhere near the other - which is the normal case between 48 and 160
            //tiles across.
            var wholeMap = NeighbourhoodCameraPlacement.VisibleWidthFor(
                NeighbourhoodCityMeshBuilder.MapSize);
            Assert.True(wholeMap > 700f && wholeMap < 730f,
                "the diamond's diagonal is about 724 tiles, and the rule is stated against it");

            //--- the stateless rule, over a zoom sweep in both directions --------------------------
            var quarter = NeighbourhoodMeshLod.ForTilesAcross(wholeMap);
            Assert.Equal(NeighbourhoodMeshLod.Quarter, quarter.Factor);
            Assert.Equal(1, quarter.Subdivisions);
            Assert.False(quarter.IsFull);
            Assert.False(quarter.IsSubdivided);

            //A lot focused at the ordinary 1.5x zoom: the quarter level would give 121 tiles of its
            //own across, which is under the 160 that makes it good enough, and the half gives 241.
            var focused = wholeMap / 1.5f;
            var half = NeighbourhoodMeshLod.ForTilesAcross(focused);
            Assert.Equal(NeighbourhoodMeshLod.Half, half.Factor);
            Assert.Equal(1, half.Subdivisions);

            //And close in, the full-detail level - which is the only one that subdivides, and it
            //subdivides into four by four quads a tile.
            var close = NeighbourhoodMeshLod.ForTilesAcross(NeighbourhoodMeshLod.SubdivTilesAcross - 1f);
            Assert.Equal(NeighbourhoodMeshLod.Full, close.Factor);
            Assert.Equal(NeighbourhoodMeshLod.MaxSubdivisions, close.Subdivisions);
            Assert.True(close.IsFull);
            Assert.True(close.IsSubdivided);
            Assert.Equal(4, NeighbourhoodMeshLod.MaxSubdivisions);

            //The band between 48 and 160 tiles across is where a tile is drawn flat: a five-pixel
            //tile at the 800-wide neighbourhood bitmap, which is exactly how it should be drawn.
            var band = NeighbourhoodMeshLod.ForTilesAcross(
                (NeighbourhoodMeshLod.SubdivTilesAcross + NeighbourhoodMeshLod.MinTilesAcross) / 2f);
            Assert.Equal(NeighbourhoodMeshLod.Full, band.Factor);
            Assert.Equal(1, band.Subdivisions);
            Assert.False(band.IsSubdivided);
            Assert.Equal(48f, NeighbourhoodMeshLod.SubdivTilesAcross);
            Assert.Equal(160f, NeighbourhoodMeshLod.MinTilesAcross);

            //Nonsense in, the finest level out: a camera looking at a fraction of a tile, at nothing
            //at all, or at a width no viewport could produce, must never select a coarse mesh. The
            //seams between coarse blocks are what a close-up view is made of.
            foreach (var nonsense in new[] { 0f, -1f, float.NaN, float.PositiveInfinity,
                float.NegativeInfinity })
            {
                var level = NeighbourhoodMeshLod.ForTilesAcross(nonsense);
                Assert.Equal(NeighbourhoodMeshLod.Full, level.Factor);
                Assert.Equal(NeighbourhoodMeshLod.MaxSubdivisions, level.Subdivisions);
                Assert.Equal(NeighbourhoodMeshLod.MaxSubdivisions,
                    NeighbourhoodMeshLod.SubdivisionsForTilesAcross(nonsense));
            }

            //Monotone in the width, on both axes, over a sweep - and the two axes move in
            //opposite directions, which is the point of having two thresholds. A wider view buys a
            //*coarser* ground (a bigger factor, fewer quads) and loses the *subdivision* (four quads
            //a tile only at close range). Asserting each axis against its own direction is what
            //catches a rule that got one of them the wrong way round, and a rule that is not
            //monotone is not safe to apply every frame.
            var previousFactor = 0;
            var previousSubdiv = int.MaxValue;
            for (float width = 1f; width <= wholeMap * 1.5f; width *= 1.1f)
            {
                var level = NeighbourhoodMeshLod.ForTilesAcross(width);
                Assert.True(level.Factor >= previousFactor,
                    "zooming out to " + width + " tiles bought finer ground");
                Assert.True(level.Subdivisions <= previousSubdiv,
                    "zooming out to " + width + " tiles bought a finer subdivision");
                previousFactor = level.Factor;
                previousSubdiv = level.Subdivisions;
            }
            Assert.Equal(NeighbourhoodMeshLod.Quarter, previousFactor);
            Assert.Equal(1, previousSubdiv);

            //The two axes are read off two thresholds, and neither is derived from the other.
            Assert.Equal(NeighbourhoodMeshLod.MaxSubdivisions,
                NeighbourhoodMeshLod.SubdivisionsForTilesAcross(
                    NeighbourhoodMeshLod.SubdivTilesAcross - 0.01f));
            Assert.Equal(1, NeighbourhoodMeshLod.SubdivisionsForTilesAcross(
                NeighbourhoodMeshLod.SubdivTilesAcross));
            Assert.Equal(NeighbourhoodMeshLod.MaxSubdivisions,
                NeighbourhoodMeshLod.SubdivisionsFor(NeighbourhoodMeshLod.Full));
            Assert.Equal(1, NeighbourhoodMeshLod.SubdivisionsFor(NeighbourhoodMeshLod.Quarter));

            //--- the clamps, and their tie-breaking ---------------------------------------------
            //Nearest, and a tie goes to the *coarser* level: a factor between two real ones costs
            //frames rather than quality, which is the safe direction for a rule whose only job is
            //to spend less.
            Assert.Equal(NeighbourhoodMeshLod.Full, NeighbourhoodMeshLod.ClampFactor(0));
            Assert.Equal(NeighbourhoodMeshLod.Full, NeighbourhoodMeshLod.ClampFactor(-7));
            Assert.Equal(NeighbourhoodMeshLod.Full, NeighbourhoodMeshLod.ClampFactor(1));
            Assert.Equal(NeighbourhoodMeshLod.Half, NeighbourhoodMeshLod.ClampFactor(2));
            Assert.Equal(NeighbourhoodMeshLod.Quarter, NeighbourhoodMeshLod.ClampFactor(3));
            Assert.Equal(NeighbourhoodMeshLod.Quarter, NeighbourhoodMeshLod.ClampFactor(4));
            Assert.Equal(NeighbourhoodMeshLod.Quarter, NeighbourhoodMeshLod.ClampFactor(9));
            //Anything at or below the finest level is the finest level, and a negative factor is
            //not "between two levels" - it is a sign a caller has already lost.
            Assert.Equal(NeighbourhoodMeshLod.Full, NeighbourhoodMeshLod.ClampFactor(-2));
            Assert.Equal(1, NeighbourhoodMeshLod.ClampSubdivisions(0));
            Assert.Equal(1, NeighbourhoodMeshLod.ClampSubdivisions(1));
            //A count between the two is the coarser answer: cheap geometry over a vertex grid
            //nobody asked for.
            Assert.Equal(1, NeighbourhoodMeshLod.ClampSubdivisions(2));
            Assert.Equal(NeighbourhoodMeshLod.MaxSubdivisions,
                NeighbourhoodMeshLod.ClampSubdivisions(NeighbourhoodMeshLod.MaxSubdivisions));
            Assert.Equal(NeighbourhoodMeshLod.MaxSubdivisions,
                NeighbourhoodMeshLod.ClampSubdivisions(99));
            //And ForFactor clamps rather than trusting its caller, and a level is two numbers: a
            //factor of three is nearer four than two, so it is the quarter level.
            Assert.Equal(NeighbourhoodMeshLod.Quarter,
                NeighbourhoodMeshLod.ForFactor(3).Factor);
            Assert.Equal(NeighbourhoodMeshLod.Half,
                NeighbourhoodMeshLod.ForFactor(2).Factor);
            Assert.True(NeighbourhoodMeshLod.SameLevel(
                NeighbourhoodMeshLod.ForFactor(1), NeighbourhoodMeshLod.ForFactor(1)));
            Assert.False(NeighbourhoodMeshLod.SameLevel(
                new NeighbourhoodMeshLod(NeighbourhoodMeshLod.Full, 1),
                new NeighbourhoodMeshLod(NeighbourhoodMeshLod.Full,
                    NeighbourhoodMeshLod.MaxSubdivisions)));
            Assert.Equal(new[] { 1, 2, 4 }, NeighbourhoodMeshLod.Factors);

            //--- the selector, over a zoom in and back out ------------------------------------------
            //The first Select is exempt from the deadband: a neighbourhood screen starts zoomed out
            //on the whole map, and a deadband there would refuse the very first change - a 724-tile
            //view would sit on the full-detail subdivided level for ever, because getting from it
            //to the quarter level needs 736 tiles and no view that starts a world at 724 will get
            //there. History needs something to be history about, and there is none on the first
            //frame.
            var selector = new NeighbourhoodMeshLodSelector();
            Assert.Equal(0, selector.Changes);
            var first = selector.Select(wholeMap);
            Assert.Equal(NeighbourhoodMeshLod.Quarter, first.Factor);
            Assert.Equal(1, selector.Changes);
            Assert.Equal(NeighbourhoodMeshLod.Quarter, selector.Current.Factor);

            //Now zoom in. A level is left only once the view has crossed the boundary by fifteen
            //per cent, and once it has, the same margin applies in the other direction - so the fine
            //level survives a small zoom-out past its own boundary, and the coarse level survives a
            //small zoom-in. A rule where one direction is sticky and the other is not is the
            //version that still pops on the way back.
            Assert.Equal(NeighbourhoodMeshLod.Quarter, selector.Select(
                NeighbourhoodMeshLod.MinTilesAcross * NeighbourhoodMeshLod.Quarter).Factor);
            Assert.Equal(1, selector.Changes);
            Assert.True(selector.Select(
                NeighbourhoodMeshLod.MinTilesAcross * NeighbourhoodMeshLod.Quarter
                * (1f + NeighbourhoodMeshLodSelector.Hysteresis) - 1f).Factor
                == NeighbourhoodMeshLod.Quarter);
            Assert.Equal(1, selector.Changes);
            //Past the margin: the half level. Its own boundary is
            //<c>MinTilesAcross * 2</c> = 320, and leaving the quarter level for it needs the view
            //inside 320 * 1.15 = 368 - so 330 is a width the stateless rule calls half *and* the
            //deadband has cleared, which is the only kind of width that changes anything.
            var halfBoundary = NeighbourhoodMeshLod.MinTilesAcross * NeighbourhoodMeshLod.Half;
            Assert.Equal(NeighbourhoodMeshLod.Half,
                NeighbourhoodMeshLod.ForTilesAcross(halfBoundary + 10f).Factor);
            selector.Select(halfBoundary + 10f);
            Assert.Equal(NeighbourhoodMeshLod.Half, selector.Current.Factor);
            Assert.Equal(2, selector.Changes);
            //And it holds there: a small zoom-out past its own boundary is inside the band.
            Assert.Equal(NeighbourhoodMeshLod.Half, selector.Select(halfBoundary * 1.10f).Factor);
            Assert.Equal(2, selector.Changes);
            //A zoom-in not far enough leaves it coarse too, because the same margin applies in the
            //other direction - which is the half of the rule that stops it popping on the way back.
            //300 tiles calls for the full-detail level statelessly and is 300 >= 184, so the fine
            //level is refused.
            Assert.Equal(NeighbourhoodMeshLod.Full, NeighbourhoodMeshLod.ForTilesAcross(300f).Factor);
            Assert.Equal(NeighbourhoodMeshLod.Half, selector.Select(300f).Factor);
            Assert.Equal(2, selector.Changes);
            //Past the margin on that side, it changes - and 180 < 184 is what cleared it.
            selector.Select(NeighbourhoodMeshLod.MinTilesAcross
                * (1f + NeighbourhoodMeshLodSelector.Hysteresis) - 1f);
            Assert.Equal(NeighbourhoodMeshLod.Full, selector.Current.Factor);
            Assert.Equal(3, selector.Changes);
            Assert.Equal(0.15f, NeighbourhoodMeshLodSelector.Hysteresis);

            //--- a whole sweep in and back out, counting the changes -------------------------------
            //The property the selector exists for: the level is a function of the camera's
            //*history*, and a sweep that changed more than once per boundary would be the pop this
            //file was written to remove.
            var swept = new NeighbourhoodMeshLodSelector();
            //The first call is exempt, and takes the stateless rule at a whole map's width.
            Assert.Equal(NeighbourhoodMeshLod.Quarter, swept.Select(wholeMap).Factor);
            //Zoom all the way in, then all the way back out, counting the changes either way. The
            //whole range has three boundaries - two factors and the subdivision - and each is owned
            //by one band, so a monotone sweep costs about one change per boundary and not one per
            //sample.
            for (float width = 10f; width <= wholeMap; width *= 1.05f) swept.Select(width);
            var outToWide = swept.Changes;
            Assert.Equal(1, swept.Current.Subdivisions);
            //Not the quarter level, and that is the deadband doing its job rather than a bug: the
            //half level owns everything up to 640 * 1.15 = 736 tiles, and a whole 512-tile map
            //framed at full screen is 724. So a camera that zoomed *out* to the whole map is left
            //on the half level, while one that started there - the first call, which is exempt -
            //is on the quarter level. Same width, different answer, and that is the entire point:
            //the level is a function of the camera's history, which is what stops it popping.
            Assert.Equal(NeighbourhoodMeshLod.Half, swept.Current.Factor);
            Assert.True(outToWide <= 4, outToWide + " changes on the way out over three boundaries");
            //And enough extra width does buy it, which is the other half: the band is bounded, not
            //a latch.
            swept.Select(736f);
            Assert.Equal(NeighbourhoodMeshLod.Quarter, swept.Current.Factor);

            for (float width = wholeMap; width >= 10f; width /= 1.05f) swept.Select(width);
            var backIn = swept.Changes;
            //All the way in, the level is the finest one the rule has: one quad per tile, cut into
            //four by four.
            Assert.Equal(NeighbourhoodMeshLod.Full, swept.Current.Factor);
            Assert.Equal(NeighbourhoodMeshLod.MaxSubdivisions, swept.Current.Subdivisions);
            //And roughly the same number coming back, which is the property the deadband exists
            //for: a rule that popped would change many times per boundary in either direction.
            Assert.True(backIn - outToWide <= 5,
                (backIn - outToWide) + " changes on the way in over the same three boundaries");
            //And a selector that has been reset forgets the history, so the next call takes the
            //stateless rule rather than a deadband it has already spent.
            swept.Reset();
            Assert.Equal(0, swept.Changes);
            Assert.Equal(NeighbourhoodMeshLod.Full, swept.Current.Factor);
            Assert.Equal(NeighbourhoodMeshLod.Quarter, swept.Select(wholeMap).Factor);
            Assert.Equal(1, swept.Changes);
            Assert.Contains("quarter", swept.Describe());
            Assert.Contains("hysteresis 15%", swept.Describe());

            //--- the boundary predicate on its own ---------------------------------------------
            //Both axes have to agree, and a width the rule cannot read is not a reason to swap
            //buffers: keep what is in hand.
            var from = new NeighbourhoodMeshLod(NeighbourhoodMeshLod.Quarter, 1);
            var to = new NeighbourhoodMeshLod(NeighbourhoodMeshLod.Half, 1);
            var halfOwnReach = NeighbourhoodMeshLod.MinTilesAcross * NeighbourhoodMeshLod.Half;
            var quarterOwnReach = NeighbourhoodMeshLod.MinTilesAcross * NeighbourhoodMeshLod.Quarter;
            //Quarter -> half is a *finer* level, so the view has to be inside the half level's own
            //reach by the margin: under 320 * 1.15 = 368 tiles. The widths here are a clear tile or
            //two either side of that rather than exactly on it, because 1.15 is not exact in a
            //float and a test that sat on the boundary would be asserting a rounding.
            Assert.False(NeighbourhoodMeshLodSelector.ClearedBoundary(quarterOwnReach, to, from));
            Assert.False(NeighbourhoodMeshLodSelector.ClearedBoundary(halfOwnReach * 1.30f, to, from));
            Assert.True(NeighbourhoodMeshLodSelector.ClearedBoundary(halfOwnReach - 1f, to, from));
            //And half -> quarter is a *coarser* level, so the mirror: over 640 * 1.15 = 736.
            Assert.False(NeighbourhoodMeshLodSelector.ClearedBoundary(quarterOwnReach, from, to));
            Assert.True(NeighbourhoodMeshLodSelector.ClearedBoundary(quarterOwnReach * 1.30f, from, to));
            Assert.False(NeighbourhoodMeshLodSelector.ClearedBoundary(float.NaN, to, from));
            Assert.False(NeighbourhoodMeshLodSelector.ClearedBoundary(0f, to, from));
            Assert.False(NeighbourhoodMeshLodSelector.ClearedBoundary(
                float.PositiveInfinity, to, from));
            //Same level is never a change, in either direction.
            Assert.False(NeighbourhoodMeshLodSelector.ClearedBoundary(wholeMap, to, to));

            //--- and the per-frame floor, which is the belt to the deadband's braces ---------------
            //A camera that is genuinely moving through the band cannot change level faster than
            //this, which also bounds how much of the screen can be in the middle of a swap. Asked
            //directly, with the first call still exempt.
            var floored = new NeighbourhoodMeshLodSelector();
            //The first call is exempt from the floor too, or a screen that starts zoomed out would
            //never leave the finest level.
            Assert.Equal(NeighbourhoodMeshLod.Quarter, floored.Select(wholeMap, 3).Factor);
            Assert.Equal(1, floored.Changes);
            //Now a width the *stateless rule* calls half (320 or more tiles across) and the deadband
            //has cleared (under 368), so the only thing left refusing the change is the floor. The
            //counter is the number of frames already held since the last change, so a floor of
            //three releases on the third call after it, not the fourth.
            var past = halfOwnReach + 20f;
            Assert.Equal(NeighbourhoodMeshLod.Half,
                NeighbourhoodMeshLod.ForTilesAcross(past).Factor);
            for (int frame = 0; frame < 2; frame++)
            {
                Assert.Equal(NeighbourhoodMeshLod.Quarter, floored.Select(past, 3).Factor);
                Assert.Equal(1, floored.Changes);
            }
            floored.Select(past, 3);
            Assert.Equal(NeighbourhoodMeshLod.Half, floored.Current.Factor);
            Assert.Equal(2, floored.Changes);
            //A floor of zero or less is no floor at all, which is the default a caller gets when it
            //has not thought about frame rates.
            Assert.Equal(0, NeighbourhoodMeshLodSelector.DefaultMinFramesBetweenChanges);
            var unfloored = new NeighbourhoodMeshLodSelector();
            unfloored.Select(wholeMap);
            Assert.Equal(NeighbourhoodMeshLod.Half, unfloored.Select(past, 0).Factor);
        }

        [Fact]
        public void EveryLevelOfDetailIsBuiltFromOneMapAndTheRoadsAreTheSameAtAllOfThem()
        {
            //The half of the LOD that is *not* the selection rule: that the three levels are three
            //builds of the same map rather than three different worlds, and that the roads never
            //coarsen. A road quad is a mask-driven cell of the road atlas, and averaging four tiles'
            //masks would produce a street that is not on the map - so the road quad count is the
            //same number at every level, and only the ground falls.
            //
            //This one works at the full 512x512, because the mesh builder refuses anything else and
            //a 96-tile map would prove nothing about a 512. It is the one expensive test in this
            //file and the generator and the builder are both O(size^2).
            var lots = new List<NeighbourhoodLotInput>();
            for (short i = 0; i < 4; i++)
            {
                lots.Add(NeighbourhoodTestInput.Lot((short)(11 + i),
                    8 + i * 24, 16, NeighbourhoodDoorSide.East));
            }
            var input = new NeighbourhoodMapInput(NeighbourhoodTestInput.DefaultSeed,
                NeighbourhoodCityMeshBuilder.MapSize, lots);
            var map = NeighbourhoodMapGenerator.Generate(input);

            var reports = new NeighbourhoodCityMeshReport[NeighbourhoodMeshLod.Factors.Length];
            var meshes = new NeighbourhoodCityMesh[NeighbourhoodMeshLod.Factors.Length];
            for (int i = 0; i < NeighbourhoodMeshLod.Factors.Length; i++)
            {
                var report = NeighbourhoodCityMeshReport.Probe(map);
                reports[i] = report;
                meshes[i] = NeighbourhoodCityMeshBuilder.TryBuild(map,
                    NeighbourhoodMeshLod.Factors[i], out var reason, out var built);
                Assert.True(meshes[i] != null, NeighbourhoodMeshLod.Factors[i] + ": " + reason);
                Assert.Equal(NeighbourhoodMeshLod.Factors[i], meshes[i].LodFactor);
                //A whole-map level is never subdivided whichever factor it is: the subdivision is
                //what the close level is for, and it is built per slice.
                Assert.Equal(1, meshes[i].Subdivisions);
            }

            //The ground falls by a factor of four a level, and the ratio is the claim rather than
            //the absolute counts - which is what makes it survive a change to the fade skirt or the
            //chunk grid.
            var full = GroundQuads(meshes[0]);
            var half = GroundQuads(meshes[1]);
            var quarter = GroundQuads(meshes[2]);
            Assert.True(full > half, full + " then " + half);
            Assert.True(half > quarter, half + " then " + quarter);
            Assert.InRange(full / (float)half, 3.5f, 4.5f);
            Assert.InRange(half / (float)quarter, 3.5f, 4.5f);

            //The roads do not. Every level draws one quad per marked road tile, because the mesh
            //does not choose a street width - the road graph does, by marking tiles - and this
            //builder draws one quad per marked tile, so the drawn width is exactly the marked width
            //with no scaling anywhere between.
            var roadQuads = RoadQuads(meshes[0]);
            Assert.True(roadQuads > 0, "the fixture generated a map with no road quads at all");
            for (int i = 1; i < meshes.Length; i++)
            {
                Assert.True(roadQuads == RoadQuads(meshes[i]),
                    "level " + NeighbourhoodMeshLod.Factors[i] + " coarsened the roads");
            }

            //And every level is the same world: the same chunk grid, the same report of what the
            //map holds, and the same road-cell set, so one draw path serves all three.
            for (int i = 1; i < meshes.Length; i++)
            {
                Assert.Equal(reports[0].MapTiles, reports[i].MapTiles);
                Assert.Equal(reports[0].MapRoadTiles, reports[i].MapRoadTiles);
                Assert.Equal(reports[0].DiamondTiles, reports[i].DiamondTiles);
                Assert.Equal(meshes[0].Layers.Length, meshes[i].Layers.Length);
                Assert.Equal(meshes[0].LayerChunkIndexStarts.Length,
                    meshes[i].LayerChunkIndexStarts.Length);
                Assert.Equal(meshes[0].RoadChunkIndexStarts.Length,
                    meshes[i].RoadChunkIndexStarts.Length);
            }

            //A level that is not one the builder accepts is clamped rather than refused, so a caller
            //that passes a factor it invented gets a real mesh and not a null.
            NeighbourhoodCityMeshReport clampedReport;
            var clamped = NeighbourhoodCityMeshBuilder.TryBuild(map, 3, out _, out clampedReport);
            Assert.NotNull(clamped);
            Assert.Equal(NeighbourhoodMeshLod.Quarter, clamped.LodFactor);
            //And a map that cannot be meshed is refused with a reason rather than a null nobody can
            //act on: the fixture is 96 tiles, and the mesh is built for 512.
            var small = NeighbourhoodMapGenerator.Generate(NeighbourhoodTestInput.FourFlatLots());
            Assert.False(NeighbourhoodCityMeshBuilder.CanMesh(small, out var why));
            Assert.Contains("512x512", why);
            Assert.False(NeighbourhoodCityMeshBuilder.CanMesh(null, out why));
            Assert.Contains("no generated map", why);
        }

        /// <summary>Every ground quad a level emitted, across its five layers.</summary>
        private static int GroundQuads(NeighbourhoodCityMesh mesh)
        {
            var total = 0;
            for (int i = 0; i < mesh.Layers.Length; i++) total += mesh.Layers[i].PrimitiveCount;
            return total;
        }

        /// <summary>Every road quad a level emitted, straight and corner alike.</summary>
        private static int RoadQuads(NeighbourhoodCityMesh mesh)
        {
            return mesh.Roads.PrimitiveCount;
        }
