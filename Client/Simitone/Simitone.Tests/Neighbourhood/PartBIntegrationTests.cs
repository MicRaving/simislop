            Assert.False(onPlot.TryPlanPath(plot.Lots[0].Number, plot.Lots[0].Number, out none, out reason));
            Assert.Same(TransitPath.None, none);
            Assert.Contains("no house", reason);
            Assert.Null(plot.Query.EntranceFor(plot.Lots[0].Number));

            //A null query is a caller bug rather than an answer, and says so.
            Assert.Throws<ArgumentNullException>(() => new NeighbourhoodTransitLot(null));

