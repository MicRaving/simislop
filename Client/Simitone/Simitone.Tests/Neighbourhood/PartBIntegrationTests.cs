            var none = SimitoneSurroundingsPlan.ForQuery(placement, world.Map, world.Query,
                world.Layout, world.LotStore,
                SimitoneSurroundingsPlan.DefaultSubWorldRadiusTiles, 0);
            Assert.True(none.IsValid, none.Failure);
            Assert.Empty(none.Neighbours);
            Assert.Equal(full.Neighbours.Count, none.DeferredCount);
            Assert.False(none.IsFullyCovered);
