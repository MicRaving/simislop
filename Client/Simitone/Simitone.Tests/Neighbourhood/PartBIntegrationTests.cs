        [Fact]
        public void TheClockHandshakeMovesAllEightFieldsAndLeavesTheLotItsOwnFireBudget()
        {
            //§5.2's handshake end to end on a real <c>VMClock</c> rather than on the session record
            //the single-type suite round-trips. The whole shape of the claim: a lot that loads from
            //its own file starts at the activator's reading, the neighbourhood pushes its time over
            //that, the player spends an hour in it, and the pull on the way out brings the hour
            //back - once, and without touching the two fields that belong to the lot.
            var world = World();
            world.Clock.SeedFromGlobalState(GameGlobals());
            Assert.True(world.Clock.IsAvailable);

            //The lot's own fire budget and its UTC anchor, set to values nothing else produces, so
            //an assertion that they survive cannot pass by accident.
            var lot = new VMClock { FirePercent = 1234, UTCStart = 42L };

            //In: the neighbourhood's time, and only the neighbourhood's time. <c>FirePercent</c> is
            //a fuel budget and <c>UTCStart</c> is the lot's own anchor for <c>UTCNow</c>; moving
            //either would change what the lot reads as the time rather than what time it is.
            Assert.True(world.SyncClockTo(lot));
            AssertSameTime(world.Clock, lot);
            Assert.Equal(5, lot.Hours);
            Assert.Equal(30, lot.Minutes);
            Assert.Equal(14, lot.DayOfMonth);
            Assert.Equal(7, lot.Month);
            Assert.Equal(2001, lot.Year);
            Assert.Equal(1234, lot.FirePercent);
            Assert.Equal(42L, lot.UTCStart);

            //The same transfer as a statement rather than a question: the handshake's two halves as
            //§5.2 words them, on a lot the world has never been asked about before. Unconditional,
            //because a caller that has decided the transfer happens does not also decide whether the
            //neighbourhood had noticed - that is the question the Sync* pair is for.
            var spoken = new VMClock { FirePercent = 999 };
            world.PushClockTo(spoken);
            AssertSameTime(world.Clock, spoken);
            Assert.Equal(999, spoken.FirePercent);

            //A second lot brought in later gets the same time whatever its own file said, and the
            //push is idempotent - one neighbourhood, one clock, and asking twice is not a change.
            var second = new VMClock();
            Assert.True(world.SyncClockTo(second));
            Assert.False(world.SyncClockTo(second));
            AssertSameTime(world.Clock, second);
            Assert.Equal(20000, second.FirePercent);
            Assert.Equal(1234, lot.FirePercent);

            //An hour in the first lot. Its clock moves; the neighbourhood's does not, because
            //nothing has told the neighbourhood this lot is finished with.
            for (long i = 0; i < TicksPerGameHour; i++) lot.Tick();
            Assert.Equal(TicksPerGameHour, lot.Ticks);
            Assert.Equal(6, lot.Hours);
            Assert.Equal(0L, world.Clock.Ticks);

            //Out: the pull is what brings the hour back, and it is not a change the second time.
            Assert.True(world.SyncClockFrom(lot));
            Assert.False(world.SyncClockFrom(lot));
            AssertSameTime(world.Clock, lot);
            Assert.Equal(6, world.Clock.Hours);
            Assert.Equal(30, world.Clock.Minutes);
            Assert.Equal(TicksPerGameHour, world.Clock.Ticks);

            //The two statement halves make the same round trip as the two question halves, and it
            //is exact including the elapsed tick count - the part a "same wall clock" check misses.
            var third = new VMClock();
            world.PushClockTo(third);
            third.Tick();
            world.PullClockFrom(third);
            AssertSameTime(world.Clock, third);
            Assert.Equal(TicksPerGameHour + 1, world.Clock.Ticks);
            Assert.Equal(TicksPerGameHour + 1, third.Ticks);
            Assert.Equal(5, spoken.Hours);
            Assert.Equal(30, spoken.Minutes);
            Assert.Equal(0, spoken.Ticks);

            //And no clock at all is a caller bug, not an unavailable neighbourhood.
            Assert.Throws<ArgumentNullException>(() => world.SyncClockTo(null));
            Assert.Throws<ArgumentNullException>(() => world.SyncClockFrom(null));
        }

        [Fact]
        public void TheSwitchPathHasToCarryTheClockItself_BecauseTheWorldsLotSwitchDoesNot()
        {
            //The seam between "there is one switch path" and "there is one clock". §5.2's handshake
            //is exposed on the world and deliberately <em>not</em> called by
            //<see cref="SimitoneNeighbourhoodWorld.SetActiveLot"/>, because a world cannot know that
            //a lot is finished with. So the screen has to do it around the switch, and a switch that
            //does not is a switch that throws away the minutes the player spent where they were.
            //
            //Both halves walk the same three lots through the same service and the same world, so
            //the only difference between them is the handshake - which is what makes the difference
            //in the answer mean anything.
            Func<bool, long> ticksLeftBehindByOneSwitch = carryTheClock =>
            {
                var world = World();
                world.Clock.SeedFromGlobalState(GameGlobals());
                var home = world.Lots[0].Number;
                var next = world.Lots[1].Number;

                var lot = new VMClock();
                world.SyncClockTo(lot);
                world.SetActiveLotWith(home, new VMMarshal());
                var host = new WorldBackedTravelHost(world, home);
                var service = new LotTravelService();

                //An hour in the house, which only the lot's own clock ever sees.
                for (long i = 0; i < TicksPerGameHour; i++) lot.Tick();

                string reason;
                Assert.True(service.TryTransition(host,
                    new LotTransitionRequest(next, TransitionReason.Picker), out reason), reason);

                //The switch did its own job either way: the lot the player left is in the store -
                //the store holds the lots the player is <em>not</em> in - and the world names the
                //lot they are in. Neither of those is the clock's business.
                Assert.Equal(next, world.ActiveLotNumber);
                Assert.Equal(NeighbourhoodLotState.Active, world.LotStore.StateOf(home));

                if (carryTheClock)
                {
                    Assert.True(world.SyncClockFrom(lot));
                    //and the lot that just came up reads the neighbourhood's time, not its file's
                    var arriving = new VMClock();
                    Assert.True(world.SyncClockTo(arriving));
                    Assert.Equal(6, arriving.Hours);
                }

                return world.Clock.Ticks;
            };

            Assert.Equal(0L, ticksLeftBehindByOneSwitch(false));
            Assert.Equal(TicksPerGameHour, ticksLeftBehindByOneSwitch(true));

            //The frame rate is not the cause either: the neighbourhood keeps time while the player
            //stands in the second lot, and it keeps the same amount of it in one frame, three frames
            //or sixty. A real second is a game minute, so the hour the lot contributed and the hour
            //the world contributed are the same unit and the same number.
            Func<int, long> ticksAfterSwitching = frames =>
            {
                var world = World();
                world.Clock.SeedFromGlobalState(GameGlobals());
                var home = world.Lots[0].Number;
                var next = world.Lots[1].Number;

                var lot = new VMClock();
                world.SyncClockTo(lot);
                world.SetActiveLotWith(home, new VMMarshal());
                var host = new WorldBackedTravelHost(world, home);
                var service = new LotTravelService();

                for (long i = 0; i < TicksPerGameHour; i++) lot.Tick();

                string reason;
                Assert.True(service.TryTransition(host,
                    new LotTransitionRequest(next, TransitionReason.Picker), out reason), reason);
                world.SyncClockFrom(lot);

                //One game hour of neighbourhood time, in whatever frames the machine is running at.
                var perFrame = (TicksPerGameHour / frames) / WorldClock.TicksPerMinuteTs1;
                for (int i = 0; i < frames; i++) world.Tick(perFrame);
                return world.Clock.Ticks;
            };

            Assert.Equal(TicksPerGameHour * 2, ticksAfterSwitching(1));
            Assert.Equal(TicksPerGameHour * 2, ticksAfterSwitching(3));
            Assert.Equal(TicksPerGameHour * 2, ticksAfterSwitching(60));
        }

