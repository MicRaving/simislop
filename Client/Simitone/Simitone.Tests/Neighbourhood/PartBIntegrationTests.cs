        [Fact]
        public void TheWorldsLightingIsAPureFunctionOfItsOwnClockAndNothingElse()
        {
            //B8 across the seam that only an integration test can see. The features object does not
            //keep a clock: it holds <em>the world's</em> clock, so a neighbourhood's Sims, its sun
            //and its weather cannot end up on different clocks - which is the whole reason
            //centralised world features exist. The lighting is the half of that which is a function
            //of the clock <em>alone</em>: no seed, no layout, no state, so it is the one thing every
            //lot in the neighbourhood and every copy of the save agrees about.
            var world = World();
            world.Clock.SeedFromGlobalState(GameGlobals());
            var features = new NeighbourhoodWorldFeatures(world.Clock, world.Layout);

            //The world's clock is the features' clock - the same instance, not a copy - and the
            //layout is the world's own, so a visitor can only be somebody who lives here.
            Assert.Same(world.Clock, features.Clock);
            Assert.Same(world.Layout, features.Layout);
            Assert.Equal((long)world.Seed, features.WorldSeed);
            Assert.Equal(world.LotCount, features.LotCount);

            //05:30 on a July morning: first light, and by this type's reckoning the sun is up.
            Assert.Equal(5, features.Lighting.TimeOfDay.Hour);
            Assert.Equal(30, features.Lighting.TimeOfDay.Minute);
            Assert.Equal(WorldDayPhase.Dawn, features.DayPhase);
            Assert.False(features.IsNight);
            Assert.Equal(features.Lighting, WorldLightingState.FromClock(world.Clock));

            //A second object over the same clock says the same thing, which is what "pure" means for
            //a value with no state behind it: not the same shape, the same numbers.
            var second = new NeighbourhoodWorldFeatures(world.Clock, world.Layout);
            Assert.Equal(features.Lighting, second.Lighting);
            Assert.Equal(features.Weather, second.Weather);

            //...and another neighbourhood, under another seed, at the very same reading, agrees
            //about the light. The seed is what makes the weather a neighbourhood's; it must not be
            //what makes the sun come up.
            var elsewhere = WorldWithSeed(world.Seed + 1);
            elsewhere.Clock.SeedFromGlobalState(GameGlobals());
            var otherFeatures = new NeighbourhoodWorldFeatures(elsewhere.Clock, elsewhere.Layout);
            Assert.NotEqual(features.Weather, otherFeatures.Weather);
            Assert.Equal(features.Lighting, otherFeatures.Lighting);

            //And it moves with the clock along the world's own arc: noon is the peak, 17:30 is dim
            //but still lit, 18:30 is the last of the light, and 03:00 is the dark.
            var noon = LightingAt(12, 0);
            var lateAfternoon = LightingAt(17, 30);
            var lastLight = LightingAt(18, 30);
            var deepNight = LightingAt(3, 0);
            Assert.Equal(WorldDayPhase.Day, noon.TimeOfDay.Phase);
            Assert.Equal(WorldDayPhase.Day, lateAfternoon.TimeOfDay.Phase);
            Assert.Equal(WorldDayPhase.Dusk, lastLight.TimeOfDay.Phase);
            Assert.Equal(WorldDayPhase.Night, deepNight.TimeOfDay.Phase);
            Assert.Equal(WorldDayPhase.Night, LightingAt(20, 0).TimeOfDay.Phase);
            Assert.Equal(WorldDayPhase.Night, LightingAt(3, 0).TimeOfDay.Phase);
            Assert.Equal(WorldDayPhase.Dawn, LightingAt(5, 30).TimeOfDay.Phase);

            //"Is it dark" and "which band is it" are two questions with two answers, and the gap
            //between them is two hours: dark from sunset, but still Dusk until the last of the light
            //is gone. So a caller who wants lamps on gets the same answer at 18:30 and at 20:00 and
            //a caller who wants to know which band it is does not - and neither of them has to work
            //out the sun angle to avoid disagreeing with the other.
            Assert.True(lastLight.IsNight);
            Assert.True(deepNight.IsNight);
            Assert.False(noon.IsNight);
            Assert.False(lateAfternoon.IsNight);
            Assert.Equal(lastLight.IsNight, !lastLight.TimeOfDay.SunIsUp);
            Assert.Equal(noon.IsNight, !noon.TimeOfDay.SunIsUp);

            //The ramp is one number - how much of the day the sun is managing - so the whole day is
            //a single rise and a single fall, sampled here rather than asserted at four hours, so
            //that a band of the day that is neither of the four would still be caught.
            var sunrise = -1;
            var peak = 0.0;
            var peakAt = -1;
            for (int minute = 0; minute < NeighbourhoodWorldFeatures.HoursPerDay * 60; minute += 15)
            {
                var reading = LightingAt(minute / 60, minute % 60);
                Assert.InRange(reading.SunIntensity, 0.0, 1.0);
                Assert.InRange(reading.AmbientIntensity,
                    WorldLightingState.MinAmbientIntensity, WorldLightingState.MaxAmbientIntensity);
                if (reading.SunIntensity <= 0.0) continue;
                if (sunrise < 0) sunrise = minute;
                if (reading.SunIntensity > peak)
                {
                    peak = reading.SunIntensity;
                    peakAt = minute;
                }
            }

            //The sun is up for part of the day and not for the rest, it is brightest at solar noon
            //and never brighter than its own peak - which is the whole of what "centralised" buys
            //over four lots each guessing their own.
            Assert.True(sunrise > 0, "the sun never came up: " + LightingAt(12, 0));
            Assert.Equal(NeighbourhoodWorldFeatures.HoursPerDay * 60 / 2, peakAt);
            Assert.Equal(1.0, peak);
            Assert.True(noon.AmbientIntensity > deepNight.AmbientIntensity,
                "solar noon is not lighter than the small hours");
            Assert.Equal(WorldLightingState.MinAmbientIntensity, deepNight.AmbientIntensity);

            //And the same hour asked twice is the same reading, on a clock walked there two ways.
            Assert.Equal(noon, LightingAt(12, 0));
        }

