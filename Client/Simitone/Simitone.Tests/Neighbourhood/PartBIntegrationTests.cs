                Assert.Equal(WorldDayPhase.Dusk, features.DayPhase);
                AssertSameVisitors(atRest, world.Visitors, "paused frame " + frame);
            }

            //Nothing moved, and not even a record was made for the lot it was looking at.
            Assert.Equal(refreshes, world.FeatureTicks);
            Assert.Equal(parked + WorldClock.TicksPerMinuteTs1, world.Clock.Ticks);
            Assert.True(world.LastOffscreenTick.Paused);
            Assert.False(world.LastOffscreenTick.Changed);
            Assert.Equal(0, world.Offscreen.RecordCount);
            OffscreenLotRecord none;
            Assert.False(world.TryGetOffscreenRecord(ResidentLot, out none));
            Assert.True(Describe(motives) == Describe(MotivesOf(StoredMarshal(world, ResidentLot))),
                "a paused world wrote into a stored lot");

            //The same fifteen frames with the dial turned back: the hour does pass, the company
            //goes with it, and the lot is simulated. Which is what makes the fifteen frames
            //above a statement about pausing rather than about the fixture.
            world.Offscreen.Fidelity = OffscreenSimulator.DefaultFidelity;
            for (int frame = 0; frame < 15; frame++) Assert.True(world.Tick(FifteenGameHours / 60));

            Assert.Equal(parked + WorldClock.TicksPerMinuteTs1
                + 15L * (FifteenGameHours / 60) * WorldClock.TicksPerMinuteTs1, world.Clock.Ticks);
            Assert.True(world.Clock.Hours >= NeighbourhoodWorldFeatures.CommunityCloseHour,
                "the unpaused run never reached the hour the community lot closes: "
                + world.Clock.Hours);
            Assert.Equal(refreshes + 15L, world.FeatureTicks);
            Assert.False(NamesCommunityLot(world.Visitors),
                "the community lot is still reported after it closed: " + features.Describe());
            Assert.Equal(WorldDayPhase.Night, features.DayPhase);
            Assert.True(world.TryGetOffscreenRecord(ResidentLot, out none));
            Assert.True(Describe(motives) != Describe(MotivesOf(StoredMarshal(world, ResidentLot))),
                "the unpaused run left the stored lot where the paused one left it");
            Assert.True(hours > 0, "the visiting window this test parks inside is empty");
        }

