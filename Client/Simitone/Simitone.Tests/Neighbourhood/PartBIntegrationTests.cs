        /// <summary>
        /// A motive table as one line of text, for a failure message. xunit's own array
        /// "collections differ" output stops at the sixth element and the interesting one is usually
        /// not the sixth, so the comparison that matters says what differed itself.
        /// </summary>
        private static string Describe(short[] motives)
        {
            var parts = new string[motives.Length];
            for (int i = 0; i < motives.Length; i++) parts[i] = motives[i].ToString();
            return "[" + string.Join(", ", parts) + "]";
        }

        /// <summary>
        /// The lighting a clock reads at a given hour of a July day, on a throwaway clock rather than
        /// the world's: the arc and the phase are the ones a real reading gives, and nothing about
        /// a world under test is disturbed.
        /// </summary>
        private static WorldLightingState LightingAt(int hour, int minute)
        {
            var clock = new WorldClock();
            clock.SeedFromGlobalState(GameGlobals());
            SetHour(clock, hour, minute);
            return WorldLightingState.FromClock(clock);
        }

        /// <summary>
        /// The weather a seed reports at each of the twenty-four hours of one day, and how many
        /// weather segments that walk crossed. A day rather than a point, so what is compared is a
        /// run of weather and not a single draw.
        /// </summary>
        private static List<WorldWeather> WeatherWalk(long seed, out int segments)
        {
            var clock = new WorldClock();
            clock.SeedFromGlobalState(GameGlobals());
            var seen = new List<long>();
            var weather = new List<WorldWeather>();

            for (int hour = 0; hour < NeighbourhoodWorldFeatures.HoursPerDay; hour++)
            {
                SetHour(clock, hour);
                var now = WorldWeather.At(seed, clock);
                weather.Add(now);
                if (!seen.Contains(now.SegmentStartTick)) seen.Add(now.SegmentStartTick);
            }

            segments = seen.Count;
            return weather;
        }

        /// <summary>
        /// Put a clock on a given hour of a day, moving <em>forwards</em> to get there. The visitor
        /// draw is keyed by the day the ticks fall in, so a helper that wound the clock back would be
        /// asking about a different evening rather than an earlier minute of this one - and a helper
        /// that counted only minutes would land an hour out, which is exactly the mistake this
        /// comment is here to stop being repeated.
        /// </summary>
        private static void SetHour(WorldClock clock, int hour, int minute = 0)
        {
            var perMinute = clock.TicksPerMinute > 0
                ? clock.TicksPerMinute
                : WorldClock.TicksPerMinuteTs1;
            var now = (long)clock.Hours * 60 + clock.Minutes;
            var target = (long)hour * 60 + minute;
            var forward = target - now;
            if (forward < 0) forward += (long)NeighbourhoodWorldFeatures.HoursPerDay * 60;
            TickBy(clock, forward * perMinute);
        }

        /// <summary>
        /// Advance a clock by a number of sub-minute ticks. <see cref="WorldClock.Tick"/> is one
        /// tick by design - B6 fast-forwards by calling it thousands of times - so a helper that
        /// wanted a whole day would loop, and says so here rather than pretending otherwise.
        /// </summary>
        private static void TickBy(WorldClock clock, long ticks)
        {
            for (long i = 0; i < ticks; i++) clock.Tick();
        }

