                world.Layout, world.LotStore, radius, SimitoneSurroundingsPlan.MaxSubWorlds);
        }

        /// <summary>
        /// A file in Simitone's own client project, found by walking up out of the test output
        /// rather than by a fixed number of levels, so a build-layout change is a clear failure
        /// instead of "file not found".
        /// </summary>
        /// <param name="parts">The path under Simitone.Client, e.g. UI/Screens/TS1GameScreen.cs.</param>
        private static string ClientSource(params string[] parts)
        {
            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            while (dir != null)
            {
                var candidate = Path.Combine(new[] { dir.FullName, "Simitone.Client" }
                    .Concat(parts).ToArray());
                if (File.Exists(candidate)) return candidate;
                dir = dir.Parent;
            }
            return null;
        }

        /// <summary>
        /// A source file read without taking an exclusive claim on it: an editor or another build
        /// holding the file open for write must not turn a source-wiring assertion into an
        /// IOException that has nothing to do with what the assertion checks.
        /// </summary>
        private static string ReadSource(string path)
        {
            using (var stream = new FileStream(path, FileMode.Open, FileAccess.Read,
                FileShare.ReadWrite | FileShare.Delete))
            using (var reader = new StreamReader(stream))
            {
                return reader.ReadToEnd();
            }
        }

        /// <summary>
        /// C# with comments removed, so an assertion about what a file <em>does</em> cannot be
        /// satisfied - or broken - by what it explains. The prose around this feature names
        /// <c>AttachSubWorlds</c> several times, and a check that counted those would pass on a
        /// screen that does not call it.
        /// </summary>
        private static string CommentsRemoved(string source)
        {
            Assert.NotNull(source);
            var withoutBlocks = System.Text.RegularExpressions.Regex.Replace(
                source, @"/\*.*?\*/", " ", System.Text.RegularExpressions.RegexOptions.Singleline);
            return System.Text.RegularExpressions.Regex.Replace(withoutBlocks, @"//[^\n]*", " ");
        }

        /// <summary>
        /// A lot switch request that is consumed without a lot switch happening must give back the
        /// pause <c>TS1GameScreen.VMLotSwitch</c> took.
        ///
        /// <para>
        /// <b>Why a source assertion and not a behavioural one.</b> The freeze needs a live
        /// <c>VM</c>, a family, a <c>World</c> and a graphics device to reproduce, and the whole
        /// of the rule is three places in one method and one call in another. What is asserted
        /// here is the shape of that, in comments-stripped source so a check cannot be satisfied by
        /// a paragraph explaining it:
        /// </para>
        /// <list type="number">
        /// <item><c>VMLotSwitch</c> bounds the destination it resolves with
        /// <c>LotTravelService.IsLotNumber</c>, so a family whose house number is not a lot is the
        /// "no lot to switch to" answer that restores the speed rather than a request the travel
        /// service will refuse a frame later - and 99, the lot-location parser's own sentinel, is
        /// the number that used to do exactly that;</item>
        /// <item>the restore itself is one method that only acts on the <c>VM</c> the pause was
        /// taken on, so a switch that already happened is never disturbed;</item>
        /// <item>every path through the <c>SwitchLot &gt; 0</c> block in <c>Update</c> that can
        /// clear <c>SwitchLot</c> without switching calls it, and
        /// <c>PerformLotSwitch</c> calls it for its own refusal.</item>
        /// </list>
        /// <para>
        /// The consequence of getting this wrong is the reported symptom exactly: a lot at
        /// <c>SpeedMultiplier == 0</c> skips <c>Context.Clock.Tick</c> in
        /// <c>VM.InternalTick</c>, so a group meal caught mid-serve keeps its
        /// <c>VMEntityFlags.Occupied</c> bit for the rest of the session and the pie menu refuses
        /// every interaction on it.
        /// </para>
        /// </summary>
        [Fact]
        public void ALotSwitchRequestThatNeverSwitchesGivesBackThePauseItTook()
        {
            var path = ClientSource("UI", "Screens", "TS1GameScreen.cs");
            Assert.NotNull(path);
            var source = CommentsRemoved(ReadSource(path));

            //(1) the guard exists and is one method
            Assert.Contains("private void RestoreSpeedAfterFailedLotSwitch()", source);
            var guardBody = MethodBody(source, "private void RestoreSpeedAfterFailedLotSwitch()");

            //only the lot that was paused, so a switch that has already replaced the VM is a no-op
            Assert.Contains("ReferenceEquals(_switchPausedVm, vm)", guardBody);
            //and only from a speed that was actually running, so a deliberately paused lot stays paused
            Assert.Contains("if (resuming <= 0) return;", guardBody);
            Assert.Contains("vm.SpeedMultiplier = resuming;", guardBody);

            //(2) VMLotSwitch bounds what it resolves the go-home sentinel to
            var switchBody = MethodBody(source, "private void VMLotSwitch(uint lotId)");
            Assert.Contains("LotTravelService.IsLotNumber((int)lotId)", switchBody);
            //and remembers the pause, which is what the guard needs to undo it
            Assert.Contains("_switchPausedVm = vm;", switchBody);
            Assert.Contains("_switchResumeSpeed = resuming;", switchBody);

            //(3) every consumer of SwitchLot without a switch ends the pause: the travel path
            //does it inside PerformLotSwitch, and the inline path cannot refuse
            var blockBody = MethodBody(source, "if (SwitchLot > 0)");
            Assert.Contains("PerformLotSwitch(SwitchLot);", blockBody);

            var travelBody = MethodBody(source, "private bool PerformLotSwitch(int houseId)");
            Assert.Contains("if (!switched) RestoreSpeedAfterFailedLotSwitch();", travelBody);
            Assert.Contains("return switched;", travelBody);
        }

