using System;
using System.Collections.Generic;
using System.Collections.ObjectModel;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Simitone.Client.UI.Panels.EODs
{
    /// <summary>
    /// The captions the generated EOD layouts show, and the ids they have in Simitone's own UI
    /// string table.
    /// </summary>
    /// <remarks>
    /// <para>
    /// A <c>.uis</c> cannot carry a literal. <c>UIScript.DefineString</c> resolves a
    /// <c>text=</c> attribute through <c>GameFacade.Strings</c>, so a button caption is a
    /// (directory, table, index) triple and nothing else - which is why the retail layouts are a
    /// wall of <c>&lt;DefineString&gt;</c> lines. These captions would otherwise be baked into
    /// the <c>.uis</c> in whatever language whoever wrote the spec was typing in, and the one
    /// thing Simitone's string table exists to stop is exactly that.
    /// </para>
    /// <para>
    /// So they go in <see cref="Simitone.Client.Utils.SimitoneStrings.Table"/>, the table
    /// <c>ContentStrings</c> reads in TS1 mode as well as TSO mode, and the block is generated
    /// from the same declaration the <c>.uis</c> files are generated from - see
    /// <see cref="Entries"/>. Ids are allocated from <see cref="FirstId"/> upwards in a fixed
    /// order, so a given build of the catalogue always produces the same ids, which is what lets
    /// the generated files be committed rather than written at load time.
    /// </para>
    /// <para>
    /// The block is a separate section at the end of the <c>.cst</c> rather than being
    /// interleaved with the hand-written ids, because it is regenerated: hand edits to it are
    /// lost, and <c>EODLayoutBuilderTests</c> fails if it stops matching
    /// <see cref="Entries"/>.
    /// </para>
    /// </remarks>
    public static class EODLayoutStrings
    {
        /// <summary>Simitone's own UI string table id, as <c>SimitoneStrings.Table</c>.</summary>
        public const string Table = Simitone.Client.Utils.SimitoneStrings.Table;

        /// <summary>File the table lives in, as <c>SimitoneStrings.TableFileName</c>.</summary>
        public const string TableFileName = Simitone.Client.Utils.SimitoneStrings.TableFileName;

        /// <summary>
        /// First id the generated block uses. Well clear of the hand-written ids, whose highest
        /// is 985, so the two can never collide and a hand-written addition below it cannot be
        /// shadowed.
        /// </summary>
        public const int FirstId = 1000;

        /// <summary>Marker opening the generated section of the <c>.cst</c>.</summary>
        public const string CstMarker = "--- EOD panel captions (GENERATED by EODLayoutStrings; do not hand edit)";

        private static readonly Dictionary<string, int> Ids = new Dictionary<string, int>(StringComparer.Ordinal);
        private static readonly List<KeyValuePair<int, string>> Ordered = new List<KeyValuePair<int, string>>();
        private static readonly object Gate = new object();
        private static bool Sealed;

        /// <summary>
        /// Every caption, as id and text, in id order. This is what the <c>.cst</c> block has to
        /// contain, and what a test compares it against.
        /// </summary>
        public static ReadOnlyCollection<KeyValuePair<int, string>> Entries
        {
            get
            {
                lock (Gate)
                {
                    return new ReadOnlyCollection<KeyValuePair<int, string>>(Ordered.ToList());
                }
            }
        }

        /// <summary>How many captions the generated block declares.</summary>
        public static int Count { get { lock (Gate) { return Ordered.Count; } } }

        /// <summary>
        /// Declares every caption a set of layouts uses, in a fixed order, so ids do not depend
        /// on which layout happened to be built first. Called once by <see cref="EODLayouts"/>
        /// and idempotent after that.
        /// </summary>
        public static void Reserve(IEnumerable<EODLayoutSpec> specs)
        {
            lock (Gate)
            {
                foreach (var spec in specs)
                {
                    foreach (var element in spec.Elements)
                    {
                        if (string.IsNullOrEmpty(element.Caption)) continue;
                        if (Ids.ContainsKey(element.Caption)) continue;
                        var id = FirstId + Ids.Count;
                        Ids[element.Caption] = id;
                        Ordered.Add(new KeyValuePair<int, string>(id, element.Caption));
                    }
                }
                Sealed = true;
            }
        }

        /// <summary>The id a caption was given, or throws if it was never reserved.</summary>
        public static int IdFor(string caption)
        {
            lock (Gate)
            {
                int id;
                if (!Ids.TryGetValue(caption ?? string.Empty, out id))
                {
                    throw new InvalidOperationException(
                        "no EOD caption was reserved for \"" + caption + "\"; EODLayoutStrings.Reserve has to see every layout");
                }
                return id;
            }
        }

        /// <summary>True once <see cref="Reserve"/> has run, so ids are final.</summary>
        public static bool Reserved
        {
            get { lock (Gate) { return Sealed; } }
        }

        /// <summary>
        /// The generated section of the <c>.cst</c>: marker, then one
        /// <c>id ^text^</c> line per caption, in id order.
        /// </summary>
        /// <remarks>
        /// Uses <c>SimitoneStrings.Delimiter</c> and the file's own field layout rather than
        /// hard-coded <c>^</c>, and refuses to emit a caption containing the delimiter - which
        /// would silently truncate the entry and lose the rest of the text.
        /// </remarks>
        public static IEnumerable<string> CstLines()
        {
            yield return "//";
            yield return "//" + CstMarker;
            yield return "//";
            yield return "// Button captions for the end-of-day minigame panels. The panels themselves are";
            yield return "// FSO.Client's; their layouts are Simitone's, because the retail ones are The Sims";
            yield return "// Online artwork layouts (see EODLayoutBuilder). A caption can only reach a .uis through";
            yield return "// a DefineString node, which resolves against a string table, so a layout with no table";
            yield return "// entry shows a button with no word on it. This is that table entry.";
            yield return "//";
            yield return "// Regenerate with Simitone.Client.UI.Panels.EODs.EODLayoutWriter rather than editing:";
            yield return "// EODLayoutBuilderTests compares this block against the layouts it generates.";

            foreach (var entry in Entries)
            {
                if (entry.Value.IndexOf(Simitone.Client.Utils.SimitoneStrings.Delimiter, StringComparison.Ordinal) >= 0)
                {
                    throw new InvalidOperationException(
                        "EOD caption \"" + entry.Value + "\" contains the .cst field delimiter and cannot be written");
                }
                yield return entry.Key.ToString(CultureInfo.InvariantCulture)
                    + " " + Simitone.Client.Utils.SimitoneStrings.Delimiter
                    + entry.Value
                    + Simitone.Client.Utils.SimitoneStrings.Delimiter;
            }
        }
    }
}
