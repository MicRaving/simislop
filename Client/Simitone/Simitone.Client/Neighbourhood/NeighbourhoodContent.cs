using System;
using System.Collections.Generic;
using System.IO;
using FSO.Common;
using FSO.Common.Utils;
using FSO.Files;
using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;

namespace Simitone.Client.Neighbourhood
{
    /// <summary>
    /// The content the generated neighbourhood draws with: the road atlas, the tree atlas and the
    /// five ground textures. All of it already ships - the road and tree atlases are TSO's own
    /// <c>Content/Textures/terrain</c> pngs, which the plan lists as in-tree and shipping, and the
    /// ground textures are generated by <see cref="NeighbourhoodTerrainTextures"/>.
    ///
    /// <para><b>Nothing here reads TSO game data.</b> The thing that would - the five
    /// <c>gamedata/terrain/newformat/*.tga</c> ground textures, the <c>cities/city_XXXX</c> folders,
    /// <c>userdata/houses/defaulthouse.bmp</c> - is exactly what <c>CityContent.LoadContent</c>
    /// loads and exactly what Scope A is avoiding. This class loads the <em>client's</em> content
    /// tree and nothing else, and it lives beside the renderer rather than in
    /// <c>CityContent</c> for that reason.
    /// </para>
    ///
    /// <para><b>Everything is optional.</b> A missing atlas, an unreadable png, a GPU that will
    /// not take a 1024x512 render target - each returns <c>null</c> or a 1x1 placeholder and is
    /// logged, because the alternative is that a content problem stops the neighbourhood opening at
    /// all, and the 2D bitmap has to stay the answer to that. The renderer draws whatever it has.
    /// </para>
    /// </summary>
    public sealed class NeighbourhoodContent : IDisposable
    {
        /// <summary>Where the shipped road, tree and ground atlases live, relative to the game root.</summary>
        public const string TerrainFolder = "Content/Textures/terrain";

        /// <summary>Where the shipped tree models live, relative to the game root.</summary>
        public const string ModelFolder = "Content/3D";

        /// <summary>
        /// The file that decides whether a candidate root is the game root. Index 1 rather than
        /// index 0 deliberately: <c>road00.png</c> is a 501-byte blank placeholder that exists to
        /// fill the unused cell of the atlas, and would happily be found in a content pack.
        /// </summary>
        public const string RootMarkerFile = "road01.png";

        /// <summary>Cells across in the road atlas; <c>NeighbourhoodRoadLayout.Width</c>.</summary>
        public const int RoadAtlasWidth = NeighbourhoodRoadLayout.Width;

        /// <summary>Cells down in the road atlas; <c>NeighbourhoodRoadLayout.Height</c>.</summary>
        public const int RoadAtlasHeight = NeighbourhoodRoadLayout.Height;

        private readonly GraphicsDevice _device;
        private readonly List<Texture2D> _owned = new List<Texture2D>();

        /// <summary>The five ground textures, indexed by <see cref="NeighbourhoodTerrain"/> value.</summary>
        public Texture2D[] Ground { get; private set; }

        /// <summary>
        /// The four blend-mask atlases, indexed by
        /// <see cref="NeighbourhoodBlendFlags.AtlasIndexForLayer"/>.
        /// </summary>
        /// <remarks>
        /// One per ground layer, as <c>CityContent.TransAtlas</c> is
        /// (<c>CityContent.cs:26</c>), and drawn by the same
        /// <c>ps.Parameters["TransAtlasTex"]</c> call <c>CityGeometry.DrawAll</c> makes at
        /// <c>CityGeometry.cs:865</c>. Generated rather than loaded - see
        /// <see cref="LoadBlendAtlases"/> - but the shape, the cell count and the index expression
        /// are the city's.
        /// </remarks>
        public Texture2D[] BlendAtlas { get; private set; }

        /// <summary>The road atlas: 16 road cells and 16 corner cells in one 8x4 texture.</summary>
        public Texture2D RoadAtlas { get; private set; }

        /// <summary>
        /// The per-tile tint the lifted <c>CityGeometry</c> reads through <c>VertexColorTex</c>
        /// when <c>UseVertexColor</c> is on.
        /// </summary>
        /// <remarks>
        /// <b>A white 1x1 stand-in, and the one place the generated neighbourhood substitutes a
        /// texture it does not have.</b> TSO's <c>terrainvertexcolor.bmp</c> is a hand-painted
        /// 512x512 per-tile tint that lives in the city install and cannot ship; a generated map
        /// has no such artwork. Binding white is the identity tint, so the lifted draw path's
        /// <c>UseVertexColor = true</c> becomes a no-op rather than a wrong colour - which is the
        /// same "draw whatever it has" rule the rest of this class follows, and is stated rather
        /// than left to a null sampler.
        /// </remarks>
        public Texture2D VertexColor { get; private set; }

        /// <summary>
        /// The large-scale water normal the lifted <c>CityGeometry</c> binds on the water layer.
        /// </summary>
        /// <remarks>
        /// <b>A flat 1x1 normal, another stand-in.</b> TSO's two water normal maps are city content
        /// that cannot ship; a flat <c>(0.5, 0.5, 1.0)</c> normal makes the water shader's normal
        /// lookup a no-op, so the water reads as flat water rather than as an undefined sample. A
        /// null here is the one thing that must not happen: <c>DrawAll</c> leaves these bound in
        /// samplers 3 and 4, and MonoGame's OpenGL path blacks the screen out over a null.
        /// </remarks>
        public Texture2D BigWNormal { get; private set; }

        /// <summary>The small-scale water normal; same stand-in as <see cref="BigWNormal"/>.</summary>
        public Texture2D SmallWNormal { get; private set; }

        /// <summary>The five ground textures, under the name the renderer's terrain loop uses.</summary>
        public Texture2D[] TerrainTextures
        {
            get { return Ground; }
        }

        /// <summary>The four blend-mask atlases, under the name the renderer's blend bind uses.</summary>
        public Texture2D[] TransAtlas
        {
            get { return BlendAtlas; }
        }

        /// <summary>The tree atlas the shipped tree models' UVs point into.</summary>
        public Texture2D TreeAtlas { get; private set; }

        /// <summary>What could not be loaded, one sentence per thing, for the log.</summary>
        public List<string> Warnings { get; private set; }

        /// <summary>Whether there is anything at all worth drawing.</summary>
        public bool HasAnything
        {
            get
            {
                if (RoadAtlas != null || TreeAtlas != null) return true;
                if (Ground == null) return false;
                foreach (var tex in Ground) if (tex != null) return true;
                return false;
            }
        }

        /// <summary>
        /// Loads everything. Never throws: a failure is a <see cref="Warnings"/> entry.
        /// </summary>
        /// <param name="device">The device to create textures on.</param>
        public NeighbourhoodContent(GraphicsDevice device)
        {
            _device = device;
            Warnings = new List<string>();
            Ground = new Texture2D[NeighbourhoodTerrainTextures.Count];
            BlendAtlas = new Texture2D[NeighbourhoodBlendFlags.AtlasCount];

            if (device == null)
            {
                Warnings.Add("there is no graphics device, so the generated neighbourhood has no textures");
                return;
            }

            //The two members of ICityGeometryContent a generated map has no artwork for. Created
            //before anything else, because the lifted draw binds them unconditionally on the
            //terrain and water passes and a null there is a blacked-out frame, not a missing
            //texture. See the remarks on the properties.
            LoadStandInTextures();

            var root = ResolveRoot(DefaultRootCandidates(), File.Exists);
            if (root == null)
            {
                Warnings.Add("no game folder with " + TerrainFolder + " was found, so the generated"
                    + " neighbourhood falls back to flat colours and no roads");
                LoadFlatGround();
                return;
            }

            LoadGround();
            RoadAtlas = LoadRoadAtlas(root);
            TreeAtlas = LoadTexture(Path.Combine(root, TerrainFolder, "trees.png"), "the tree atlas");
        }

        /// <summary>
        /// The identity tint and the flat water normals the lifted draw binds but a generated map
        /// has no artwork for. Each is a 1x1 texture, owned and disposed like every other texture
        /// here. See the property remarks for why white and why a flat normal.
        /// </summary>
        private void LoadStandInTextures()
        {
            VertexColor = Solid(Color.White);
            var flatNormal = new Color(128, 128, 255, 255);
            BigWNormal = Solid(flatNormal);
            SmallWNormal = Solid(flatNormal);
        }

        private void LoadFlatGround()
        {
            for (int i = 0; i < Ground.Length; i++)
            {
                Ground[i] = Solid(NeighbourhoodTerrainTextures.BaseColorFor((byte)i));
            }
            //The blend masks are generated, not found in the game folder, so the flat-ground
            //fallback still gets real ones. Skipping them would leave every terrain-type boundary a
            //hard step, which is the thing the masks exist to remove.
            LoadBlendAtlases();
        }

        private void LoadGround()
        {
            for (int i = 0; i < Ground.Length; i++)
            {
                var type = (byte)i;
                Color[] pixels;
                try
                {
                    pixels = NeighbourhoodTerrainTextures.PixelsFor(type);
                }
                catch (Exception ex)
                {
                    Warnings.Add("could not generate the ground texture for terrain " + type + ": " + ex.Message);
                    pixels = null;
                }
                Ground[i] = pixels == null ? Solid(NeighbourhoodTerrainTextures.BaseColorFor(type)) : Upload(pixels);
            }
            LoadBlendAtlases();
        }

        /// <summary>
        /// The four transparency atlases, one per ground layer, generated into the same 7x3 cell
        /// layout <c>CityContent.CreateTransparencyAtlas</c> builds
        /// (<c>CityContent.cs:265-299</c>) and indexed exactly as
        /// <c>CityGeometry.DrawAll</c> indexes them (<c>CityGeometry.cs:864</c>).
        /// </summary>
        /// <remarks>
        /// <para>
        /// <b>Generated, like the ground textures, and for the same reason.</b> TSO's blend masks
        /// are <c>gamedata/terrain/newformat/transa*.tga</c> and <c>transb*.tga</c> - sixty
        /// files of TSO game data that cannot ship. The <em>layout</em> is the part that has to
        /// match the city and it does: 7x3 cells, <see cref="NeighbourhoodBlendFlags.FlagLayout"/>'s
        /// remap, <c>(1/7, 1/3)</c> cell deltas, and the same per-layer atlas index. Only the
        /// pixels inside each cell are ours, and they are a smooth ramp rather than a hand-painted
        /// one - which is a content difference, not a geometry one, and is the substitution §9.3
        /// already sanctions for the ground.
        /// </para>
        /// <para>
        /// <b>A cell is the max of its own edges' ramps.</b> A mask names the edges that have
        /// <em>no</em> higher-priority neighbour, so a cell's alpha is one on the edges that do
        /// have one and falls to zero towards the tile's middle - which is what
        /// <c>PixShader.fx</c>'s <c>GetNCityColor</c> wants: it reads the mask's red channel as
        /// <c>A</c> and returns <c>float4(Base.xyz, A * Base.w)</c>
        /// (<c>PixShader.fx:379-391</c>), so the blend quad is opaque where the mask is and absent
        /// where it is not. <c>CityContent</c> clears the whole atlas to black first and then fills
        /// fifteen of the twenty-one cells, so the six it leaves are the "no blend" answer for a
        /// mask that never reaches them; the generated cells do the same by leaving anything not
        /// named by <see cref="NeighbourhoodBlendFlags.FlagLayout"/> black.
        /// </para>
        /// <para>
        /// Four atlases rather than one because the city has four
        /// (<c>CityContent.TransAtlas</c> is a <c>Texture2D[4]</c>, <c>CityContent.cs:26</c>) and
        /// the index expression is not constant across layers. They differ here only in the ramp
        /// width, so the four layers do not all cross-fade at exactly the same rate; TSO's differ
        /// in the painted masks, and the index arithmetic - which is what the mesh and the draw path
        /// depend on - is identical.
        /// </para>
        /// </remarks>
        private void LoadBlendAtlases()
        {
            for (int i = 0; i < BlendAtlas.Length; i++)
            {
                Color[] pixels;
                try
                {
                    pixels = NeighbourhoodBlendTextures.PixelsFor(i);
                }
                catch (Exception ex)
                {
                    Warnings.Add("could not generate blend mask atlas " + i + ": " + ex.Message);
                    pixels = null;
                }
                BlendAtlas[i] = pixels == null ? Solid(new Color(0, 0, 0, 0))
                    : UploadBlend(pixels);
            }
        }

        private Texture2D UploadBlend(Color[] pixels)
        {
            Texture2D texture = null;
            try
            {
                texture = new Texture2D(_device, NeighbourhoodBlendTextures.AtlasWidth,
                    NeighbourhoodBlendTextures.AtlasHeight, false, SurfaceFormat.Color);
                texture.SetData(pixels);
                _owned.Add(texture);
            }
            catch (Exception ex)
            {
                Warnings.Add("could not upload blend mask atlas: " + ex.Message);
                texture?.Dispose();
                //Opaque black, not transparent: the shader reads the mask's red channel as an
                //alpha, so a texture it cannot bind has to read as "no blend" rather than as
                //something undefined. Solid() is the same 1x1 the ground falls back to.
                texture = Solid(new Color(0, 0, 0, 0));
            }
            return texture;
        }

        private Texture2D Upload(Color[] pixels)
        {
            Texture2D texture = null;
            try
            {
                texture = new Texture2D(_device, NeighbourhoodTerrainTextures.Size,
                    NeighbourhoodTerrainTextures.Size, true, SurfaceFormat.Color);
                //The mip chain has to be filled, not just level 0: the ground is drawn with a
                //sampler that filters mips, so wherever the texture is minified the hardware samples
                //a level a bare SetData would leave undefined - and an undefined level is not the
                //ground colour. The road atlas below already does exactly this for the same reason.
                TextureUtils.UploadWithAvgMips(texture, _device, pixels);
                _owned.Add(texture);
            }
            catch (Exception ex)
            {
                Warnings.Add("could not upload a ground texture: " + ex.Message);
                texture?.Dispose();
                texture = Solid(NeighbourhoodTerrainTextures.BaseColorFor(NeighbourhoodTerrain.Grass));
            }
            return texture;
        }

        private Texture2D Solid(Color color)
        {
            var texture = new Texture2D(_device, 1, 1, false, SurfaceFormat.Color);
            texture.SetData(new[] { color });
            _owned.Add(texture);
            return texture;
        }

        /// <summary>
        /// The 8x4 road atlas, assembled the way <c>CityContent.CreateRoadAtlas</c> assembles it -
        /// which is not optional, because the UVs <c>CityGeometry</c> writes for a road tile are
        /// <c>(RoadLayout[mask] % RoadWidth, RoadLayout[mask] / RoadWidth)</c> into this exact
        /// layout. Cell 0 of the atlas is left clear because both tables' entry 0 is -1.
        /// </summary>
        private Texture2D LoadRoadAtlas(string root)
        {
            var roads = new Texture2D[16];
            var corners = new Texture2D[16];
            var cellSize = 0;
            for (int i = 0; i < 16; i++)
            {
                roads[i] = LoadTexture(Path.Combine(root, TerrainFolder, "road" + TwoDigits(i) + ".png"), "road " + i);
                corners[i] = LoadTexture(Path.Combine(root, TerrainFolder, "roadcorner" + TwoDigits(i) + ".png"), "road corner " + i);
                if (roads[i] == null || corners[i] == null)
                {
                    foreach (var t in roads) t?.Dispose();
                    foreach (var t in corners) t?.Dispose();
                    return null;
                }
                cellSize = roads[i].Width;
            }

            RenderTarget2D target = null;
            Texture2D atlas = null;
            SpriteBatch batch = null;
            var oldTarget = _device.GetRenderTargets();
            try
            {
                target = new RenderTarget2D(_device, cellSize * RoadAtlasWidth, cellSize * RoadAtlasHeight,
                    false, SurfaceFormat.Color, DepthFormat.None, 0, RenderTargetUsage.PreserveContents);
                _device.SetRenderTarget(target);
                _device.Clear(new Color(0, 0, 0, 0));

                batch = new SpriteBatch(_device);
                batch.Begin(SpriteSortMode.Deferred, BlendState.NonPremultiplied, SamplerState.PointClamp,
                    DepthStencilState.None, RasterizerState.CullNone, null);
                //Two tables, two sources. The corner layout names the turn/T/intersection cells and
                //has to be filled from roadcornerNN, not from the straight roadNN: drawing both
                //tables from `roads` put straight-road art in every corner cell, which on a street
                //grid reads as wrong/miniature street texture filling tiles it should not. This is
                //the same split CityContent.CreateRoadAtlas makes (Roads at RoadLayout, RoadCorners
                //at RoadCLayout).
                DrawCells(batch, roads, CityRoadLayout, cellSize);
                DrawCells(batch, corners, CityRoadCornerLayout, cellSize);
                batch.End();

                _device.SetRenderTargets(oldTarget);
                atlas = new Texture2D(_device, target.Width, target.Height, true, SurfaceFormat.Color);
                var data = new Color[target.Width * target.Height];
                target.GetData(data);
                TextureUtils.UploadWithAvgMips(atlas, _device, data);
                _owned.Add(atlas);
            }
            catch (Exception ex)
            {
                Warnings.Add("could not build the road atlas: " + ex.Message);
                atlas?.Dispose();
                atlas = null;
            }
            finally
            {
                batch?.Dispose();
                target?.Dispose();
                foreach (var cell in roads) cell?.Dispose();
                foreach (var cell in corners) cell?.Dispose();
            }
            return atlas;
        }

        private void DrawCells(SpriteBatch batch, Texture2D[] cells, int[] layout, int cellSize)
        {
            for (int i = 1; i < 16; i++)
            {
                var index = layout[i];
                if (index < 0) continue;
                var x = (index % RoadAtlasWidth) * cellSize;
                var y = (index / RoadAtlasWidth) * cellSize;
                batch.Draw(cells[i], new Rectangle(x, y, cellSize, cellSize), Color.White);
            }
        }

        private Texture2D LoadTexture(string path, string what)
        {
            try
            {
                using (var stream = File.OpenRead(path))
                {
                    return ImageLoader.FromStream(_device, stream);
                }
            }
            catch (Exception ex)
            {
                Warnings.Add("could not load " + what + " from " + path + ": " + ex.Message);
                return null;
            }
        }

        private static string TwoDigits(int value)
        {
            return value < 10 ? "0" + value : value.ToString();
        }

        /// <summary>
        /// The road cell tables, re-exported from <see cref="NeighbourhoodRoadLayout"/> so there
        /// is exactly one copy of them in the tree and the atlas assembly and the mesh builder
        /// cannot disagree about which cell a road shape lives in.
        /// </summary>
        public static int[] CityRoadLayout
        {
            get { return NeighbourhoodRoadLayout.Straights; }
        }

        /// <summary>The road corner cell table, from <see cref="NeighbourhoodRoadLayout"/>.</summary>
        public static int[] CityRoadCornerLayout
        {
            get { return NeighbourhoodRoadLayout.Corners; }
        }

        /// <summary>
        /// The game folders to look in, in order.
        /// </summary>
        /// <remarks>
        /// <c>FSOEnvironment.UserDir</c> first, because that is the folder the game resolved its
        /// content into and it is what the rest of the engine's relative loads resolve against;
        /// then the assembly's own folder, which is where the game lives when the working directory
        /// has been changed by something else (a debugger, a file dialog, a launcher).
        /// </remarks>
        public static IReadOnlyList<string> DefaultRootCandidates()
        {
            var roots = new List<string>();
            if (!string.IsNullOrEmpty(FSOEnvironment.UserDir)) roots.Add(FSOEnvironment.UserDir);
            var baseDirectory = AppContext.BaseDirectory;
            if (!string.IsNullOrEmpty(baseDirectory)) roots.Add(baseDirectory);
            var current = Environment.CurrentDirectory;
            if (!string.IsNullOrEmpty(current)) roots.Add(current);
            return roots;
        }

        /// <summary>
        /// The first candidate that actually holds the terrain folder, or <c>null</c>.
        /// </summary>
        /// <remarks>
        /// The existence test is a parameter so the rule can be asserted without touching a disk -
        /// which matters because "which folder do we load out of" is exactly the question that
        /// goes wrong silently on somebody else's machine (a portable install, a symlinked
        /// content folder) and a wrong answer here means an empty neighbourhood.
        /// </remarks>
        /// <param name="candidates">Game roots to try, in order.</param>
        /// <param name="fileExists">The existence test.</param>
        public static string ResolveRoot(IReadOnlyList<string> candidates, Func<string, bool> fileExists)
        {
            if (candidates == null || fileExists == null) return null;
            for (int i = 0; i < candidates.Count; i++)
            {
                var root = candidates[i];
                if (string.IsNullOrEmpty(root)) continue;
                try
                {
                    var marker = Path.Combine(root, TerrainFolder, RootMarkerFile);
                    if (fileExists(marker)) return root;
                }
                catch (Exception)
                {
                    //a malformed path is not a reason to stop looking
                }
            }
            return null;
        }

        public void Dispose()
        {
            foreach (var texture in _owned) texture?.Dispose();
            _owned.Clear();
        }
    }
